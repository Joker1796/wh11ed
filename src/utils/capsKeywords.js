import { foldName } from '../core/shared/foldName.js'

// The ALL-CAPS keywords our rule text writes, for the renderer to bold (useRenderInline's
// AUTO_BOLD_RE). The data writes a keyword in capitals and leaves the bold to the renderer, which
// knew only the core and Faction keywords — so "ORKS AIRCRAFT/DEFFKOPTAS" came out half bold, and
// ~1460 unit keywords (MOUNTED, DAMNED, JUMP PACK…) were bold where somebody had added `**` and
// plain where nobody had (a player's screenshot, 2026-10-20). The GW app marks the whole of it.
//
// A run of capitals is split into the longest phrases the keyword vocabulary knows (every keyword
// a unit carries, its datasheet name included — gen-datasheet-index.mjs); a word that is no
// keyword ("WHEN", "AND") is left alone and splits the run. A plural is the singular's keyword and
// the other way round (TERMINATORS a keyword's plural; PINK HORROR one model of the sheet Pink Horrors). Only the phrases the data actually writes
// are kept, so the list the shell carries is what the text needs and no more.
//
// Shared by the generator (which writes src/data/capsKeywords.js) and capsKeywords.test.js (which
// re-reads the data and fails when the written list is out of date).

// A hyphen may be the non-breaking one (U+2011, "SHIELD‑CAPTAIN"): not read as part of the word, it
// left "SHIELD‑" plain and "CAPTAIN" bold.
const TOKEN = /(?:[A-Z][A-Z’'\u2011-]*[A-Z]|[A-Z])/
// A run: capital words joined by single spaces. A slash, a comma, a lowercase word end it.
const RUN = new RegExp(`(?<![\\p{L}\\p{N}’'\u2011-])${TOKEN.source}(?: ${TOKEN.source})*(?![\\p{L}\\p{N}’'\u2011-])`, 'gu')
const MAX_WORDS = 6

/**
 * The keyword phrases, as spelled, that the ALL-CAPS runs of `text` are made of.
 * @param {string} text @param {Set<string>} vocabulary folded keywords @param {Set<string>} into
 */
export function capsKeywordsIn(text, vocabulary, into = new Set()) {
  for (const m of String(text || '').matchAll(RUN)) {
    const words = m[0].split(' ')
    for (let i = 0; i < words.length;) {
      let took = 0
      for (let n = Math.min(MAX_WORDS, words.length - i); n > 0 && !took; n--) {
        const phrase = words.slice(i, i + n).join(' ')
        if (phrase.length < 3) continue
        const k = foldName(phrase)
        if (vocabulary.has(k) || (k.endsWith('s') && vocabulary.has(k.slice(0, -1))) || vocabulary.has(`${k}s`)) {
          into.add(phrase)
          took = n
        }
      }
      i += took || 1
    }
  }
  return into
}

/**
 * A source the scan reads: hand-written data, not a generated file (those say "Generated by" on
 * line 1). The roster modifiers' "Generated skeletons" are read: their notes are written by hand
 * and shown ("a friendly FRENZIED REAVERS INFANTRY unit" was half bold).
 */
export const isScannedSource = (text) => !String(text).startsWith('// Generated by')

/**
 * The names of a sheet's models, folded — "Blue Horror, Brimstone Horror" is two. Rules write them
 * in capitals like keywords ("add one BRIMSTONE HORROR model"), and the scan reads them as such.
 * @param {{ profiles?: { name?: string }[] }} sheet
 */
export const modelNamesOf = (sheet) =>
  (sheet?.profiles || []).flatMap((p) => String(p.name || '').split(/,\s*/)).filter(Boolean).map(foldName)

/**
 * What a rule writes in capitals for a sheet besides its keywords: its models' names, and the name
 * the sheets "Tyranid Warriors with Melee/Ranged Bio-weapons" share ("TYRANID WARRIORS with Ranged
 * Bio-weapons" came out half bold). Folded.
 * @param {{ name?: string, profiles?: { name?: string }[] }} sheet
 */
export function capsNamesOf(sheet) {
  const base = /^(.+?) with /i.exec(String(sheet?.name || ''))?.[1]
  return base ? [...modelNamesOf(sheet), foldName(base)] : modelNamesOf(sheet)
}
