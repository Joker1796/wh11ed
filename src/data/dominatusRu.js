// An Objective Action box as dominatus.js's action() writes one, labels as missionsRu.js has them.
function action(name, { starts = 'Ваша фаза стрельбы (Shooting phase).', units, limit, completes, effect }) {
  return {
    action: `${name} — действие (Objective Action)`,
    rows: [
      { label: 'Начинается', text: starts },
      { label: 'Юниты', text: units },
      { label: 'Лимит использования', text: limit },
      { label: 'Завершается', text: completes },
      { label: 'Эффект', text: effect },
    ],
  }
}

