// The weapons an enhancement GIVES its bearer ("This model has the following weapon:"), as rows the
// roster's unit card can add to its weapon table — src/data/enhancementWeapons.js.
//
// appdata keeps the profile in `enhancement_wargear_item_profile` and nowhere in the enhancement's
// text, which stops at the colon; the faction page prints it as prose (data/factions/extras). On
// the card a player had to scroll to the enhancement to remember the bearer had a sword at all
// (a player's report, 2026-10-08), so the row now stands among the bearer's own weapons.
//
// Keyed by the enhancement's normalised English name (sync-common `norm`: typographic quotes,
// a trailing "(Upgrade)"), the form the roster's `entry.enh` normalises to as well.
//
// Usage: node scripts/gen-enhancement-weapons.mjs   (also part of `npm run roster:data`).

import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { ROOT, norm, table, nameOfEn, groupBy } from './lib/sync-common.mjs'
import { baseTag } from '../src/core/rules/weaponTag.js'

const enhancements = new Map(table('enhancement.json').map((e) => [e.id, e]))
const profiles = new Map(table('wargear_item_profile.json').map((p) => [p.id, p]))
const abilityRows = new Map(table('wargear_ability.json').map((a) => [a.id, a]))
const abilities = new Map([...abilityRows].map(([id, a]) => [id, nameOfEn(a)]))
// A tag that is no Core Rules ability ([BLINDING LIGHT] on the Auriferous Orb) carries its text
// here, the one place it exists outside appdata — so a tap on it opens something
// (scripts/lib/own-abilities.mjs; the Russian is src/data/enhancementWeaponsRu.js).
const coreNames = new Set((await import(pathToFileURL(path.join(ROOT, 'src/data/reference.js')).href)).coreAbilities.en.map((a) => a.name.replace(/^\[|\]$/g, '').toUpperCase()))
const own = {}
const abilitiesOf = groupBy(table('wargear_item_profile_wargear_ability.json'), 'wargearItemProfileId')

const out = {}
for (const row of table('enhancement_wargear_item_profile.json')) {
  const enh = enhancements.get(row.enhancementId)
  const p = profiles.get(row.wargearItemProfileId)
  if (!enh || !p) continue
  const melee = p.type === 'melee'
  const tags = [...(abilitiesOf.get(p.id) || [])]
    .sort((a, b) => (a.displayOrder ?? 0) - (b.displayOrder ?? 0))
    .map((r) => abilities.get(r.wargearAbilityId))
    .filter(Boolean)
  for (const r of abilitiesOf.get(p.id) || []) {
    const a = abilityRows.get(r.wargearAbilityId)
    const name = a && nameOfEn(a)
    const text = a?.localisations?.en?.rules
    if (name && text && !coreNames.has(baseTag(name))) {
      own[name.toUpperCase()] = text.replace(/<\/?b>/g, '**').replace(/<\/?i>/g, '').trim()
    }
  }
  const weapon = {
    name: nameOfEn(p),
    tags,
    ...(melee ? {} : { range: p.range }),
    a: p.attacks,
    [melee ? 'ws' : 'bs']: melee ? p.weaponSkill : p.ballisticSkill,
    s: p.strength,
    ap: p.armourPenetration,
    d: p.damage,
  }
  const key = norm(nameOfEn(enh))
  ;(out[key] ||= { melee: [], ranged: [] })[melee ? 'melee' : 'ranged'].push(weapon)
}

const file = path.join(ROOT, 'src/data/enhancementWeapons.js')
const body = `// Generated by scripts/gen-enhancement-weapons.mjs — do not edit.\n// The weapons an enhancement gives its bearer, by normalised enhancement name.\nexport default ${JSON.stringify(out, null, 2)}\n\n// What a tag on those weapons means when it is no Core Rules ability (EN; RU: enhancementWeaponsRu.js).\nexport const abilities = ${JSON.stringify(Object.fromEntries(Object.entries(own).sort()), null, 2)}\n`
fs.writeFileSync(file, body)
console.log(`enhancement weapons: ${Object.keys(out).length} enhancements → ${path.relative(ROOT, file)}`)
