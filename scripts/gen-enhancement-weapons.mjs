// What a tag on an enhancement's weapon means when it is no Core Rules ability ([BLINDING LIGHT] on
// the Auriferous Orb) — src/data/enhancementWeapons.js `abilities`, read by scripts/lib/own-abilities.mjs
// so a tap on the tag opens something (the Russian is src/data/enhancementWeaponsRu.js). The weapons
// themselves ride on their enhancements in the roster data (gen-roster-data, `weapons`); both are
// read from appdata by scripts/lib/enhancement-weapons.mjs.
//
// Usage: node scripts/gen-enhancement-weapons.mjs   (also part of `npm run roster:data`).
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from './lib/sync-common.mjs'
import { readEnhancementWeapons } from './lib/enhancement-weapons.mjs'

const { abilities } = await readEnhancementWeapons()
const file = path.join(ROOT, 'src/data/enhancementWeapons.js')
const body = `// Generated by scripts/gen-enhancement-weapons.mjs — do not edit.\n// What a tag on an enhancement's weapon means when it is no Core Rules ability (EN; RU: enhancementWeaponsRu.js).\nexport const abilities = ${JSON.stringify(abilities, null, 2)}\n`
fs.writeFileSync(file, body)
console.log(`enhancement weapon abilities: ${Object.keys(abilities).length} → ${path.relative(ROOT, file)}`)
