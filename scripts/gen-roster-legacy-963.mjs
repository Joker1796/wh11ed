#!/usr/bin/env node
// One-off, kept to show where src/data/rosterLegacy963.js came from: data 963 (Codex: Space Marines,
// commit c4b6d8ae, shipped in 2.7.8 on 2026-09-30) moved the wargear and size indices of 105 units
// in the Space Marines family, and no migration was written. This matches the generation before it
// to the one it produced, by meaning (scripts/lib/roster-meanings.mjs), from git history.
//   node scripts/gen-roster-legacy-963.mjs           write the file
//   node scripts/gen-roster-legacy-963.mjs --report  print what moves and what is gone
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { meaningsOf, matchMeanings } from './lib/roster-meanings.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const COMMIT = 'c4b6d8ae'
const git = (...a) => execFileSync('git', ['-C', ROOT, ...a], { encoding: 'utf8', maxBuffer: 1 << 28 })

async function meaningsAt(ref, dir, aliases) {
  const files = git('ls-tree', '--name-only', `${ref}:src/data/roster`).split('\n').filter((f) => f.endsWith('.js') && !f.includes('.test.'))
  const load = async (f) => {
    const file = path.join(dir, f)
    fs.writeFileSync(file, git('show', `${ref}:src/data/roster/${f}`))
    return (await import(pathToFileURL(file).href)).default
  }
  const names = (await load('items.js')).items
  const out = {}, shared = {}
  for (const f of files) {
    if (['items.js', 'index.js', 'core.js'].includes(f)) continue
    const data = await load(f)
    Object.assign(out, meaningsOf(data.slug, data, names, aliases))
    if (data.sharedUnitIds) shared[data.slug] = data.sharedUnitIds
  }
  return { out, shared }
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'roster-963-'))
fs.mkdirSync(path.join(tmp, 'a')); fs.mkdirSync(path.join(tmp, 'b'))
const aliases = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/lib/roster-item-aliases-963.json'), 'utf8'))
const before = await meaningsAt(`${COMMIT}^`, path.join(tmp, 'a'), aliases)
const after = await meaningsAt(COMMIT, path.join(tmp, 'b'), {})
fs.rmSync(tmp, { recursive: true, force: true })
const SM = new Set(['space-marines', 'black-templars', 'blood-angels', 'dark-angels', 'deathwatch', 'space-wolves'])
const smOnly = Object.fromEntries(Object.entries(before.out).filter(([k]) => SM.has(k.split(':')[0])))
const { moves, gone } = matchMeanings(smOnly, after.out)
for (const [chapter, ids] of Object.entries(before.shared)) {
  for (const id of ids) if (moves[`space-marines:${id}`] && !moves[`${chapter}:${id}`]) moves[`${chapter}:${id}`] = moves[`space-marines:${id}`]
}
if (process.argv.includes('--report')) {
  console.log(`${Object.keys(moves).length} unit keys move; ${gone.length} indices gone`)
  for (const g of gone) console.log('  gone', g)
} else {
  const sorted = Object.fromEntries(Object.entries(moves).sort(([a], [b]) => a.localeCompare(b)))
  fs.writeFileSync(path.join(ROOT, 'src/data/rosterLegacy963.js'), `// Generated by gen-roster-legacy-963.mjs — do not edit.
// Data 963 (Codex: Space Marines, shipped in 2.7.8 on 2026-09-30) moved these indices and no
// migration followed; useRosters.js applies them to a list untouched since then (see LEGACY_963_AT).
export default ${JSON.stringify(sorted)}
`)
  console.log(`✓ rosterLegacy963.js: ${Object.keys(moves).length} unit keys, ${gone.length} indices gone`)
}
