const CHAPTERS = new Set(['black-templars', 'blood-angels', 'dark-angels', 'deathwatch', 'space-wolves'])
const isChapter = (slug) => CHAPTERS.has(slug)

function keyword(kws, name) {
  const n = name.toLowerCase()
  return (kws || []).some((k) => k.toLowerCase() === n)
}

// A handful of wargear groups depend on ANOTHER group on the same datasheet+miniature — e.g.
// Necron Overlord's Resurrection Orb is only on offer after giving up the default tachyon arrow,
// and several Chaos Daemon units offer a daemonic-icon/instrument-of-Chaos pair that are
// mutually exclusive. wh40k-appdata has no structural field linking two `wargear_option_group`
// rows for this — the relationship lives only in prose ("if [not] equipped with X", "…can be
// replaced with…") — so this parses it conservatively: an unresolved phrase or an ambiguous
// sibling match just leaves the group unconstrained (today's already-correct behaviour for the
// ~1100 other datasheets), never a wrong link. Mutates `drafts` in place, adding `rep`
// (item UUIDs this group replaces, for defaultLoadoutLines' default-vs-swap accounting) and
// `cond` (`{ sibling: <draft>, active }` — this group is only live once the sibling's own
// "has a deviation recorded" state matches `active`; see rosterEngine.js wargearGroupLive) to
// whichever drafts resolve.
// The starting gear of a datasheet that has no `base_miniature_loadout` row: appdata records it as
// a wargear_option_group whose instruction is literally "Default Wargear", one per miniature. 144
// datasheets are in that shape (136 with such a group), and reading only the loadout table left
// them with NO default loadout at all — no "starts equipped with" line in the editor and nothing
// for Tier A's weapon trim to subtract from. Returns the same `[[miniatureIndex, [[uuid, count]]]]`
// shape as the loadout table so the caller can't tell the two sources apart; count is 1, which is
// all a wargear_option can express.
// Which groups are that starting gear. Nearly all of them SAY so — the instruction is literally
// "Default Wargear", 899 groups — but four state it in prose instead ("One other Navis Armsman is
// equipped with:", "One Voidsman is equipped with:", the Tesseract Vault's "Powers of the C'tan"),
// and appdata marks their options the same way either title does: every one of them a default.
// Read as choices, those four became a group of alternatives capped at one, and a legal list came
// out illegal — the Breachers' second armsman carries a heavy shotgun AND an Endurant Shield AND a
// close combat weapon, which is three picks in a group that allows one. So the test is the SHAPE:
// a group every option of which is a default is not a choice, whatever it calls itself.
function isDefaultGroup(g) {
  const text = (enOf(g).instructionText || '').trim().toLowerCase()
  if (text === 'default wargear' || text === 'defualt wargear') return true
  const opts = woByGroup.get(g.id) || []
  return opts.length > 1 && opts.every((o) => o.defaultValue > 0)
}

function staticLoadout(datasheetId, miniIdx) {
  const idx = miniIdx || new Map((minisByDs.get(datasheetId) || []).slice()
    .sort((a, b) => a.displayOrder - b.displayOrder).map((m, i) => [m.id, i]))
  const out = []
  for (const g of wogByDs.get(datasheetId) || []) {
    if (!isDefaultGroup(g)) continue
    const items = (woByGroup.get(g.id) || [])
      .sort((a, b) => a.displayOrder - b.displayOrder)
      .map((o) => [o.wargearItemId, o.defaultValue > 0 ? o.defaultValue : 1])
      .filter(([uuid]) => uuid)
    if (items.length) out.push([idx.get(g.miniatureId) ?? 0, items])
  }
  return out
}

function linkWargearConditions(datasheetId, drafts) {
  if (!drafts.length) return
  const repStats = report.rep

  // Item names known to THIS datasheet only — defaults plus every draft's own options — so a
  // same-named item belonging to some unrelated unit elsewhere can never match. Keyed through
  // norm(), not toLowerCase(): appdata types these names by hand, so the same weapon appears with
  // a curly apostrophe here and a U+2010 hyphen there ("multi‐laser", "hot‐shot lascarbine") — the
  // same class of silent no-op that apostrophes caused in enhancements and ë in Votann detachments.
  const nameToUuid = new Map()
  // The same names again with every apostrophe, hyphen and space removed. appdata spells one
  // item two ways across its own tables — the prose says "kustom-mega blasta" where the item
  // table says "Kustom mega-blasta" — and this index is what lets the two meet. A key that two
  // different items would share is poisoned to null rather than resolving to whichever came last.
  const canonToUuid = new Map()
  const canon = (s) => s.replace(/[^a-z0-9]/g, '')
  const remember = (uuid) => {
    const n = norm(wgItemName.get(uuid) || '')
    if (!n) return
    nameToUuid.set(n, uuid)
    const c = canon(n)
    canonToUuid.set(c, canonToUuid.has(c) && canonToUuid.get(c) !== uuid ? null : uuid)
  }
  // What each PROFILE starts with, by miniature id. Two of the readings below need it: an
  // instruction naming a weapon category ("its ranged weapon") and one naming two alternatives
  // ("its power sword or shuriken rifle") are both answered by looking at what the profile
  // actually holds — the datasheet knows, even though the sentence doesn't say.
  //
  // 144 datasheets have no base_miniature_loadout row at all — for 136 of them the starting gear
  // is a "Default Wargear" option group instead (see staticLoadout), and those groups are dropped
  // before the drafts are built, so their items have to be collected here too or a swap on one of
  // them ("this model's heavy bolt pistol can be replaced with…") resolves nothing. Same test as
  // staticLoadout uses — by SHAPE, not by title: the Breachers' las-volley is named only by a
  // group that says "One Navis Armsman is equipped with:", and reading that group as a choice is
  // what left "1 Navis Armsman's Navis las-volley can be replaced with…" replacing nothing.
  const defaultsByMini = new Map()
  const addDefault = (miniatureId, uuid) => {
    if (!uuid) return
    if (!defaultsByMini.has(miniatureId)) defaultsByMini.set(miniatureId, new Set())
    defaultsByMini.get(miniatureId).add(uuid)
    remember(uuid)
  }
  for (const b of bmlByDs.get(datasheetId) || []) {
    for (const o of b.opts) addDefault(b.miniatureId, woById.get(o.wargearOptionId)?.wargearItemId)
  }
  for (const g of wogByDs.get(datasheetId) || []) {
    if (!isDefaultGroup(g)) continue
    for (const o of woByGroup.get(g.id) || []) addDefault(g.miniatureId, o.wargearItemId)
  }
  for (const d of drafts) for (const o of d.opts) remember(o.uuid)

  // One name out of the prose. The prose counts and pluralises what the item table does not
  // ("this model's 2 twin heavy flamers" vs the item "Twin heavy flamer"), so both are stripped
  // before the lookup — a leading quantity, then a trailing plural if the exact name missed.
  const resolveItem = (raw, miniId) => {
    const n = norm(raw).replace(/^\d+\s+/, '')
    // "-s" before "-es": stripping greedily turns "dark lances" into "dark lanc", not "dark lance".
    const exact = nameToUuid.get(n) || nameToUuid.get(n.replace(/s$/, '')) || nameToUuid.get(n.replace(/es$/, ''))
    if (exact) return exact
    // A weapon CATEGORY rather than a name — answerable only when the profile holds exactly one
    // weapon of that type, which is the case for all three instructions written this way.
    const cat = n.match(/^(ranged|melee) weapons?$/)
    if (cat) {
      const hits = [...(defaultsByMini.get(miniId) || [])].filter((u) => wgItemTypes.get(u)?.has(cat[1]))
      return hits.length === 1 ? hits[0] : null
    }
    if (canonToUuid.get(canon(n))) return canonToUuid.get(canon(n))
    // Below here the prose and the item table disagree about the name itself, so a match is a
    // judgement, not a lookup: each of these accepts only when exactly ONE item can be meant.
    // A one-character difference at equal length — "absolver bolt pistol" for "Absolvor bolt
    // pistol". Equal length is what keeps it from reaching a genuinely different weapon.
    const typo = [...nameToUuid].filter(([k]) => k.length === n.length && k !== n
      && [...k].filter((ch, i) => ch !== n[i]).length === 1)
    if (typo.length === 1) return typo[0][1]
    // A name the prose has prefixed with one adjective — "plague combi-bolter" for the item
    // "Combi-bolter". Exactly one leading word, because anything longer is a phrase naming more
    // than one item ("condemnor bolt pistol and null mace", "bolter or ion blaster") and matching
    // its tail would silently answer with the last weapon named instead of all of them. That one
    // word also has to be an adjective and not an article or possessive: "its bolt shotgun" is a
    // fresh clause the split missed, and reading it as a name would answer half a sentence.
    const suffix = [...nameToUuid].filter(([k]) => n.endsWith(` ${k}`)
      && /^(?!(?:a|an|the|its|their|his|her|one|each)$)[a-z0-9'-]+$/.test(n.slice(0, -k.length - 1)))
    if (suffix.length === 1) return suffix[0][1]
    return null
  }

  // "X or Y" names ONE of two items as the thing given up. The sentence doesn't say which — but
  // the profile usually does, because it holds only one of them; that's why the option exists in
  // the first place. Two of these are genuinely ambiguous (the profile holds both) and stay
  // unresolved. Note the answer is only right for the FIRST such swap: a model that already
  // traded X for Y through an earlier group has moved on, and static data can't follow it.
  const resolveAlternatives = (chunk, miniId) => {
    const alts = chunk.split(/\s+or\s+/i).map((s) => s.trim()).filter(Boolean)
    if (alts.length < 2) return null
    const uuids = alts.map((a) => resolveItem(a, miniId))
    if (!uuids.every(Boolean)) return null
    const held = [...new Set(uuids)].filter((u) => defaultsByMini.get(miniId)?.has(u))
    return held.length === 1 ? held[0] : null
  }

  const resolveChunk = (chunk, miniId) => resolveItem(chunk, miniId) || resolveAlternatives(chunk, miniId)

  // A phrase into the set of items it names. Commas always separate; "and" may or may not, since
  // an item can BE called "Cult claws and knife" — so every way of splitting on "and" is tried,
  // fewest pieces first, and the first reading where every piece is a real item wins. Fewest-first
  // is what keeps a compound name whole ("autopistol and cult claws and knife" is two items, not
  // three, and only one of the four readings resolves).
  const resolveConjunction = (part, miniId) => {
    const segs = part.split(/\s+and\s+/i)
    if (segs.length === 1) { const u = resolveChunk(part, miniId); return u ? [u] : null }
    if (segs.length > 5) return null
    const masks = [...Array(1 << (segs.length - 1)).keys()]
      .sort((a, b) => (a.toString(2).split('1').length) - (b.toString(2).split('1').length))
    for (const mask of masks) {
      const chunks = []
      let cur = segs[0]
      for (let i = 0; i < segs.length - 1; i++) {
        if (mask & (1 << i)) { chunks.push(cur); cur = segs[i + 1] } else cur += ` and ${segs[i + 1]}`
      }
      chunks.push(cur)
      const uuids = chunks.map((c) => resolveChunk(c, miniId))
      if (uuids.every(Boolean)) return uuids
    }
    return null
  }

  const resolvePhrase = (phrase, miniId) => {
    const out = []
    for (const part of phrase.split(/\s*,\s*/).map((s) => s.trim()).filter(Boolean)) {
      const got = resolveConjunction(part, miniId)
      if (!got) return null
      out.push(...got)
    }
    return out.length ? out : null
  }

  // What each draft REPLACES, from its own "…'s X[, Y and Z] can be replaced with…" prose.
  // Three shapes of possessive, because appdata writes all three: "model's", "models'" (plural,
  // no second s) and the bare pronoun.
  const REP_RE = /(?:'s|’s|s’|\bhis\b|\bher\b|\btheir\b|\bits\b)\s+((?:\d+\s+)?[a-z][a-z0-9' ’‐‑–,-]*?)\s*(?:can\s+(?:each\s+)?be\s+|be\s+|is\s+|are\s+)?replaced with/i
  // …and once, corpus-wide, with no possessive at all: "Each model can have each shuriken cannon
  // it is equipped with replaced with one of the following".
  const HAVE_RE = /\bhave\s+(?:each|its|their|the|1|one)\s+((?:\d+\s+)?[a-z][a-z0-9' ’‐‑–,-]*?)\s+(?:it is|they are|this model is|that model is)\s+equipped with\s+replaced with/i
  for (const d of drafts) {
    // A sentence can carry more than one possessive before the swap — "The Celestian Insidiant's
    // Superior's condemnor bolt pistol" — and the first one starts a phrase that names no item.
    // So walk them from the left and keep the first candidate that resolves COMPLETELY; a partial
    // resolve is rejected rather than trimmed, since half a set is a wrong subtraction.
    let from = 0, m = null, last = null
    while ((m = d.text.slice(from).match(REP_RE))) {
      last = m
      const uuids = resolvePhrase(m[1], d.miniId)
      if (uuids) { d.rep = uuids; repStats.resolved++; break }
      from += d.text.slice(from).indexOf(m[0]) + 2
    }
    if (!d.rep && (m = d.text.match(HAVE_RE))) {
      last = m
      const uuids = resolvePhrase(m[1], d.miniId)
      if (uuids) { d.rep = uuids; repStats.resolved++ }
    }
    if (d.rep) continue
    if (last) repStats.unresolved.push(`${enOf(dsById.get(datasheetId)).name}: ${last[1].trim()}`)
    else if (/replaced with/i.test(d.text)) repStats.noMatch.push(`${enOf(dsById.get(datasheetId)).name}: ${d.text.split('\n')[0].slice(0, 80)}`)
  }

  // What each draft is CONDITIONED on, from "[if …] not equipped with X" / "equipped with X".
  const NOT_EQ_RE = /\bnot equipped with (?:a |an |1 |one )?([a-z][a-z' ’-]*?)(?:[,.]|\s+(?:it|its|can)\b)/i
  const EQ_RE = /\bequipped with (?:a |an |1 |one )?([a-z][a-z' ’-]*?)(?:[,.]|\s+(?:it|its|can)\b)/i
  for (const d of drafts) {
    let negated = true
    let m = d.text.match(NOT_EQ_RE)
    if (!m) { negated = false; m = d.text.match(EQ_RE) }
    if (!m) continue
    const uuid = nameToUuid.get(m[1].trim().toLowerCase())
    if (!uuid) continue

    // Case (a): the item is exactly another group's sole toggle option — mutual exclusion.
    const toggleSibling = drafts.find((s) => s !== d && s.m === d.m && s.opts.length === 1 && s.opts[0].uuid === uuid)
    if (toggleSibling) { d.cond = { sibling: toggleSibling, active: !negated }; continue }

    // Case (b): a sibling group's own `rep` shows it replaces this exact item — this group is
    // only live once that sibling has actually been picked away from its default.
    const repSibling = drafts.find((s) => s !== d && s.m === d.m && s.rep?.includes(uuid))
    if (repSibling) d.cond = { sibling: repSibling, active: negated }
  }
}

// ---- Wargear bundles -------------------------------------------------------------------
// A `wargear_option` row carries exactly ONE item, but an option is often a PAIR — "1 model's
// twin torturer's tools can be replaced with 1 hexrifle and 1 torturer's tool". The pairing
// exists in appdata only in the group's own instruction prose, so it is parsed from there and
// then VERIFIED against structure: `loadout_choice` enumerates the complete legal loadouts per
// miniature (1145 of 1146 datasheets have them), so every set the prose yields must fit inside
// one of them. Prose alone would be a guess; prose checked against the enumeration is not.
//
// Fail-open throughout — a group whose statements don't all resolve, or whose sets the
// enumeration doesn't back, is emitted exactly as appdata lists it (one item per option), which
// is today's behaviour. Never a guessed pair.
const lcItemsByChoice = new Map()
for (const r of table('loadout_choice_wargear_item')) {
  if (!lcItemsByChoice.has(r.loadoutChoiceId)) lcItemsByChoice.set(r.loadoutChoiceId, [])
  lcItemsByChoice.get(r.loadoutChoiceId).push(r.wargearItemId)
}
const lcSetById = new Map(table('loadout_choice_set').map((s) => [s.id, s]))
const legalLoadouts = new Map() // `${datasheetId}|${miniatureId}` -> [Set(itemUuid), …]
for (const c of table('loadout_choice')) {
  const set = lcSetById.get(c.loadoutChoiceSetId)
  if (!set) continue
  const key = `${set.datasheetId}|${set.miniatureId || ''}`
  if (!legalLoadouts.has(key)) legalLoadouts.set(key, [])
  legalLoadouts.get(key).push(new Set(lcItemsByChoice.get(c.id) || []))
}

// Four markers are in use (◦ 348 lines, ■/▫ 5 each, • 2) — and one list has no marker at all,
// just a head line ending in ':' with an option per line (Grey Knights' Brotherhood Terminator
// Squad). A trailing '*' line is a footnote about the options, not one of them.
const BULLET_RE = /^[◦•■▫]\s*/
const FOOTNOTE_RE = /^\*/
// The value half of a statement. Everything before it names what is GIVEN UP, which repeats item
// names the group also offers ("twin torturer's tools" contains "torturer's tool") — reading the
// whole sentence would pick those up as part of the new loadout.
const VALUE_SPLIT = /\b(?:replaced with|replaced by|equipped with)\b/i
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// The group's own items named in one statement, in order, with the count written in front of
// them ("2 Mortifier flamers"). Longest name first so a name containing another ("master-crafted
// power weapon" vs "power weapon") wins the match.
function itemsNamedIn(clause, vocab) {
  const sorted = [...vocab].sort((a, b) => b.name.length - a.name.length)
  const re = new RegExp(`(?:(\\d+)\\s+)?\\b(${sorted.map((v) => reEsc(v.name)).join('|')})(?:e?s)?\\b`, 'gi')
  const out = []
  for (const m of clause.matchAll(re)) {
    const hit = sorted.find((v) => v.name === m[2].toLowerCase())
    if (!hit || out.some(([uuid]) => uuid === hit.uuid)) continue
    out.push([hit.uuid, Number(m[1]) || 1])
  }
  return out
}

function linkWargearBundles(datasheetId, unitName, drafts, stats) {
  for (const d of drafts) {
    const vocab = d.opts.map((o) => ({ uuid: o.uuid, name: (wgItemName.get(o.uuid) || '').toLowerCase() }))
    if (vocab.some((v) => !v.name)) continue

    const lines = d.text.split('\n').map((l) => l.trim()).filter(Boolean)
    const bullets = lines.filter((l) => BULLET_RE.test(l))
    // With a list the statements ARE its entries: the sentence above them only introduces the
    // list ("…replaced with one of the following:") and names the items being given up.
    let entries = [d.text]
    if (bullets.length) entries = bullets
    else if (lines.length > 1 && /:$/.test(lines[0])) entries = lines.slice(1).filter((l) => !FOOTNOTE_RE.test(l))
    const stmts = entries.map((l) => l.replace(BULLET_RE, '').split(VALUE_SPLIT).pop())

    const sets = stmts.map((c) => itemsNamedIn(c, vocab))
    if (sets.some((set) => !set.length)) continue        // a statement nothing resolved in

    // A number in front of an item is not always a quantity: "up to 2 seeker missiles" / "up to 4
    // big shootas" state an ALLOWANCE — how many separate picks the model may take, each of one
    // item — and reading them as a set would hand the model six seeker missiles for one pick.
    // 7 groups are in that shape, and they are exactly the 7 whose prose number contradicts every
    // legal loadout in appdata. Membership still stands; only the count is dropped.
    if (/\bup to \d+\b/i.test(d.text.split('\n')[0])) for (const set of sets) for (const pair of set) pair[1] = 1

    if (!sets.some((set) => set.length > 1)) {
      // No bundle, but the prose may still say how many of the one item an option grants ("this
      // model's 2 starcannons can be replaced with 2 bright lances"). 76 groups across 22 factions
      // are in this shape and appdata has no structural count for them — `loadout_choice` records
      // the model's TOTAL of that weapon, not this option's contribution (Baneblade's twin heavy
      // bolter reads 1/3/5), so the prose is the only source. Written onto the existing options
      // in place: unlike a bundle this changes no option's INDEX, so stored picks stay valid and
      // SCHEMA_VERSION doesn't move.
      const qty = new Map(sets.flat().map(([uuid, n]) => [uuid, n]))
      let counted = false
      for (const o of d.opts) {
        const n = qty.get(o.uuid) || 1
        if (n > 1) { o.items = [[o.uuid, n]]; counted = true }
      }
      if (counted) stats.quantified++
      continue
    }
    // Every option appdata lists must be accounted for by the prose, or the prose is describing
    // something other than this group's option list and can't be trusted to replace it.
    const claimed = new Set(sets.flat().map(([uuid]) => uuid))
    if (claimed.size !== new Set(vocab.map((v) => v.uuid)).size) { stats.unclaimed.push(`${unitName}: ${stmts[0].trim()}`); continue }

    const legal = legalLoadouts.get(`${datasheetId}|${d.miniId || ''}`) || []
    const backed = sets.every((set) => set.length < 2
      || legal.some((choice) => set.every(([uuid]) => choice.has(uuid))))
    if (!backed) { stats.unbacked.push(`${unitName}: ${stmts[0].trim()}`); continue }

    const byUuid = new Map(d.opts.map((o) => [o.uuid, o]))
    d.opts = sets.map((set) => {
      const members = set.map(([uuid]) => byUuid.get(uuid)).filter(Boolean)
      return {
        uuid: set[0][0],
        pts: members.reduce((n, o) => n + (o.pts || 0), 0),
        def: members.length && members.every((o) => o.def) ? 1 : 0,
        items: set,
      }
    })
    stats.rewritten++
  }
}

// ---- One bullet, recorded once per miniature -------------------------------------------
// A datasheet's wargear bullet that talks about the UNIT ("Any number of models can each have
// their hallowed mace replaced…", "For every 5 models in this unit, 1 model's…") is stored by
// appdata once per MINIATURE profile — as a checkbox on the single leader model and a stepper on
// the rank-and-file one — because its option groups hang off miniatures, not off the datasheet.
// Rendered straight, that is the same instruction twice (reported on Drukhari Wracks), and worse
// than cosmetic: each copy carries its own allowance, so the choice can be taken twice.
//
// The two are folded into one unit-wide group. Matching on the exact instruction TEXT plus the
// exact option sets is what makes this safe: a leader with a genuinely separate allowance is
// always worded differently ("The Sister Superior's boltgun…"), so it never collides. 99 pairs
// across 50 units, and in every one of them the two copies agree on what they replace.
function mergeMiniatureDuplicates(drafts, stats) {
  const byKey = new Map()
  for (const d of drafts) {
    // Whitespace-insensitive: the two copies of one bullet are typed twice into appdata and do
    // differ by a stray trailing space (Deathwatch Terminator Squad), which is not a difference
    // in meaning. Line ORDER still counts — a reordered option list is a different statement.
    const k = `${d.text.replace(/\s+/g, ' ').trim()}||${d.opts.map((o) => (o.items ? o.items.map(([u]) => u) : [o.uuid]).slice().sort().join('+')).sort().join('/')}`
    if (!byKey.has(k)) byKey.set(k, [])
    byKey.get(k).push(d)
  }
  const dropped = new Map() // dropped draft -> the one that survives
  for (const list of byKey.values()) {
    if (list.length < 2) continue
    // Two copies on the SAME miniature would be two real allowances, not one bullet recorded
    // twice — leave those alone.
    if (new Set(list.map((d) => d.m)).size !== list.length) continue
    const keep = list.find((d) => d.in === 'stepper') || list[0]
    keep.all = 1 // unit-wide: no miniature owns it, and the count runs over the whole squad
    for (const d of list) if (d !== keep) dropped.set(d, keep)
    stats.merged += list.length - 1
  }
  if (!dropped.size) return drafts
  // A sibling condition points at a draft object; if that object is one of the dropped copies,
  // it has to follow the survivor or the dependent group would never go live.
  for (const d of drafts) if (d.cond && dropped.has(d.cond.sibling)) d.cond.sibling = dropped.get(d.cond.sibling)
  return drafts.filter((d) => !dropped.has(d))
}

// ---- Per-group pick limits -------------------------------------------------------------
// How MANY models in a squad may take an option is not in `wargear_option_group` either — it is
// its own family: `limited_wargear_choice_set` (per datasheet, sometimes per miniature) holds
// the same choices again, and `wargear_limit` gives the cap as a step table keyed by unit size
// ({modelCount: 5, choiceLimit: 1}, {modelCount: 10, choiceLimit: 2} = "for every 5 models,
// 1 model"). Without it the editor guesses from prose — "Up to 4 Dominions can each…" reads as
// no cap at all, "For every 5 models, up to 2 Seraphim" as one — and a wrong cap here is not
// cosmetic: a paid option's points are multiplied by the count, so it misprices the army.
//
// Matched by ITEM SETS, not by name or order: a limited set is attached to a group only when its
// choices are exactly that group's options (and its miniature, when it names one) and no other
// group on the unit is an equally good match. Sets that enumerate combinations ACROSS groups —
// 82 of 345, the Battle Sisters "2 models may take one of these specials/heavies" pools — match
// nothing and are left alone, exactly like every other fail-open path here.
const lwcItems = new Map()
for (const r of table('limited_wargear_choice_wargear_item')) {
  if (!lwcItems.has(r.limitedWargearChoiceId)) lwcItems.set(r.limitedWargearChoiceId, [])
  lwcItems.get(r.limitedWargearChoiceId).push(r)
}
const lwcBySet = new Map()
for (const c of table('limited_wargear_choice')) {
  if (!lwcBySet.has(c.limitedWargearChoiceSetId)) lwcBySet.set(c.limitedWargearChoiceSetId, [])
  lwcBySet.get(c.limitedWargearChoiceSetId).push(c)
}
const wgLimitsBySet = new Map()
for (const l of table('wargear_limit')) {
  if (!wgLimitsBySet.has(l.limitedWargearChoiceSetId)) wgLimitsBySet.set(l.limitedWargearChoiceSetId, [])
  wgLimitsBySet.get(l.limitedWargearChoiceSetId).push(l)
}
const limitedSetsByDs = new Map()
for (const s of table('limited_wargear_choice_set')) {
  if (!limitedSetsByDs.has(s.datasheetId)) limitedSetsByDs.set(s.datasheetId, [])
  limitedSetsByDs.get(s.datasheetId).push(s)
}

// An option / choice as a comparable key: its item uuids, order-independent, counts ignored
// (the two families disagree on quantity often enough that requiring it would lose real matches;
// the count is taken FROM the limited set once matched).
const itemsKey = (uuids) => [...new Set(uuids)].sort().join('|')
const groupKey = (opts) => opts.map((o) => itemsKey((o.items || [[o.uuid]]).map(([u]) => u))).sort().join('#')

// The allowance the instruction states, or null when it doesn't state one plainly. Deliberately
// narrow: anything scaled ("for every 5 models") or conditional ("if this unit contains 10
// models") is left to the step table, which expresses those properly; this only reads the flat
// "up to 2 Dominions…" / "1 model's boltgun…" forms, which is where a wrong match would show up.
const WORD_NUM = { one: 1, two: 2, three: 3, four: 4, five: 5 }
function proseAllowance(text) {
  const t = text.split('\n')[0]
  if (/\bfor every \d+\b|\bif this unit contains\b|\bany number of\b/i.test(t)) return null
  const up = t.match(/\bup to (\d+|one|two|three|four|five)\b/i)
  if (up) return WORD_NUM[up[1].toLowerCase()] || Number(up[1])
  const lead = t.match(/^\s*(\d+|one|two|three|four|five)\b/i)
  if (lead) return WORD_NUM[lead[1].toLowerCase()] || Number(lead[1])
  return null
}

function linkWargearLimits(datasheetId, unitName, miniIdx, drafts, stats) {
  const sets = limitedSetsByDs.get(datasheetId) || []
  if (!sets.length) return
  for (const set of sets) {
    const choices = (lwcBySet.get(set.id) || []).map((c) => lwcItems.get(c.id) || [])
    if (!choices.length) continue
    const wantKey = choices.map((its) => itemsKey(its.map((i) => i.wargearItemId))).sort().join('#')
    const wantMini = set.miniatureId == null ? null : miniIdx.get(set.miniatureId)

    const hits = drafts.filter((d) => groupKey(d.opts) === wantKey && (wantMini == null || d.m === wantMini))
    // Several identical groups (the same choice repeated per miniature) — no way to tell which
    // one the set means, so neither gets a cap it might not have.
    if (hits.length !== 1) { stats[hits.length ? 'ambiguous' : 'unmatched']++; continue }
    const d = hits[0]
    if (d.lim) { stats.ambiguous++; continue }

    // `[modelCount, choiceLimit]`, plus the duplicate cap as a third slot when there is one —
    // it belongs to the threshold, not to the set (Cadian Shock Troops: 2 picks / 1 of a kind at
    // 10 models, 4 picks / 2 of a kind at 20), so hoisting it to the group would misread half
    // the brackets.
    const limits = (wgLimitsBySet.get(set.id) || [])
      .map((l) => (l.duplicateLimit > 0
        ? [l.modelCount || 0, l.choiceLimit, l.duplicateLimit]
        : [l.modelCount || 0, l.choiceLimit]))
      .filter(([, n]) => n > 0)
      .sort((a, b) => a[0] - b[0])
    if (!limits.length) continue
    // Cross-check against the instruction. Two GW sources describing the same allowance can
    // disagree, and a set matches by ITEMS — so a set that really describes a different, wider
    // allowance over the same weapons would attach here and quietly hand out extra models
    // (Blood Angels' Death Company Marines with Jump Packs: prose "1 model's Astartes chainsword
    // can be replaced with one of the following", limits 2/3). Where the prose states a plain
    // allowance, it has to agree, or the group keeps the no-cap behaviour — which for a
    // one-of group IS "one model", the conservative reading.
    const said = proseAllowance(d.text)
    if (said != null && said !== limits[0][1]) { stats.conflict.push(`${unitName}: prose ${said} vs appdata ${limits[0][1]} — ${d.text.split('\n')[0].slice(0, 70)}`); continue }
    d.lim = limits

    // The quantity per option lives here too — "2 inferno pistols", where wargear_option knows
    // only the item. Applied only where the option doesn't already carry its own count.
    const byKey = new Map(choices.map((its) => [itemsKey(its.map((i) => i.wargearItemId)), its]))
    for (const o of d.opts) {
      const its = byKey.get(itemsKey((o.items || [[o.uuid]]).map(([u]) => u)))
      if (!its || its.every((i) => (i.count || 1) === 1)) continue
      o.items = its.map((i) => [i.wargearItemId, i.count || 1])
      stats.counted++
    }
    stats.limited++
  }
}

// ── What a unit costs ─────────────────────────────────────────────────────────────────────────
// The BRACKETS are appdata's (model counts + the per-miniature composition behind them); the
// PRICE of each is the Munitorum Field Manual's, read from the same scraped modules the datasheet
// pages already use (src/data/mfm/*.js — see scrape-mfm.py / sync-mfm-points.mjs).
//
// Not a preference between two equal sources: appdata records SEVERAL price rows per datasheet —
// one per Chapter (Blood Angels pay 80 for an Assault Intercessor Squad where the Codex price is
// 75), and for Imperial Agents one per allied context (Draxus 75 in her own army, 110 as an ally).
// Mapped straight onto `sizes` those became unit-SIZE choices: two identical "5 models" pills at
// different prices, the first one arbitrarily pre-selected, and the roster quoting a different
// number than the unit's own datasheet page. Pricing every bracket from one source collapses them
// back into one pill (the fold below does it, once the only thing that differed is gone) and puts
// the builder back in step with the rest of the app.
//
// A copy-tax tier ("1st-2nd" / "3rd+") is a NOTE on an MFM row, not a bracket of its own: the base
// price is the first tier and the surcharge stays `datasheet_points_step` (appdata's own field),
// which this cross-checks and reports on.
// The MFM prints some of a faction's OWN datasheets in a separate section — Aeldari's Harlequins
// and Ynnari, the Chaos legion sections, Space Marines' named-character chapters — and those are
// units of this army like any other. Two kinds of subfaction are not: a Chapter's "Space Marines"
// section (the shared Codex pool, folded in at load time and priced by `unitPoints`) and Imperial
// Agents' "(allied)" list, which is what those units cost in SOMEBODY ELSE'S army. The faction's
// own list is appended last so it wins wherever a name appears in both.
function ownMfmUnits(mfmFaction) {
  const extra = (mfmFaction?.subfactions || [])
    .filter((s) => norm(s.name) !== 'space marines' && !/allied/i.test(s.name))
    .flatMap((s) => s.units || [])
  return [...extra, ...(mfmFaction?.units || [])]
}

function mfmPrices(mfmUnits) {
  const byName = new Map()
  for (const u of mfmUnits || []) {
    const byModels = new Map()
    for (const o of u.options || []) {
      const n = Number(o.models)
      if (!Number.isFinite(n) || !(o.points > 0)) continue
      if (!byModels.has(n)) byModels.set(n, [])
      byModels.get(n).push(o)
    }
    if (!byModels.size) continue
    const prices = new Map()
    for (const [n, rows] of byModels) {
      const first = rows.find((r) => !r.note) || rows.find((r) => /^1st/i.test(r.note || '')) || rows[0]
      const later = rows.filter((r) => r !== first).map((r) => Number(r.points))
      prices.set(n, { base: Number(first.points), step: later.length ? Math.min(...later) - Number(first.points) : null })
    }
    byName.set(normApost(u.name), prices)
  }
  return byName
}

// One bracket per unit SIZE, priced by the MFM.
//
// appdata lists a datasheet's price rows as several parallel lists — one per Chapter, or per allied
// context — so the same size appears more than once at different prices. Those are not sizes, and
// emitting them as such is what put two identical "5 models" pills, at 80 and 75 points, in the
// editor. Rows are therefore grouped by what actually makes a bracket distinct (model range +
// per-miniature composition — Corsair Voidscarred really does have three different 7-model builds)
// and each group collapses to ONE bracket.
//
// Which of the parallel lists is this army's own? Where the MFM prices that size it says so
// outright. Where it doesn't (Imperial Agents' "7-11 models", which the MFM covers with a 6- and a
// 12-model row) the row's RANK decides: the lists are parallel, so the position that won on every
// priced size wins here too. Nothing is interpolated — a size the MFM doesn't price keeps an
// appdata number, just the one from the right list.
function pickPrices(rows, priced, name, mfmSteps) {
  const groups = new Map()
  for (const r of rows) {
    const k = `${r.per.join('-')}|${JSON.stringify(r.comp || null)}`
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(r)
  }
  const mfmOf = (r) => (priced ? priced.get(r.per[1]) ?? priced.get(r.per[0]) : null)

  const tally = new Map()
  for (const list of groups.values()) {
    const mfm = mfmOf(list[0])
    const at = mfm ? list.findIndex((r) => r.pts === mfm.base) : -1
    if (at >= 0) tally.set(at, (tally.get(at) || 0) + 1)
  }
  let rank = 0
  let best = 0
  for (const [at, n] of [...tally].sort((a, b) => a[0] - b[0])) if (n > best) { best = n; rank = at }

  const out = []
  for (const list of groups.values()) {
    const mfm = mfmOf(list[0])
    const chosen = (mfm && list.find((r) => r.pts === mfm.base)) || list[Math.min(rank, list.length - 1)]
    if (mfm) {
      chosen.pts = mfm.base
      if (mfm.step != null) mfmSteps.push(mfm.step)
    } else if (list.length > 1) {
      report.price.noBracket.push(`${name} ${list[0].per.join('-')}: kept ${chosen.pts} of ${list.map((r) => r.pts).join('/')}`)
    }
    if (chosen.pts !== list[0].pts) report.price.repriced++
    report.price.collapsed += list.length - 1
    if (list.some((r) => r.default)) chosen.default = 1
    out.push(chosen)
  }
  return out
}

// ── Allies ────────────────────────────────────────────────────────────────────────────────────
// An army can include units that do NOT have its Faction keyword: Agents of the Imperium in any
// IMPERIUM army, a Knight or a Titan, Daemons in a Chaos Space Marines army, Brood Brothers in a
// Genestealer Cults one, Harlequins in an Aeldari one. appdata models all 21 of those contexts
// structurally (`allied_faction` + six satellite tables), so nothing here is hand-written: which
// armies may take the group, which datasheets it offers, how many of each keyword per battle size,
// what the combined points may reach, and which Detachment (if any) unlocks it.
//
// Two shapes come out of that, and the difference matters to the loader:
//  - CROSS-FACTION — the units live in another faction's bundle (Draxus is in imperial-agents.js).
//    Their ids are emitted NAMESPACED, `<source slug>:<unit id>`, because a bare id is only unique
//    within a bundle: Astra Militarum and Imperial Agents each have their own `ministorum-priest`
//    datasheet, and an AM army can ally the Agents one. The prefix is also how the runtime knows
//    which bundle to load and which faction's datasheet page a unit links to. One group can even
//    mix sources — the Chaos Space Marines' cult-legion group takes one datasheet from each of
//    Emperor's Children, Death Guard, Thousand Sons and World Eaters — so the source is per id.
//  - IN-BUNDLE (appdata's `isSiblingFaction`, plus Drukhari's Harlequins) — the units are already
//    in this faction's own file (Blood Legions are in world-eaters.js, Harlequins in aeldari.js).
//    Ids stay bare; the group exists only to carry the limits that apply to them.
//
// What the group does NOT carry is the warlord/enhancement ban, because it isn't uniform: the
// cross-faction rules all end "None of these models can be your WARLORD, and they cannot be given
// Enhancements", while Aeldari's Harlequins have no such sentence and Ynnari units are exactly
// what the Devoted of Ynnead Detachment's Enhancements are for. `canTakeEnhancements` is appdata's
// own field and is emitted as `enh`; the rest is the runtime's rule (see rosterValidation.js).
const alliedRows = table('allied_faction')
const fkParentOf = new Map(table('faction_keyword').map((k) => [k.id, k.parentFactionKeywordId]))
const bsSlug = new Map(table('battle_size').map((b) => [b.id, slugify(enOf(b).name)]))
const groupBy = (rows, key) => {
  const m = new Map()
  for (const r of rows) {
    if (!m.has(r[key])) m.set(r[key], [])
    m.get(r[key]).push(r)
  }
  return m
}
const alliedTakers = groupBy(table('faction_keyword_allied_faction'), 'alliedFactionId')
const alliedParents = groupBy(table('allied_faction_parent_faction_keyword'), 'alliedFactionId')
const alliedSheets = groupBy(table('allied_faction_datasheet'), 'alliedFactionId')
const alliedKeywords = groupBy(table('allied_faction_keyword'), 'alliedFactionId')
const alliedPoints = groupBy(table('allied_faction_points_limit'), 'alliedFactionId')
const alliedDets = groupBy(table('allied_faction_required_detachment'), 'alliedFactionId')

// datasheet uuid -> [our faction slug, our unit id]. sourceIds.json is the same map the datasheet
// pages are keyed by, and a datasheet appears under exactly one faction there (1039 of them, no
// duplicates), so this resolves an allied datasheet to the bundle that actually holds it.
const unitBySheet = new Map()
{
  const all = loadJson(path.join(ROOT, 'src/data/sourceIds.json')) || {}
  for (const [slug, entries] of Object.entries(all)) {
    for (const [k, uuid] of Object.entries(entries)) if (k.startsWith('ds:')) unitBySheet.set(uuid, [slug, k.slice(3)])
  }
}

// Is this faction (or a faction it is a chapter/subfaction of) allowed to take the group? Takers
// are recorded at whatever level the rule is written — "Adeptus Astartes" for the Codex armies,
// "Dark Angels" where a Chapter is named — so walk up the keyword's parents.
function fkChain(id) {
  const out = []
  for (let cur = id, n = 0; cur && n < 8; cur = fkParentOf.get(cur), n++) out.push(cur)
  return out
}

// What the group's units cost as ALLIES. The MFM prints a second, dearer list for Agents of the
// Imperium ("Agents of the Imperium (allied)": Draxus 75 in her own army, 110 in somebody else's)
// and ownMfmUnits deliberately ignores it when pricing that faction's own bundle. Same mechanism
// as a Chapter's `unitPoints`: model count -> points, emitted only where it differs, applied by
// loadRosterFaction to a `sizes` array built elsewhere.
const alliedPriceCache = new Map()
async function alliedPricesOf(slug) {
  if (alliedPriceCache.has(slug)) return alliedPriceCache.get(slug)
  const mfm = (await loadModule(path.join(ROOT, 'src/data/mfm', `${slug}.js`)))?.default
  const sub = (mfm?.subfactions || []).find((s) => /allied/i.test(s.name))
  let out = null
  if (sub) {
    const allied = mfmPrices(sub.units)
    const own = mfmPrices(ownMfmUnits(mfm))
    out = new Map()
    for (const [name, prices] of allied) {
      const diff = {}
      for (const [models, p] of prices) if (own.get(name)?.get(models)?.base !== p.base) diff[models] = p.base
      if (Object.keys(diff).length) out.set(name, diff)
    }
  }
  alliedPriceCache.set(slug, out)
  return out
}

async function alliesFor(factionKeywordId, ownUnitIds, slug) {
  const chain = fkChain(factionKeywordId)
  const mine = new Map(chain.map((id, i) => [id, i]))     // keyword -> how far up the chain it is
  const out = []
  for (const af of alliedRows) {
    const takers = (alliedTakers.get(af.id) || []).filter((t) => mine.has(t.factionKeywordId))
    if (!takers.length) continue
    // How specifically this army is named: 0 when the rule names the faction itself, higher when it
    // names a parent. Deathwatch is offered the Agents of the Imperium list twice — the general one
    // (written for ADEPTUS ASTARTES) and its own, which is that list minus the five Deathwatch
    // datasheets its own bundle already has. Both are real rows; the one written FOR this army is
    // the one that applies, and emitting both would also print the group twice on screen.
    const distance = Math.min(...takers.map((t) => mine.get(t.factionKeywordId)))
    const names = (alliedParents.get(af.id) || []).map((p) => fkwName.get(p.factionKeywordId)).filter(Boolean)
    const group = { key: slugify(names.join(' ')), name: names.join(' / ') }
    const ids = []
    const missing = []
    const up = {}
    for (const row of alliedSheets.get(af.id) || []) {
      const found = unitBySheet.get(row.datasheetId)
      if (!found) { missing.push(enOf(dsById.get(row.datasheetId)).name || row.datasheetId); continue }
      const [srcSlug, unitId] = found
      if (srcSlug === slug) {
        // Already in this bundle (a sibling faction, or a Chapter's own copy) — bare id.
        if (ownUnitIds.has(unitId)) ids.push(unitId)
        else missing.push(`${unitId} (not a buildable entry)`)
        continue
      }
      const id = `${srcSlug}:${unitId}`
      ids.push(id)
      const prices = await alliedPricesOf(srcSlug)
      const diff = prices?.get(normApost(enOf(dsById.get(row.datasheetId)).name || ''))
      if (diff) up[id] = diff
    }
    if (!ids.length) { report.allies.empty.push(`${slug}: ${group.name}`); continue }
    group.ids = ids.sort()
    // Keyword caps ("up to 3 ARMIGER models"), per battle size. `mutex` is appdata's
    // isMutuallyExclusiveKeywordLimit — the Knight/Titan rule reads "either one TITANIC model OR
    // up to three ARMIGER models", so the caps are alternatives, not a budget each.
    const lim = {}
    for (const r of alliedKeywords.get(af.id) || []) {
      const kw = kwName.get(r.keywordId)
      const size = bsSlug.get(r.battleSizeId)
      if (!kw || !size) continue
      lim[kw] = lim[kw] || {}
      lim[kw][size] = r.limitCount
    }
    if (Object.keys(lim).length) group.lim = lim
    if (af.isMutuallyExclusiveKeywordLimit) group.mutex = 1
    const pts = {}
    for (const r of alliedPoints.get(af.id) || []) if (bsSlug.get(r.battleSizeId)) pts[bsSlug.get(r.battleSizeId)] = r.pointsLimit
    if (Object.keys(pts).length) group.pts = pts
    const dets = (alliedDets.get(af.id) || []).map((r) => enOf(detById.get(r.detachmentId)).name).filter(Boolean).sort()
    if (dets.length) group.dets = dets
    if (af.canTakeEnhancements) group.enh = 1
    if (Object.keys(up).length) group.up = up
    if (missing.length) report.allies.missing.push(`${slug}/${group.name}: ${missing.join(', ')}`)
    out.push({ group, distance })
  }
  const best = new Map()
  for (const { group, distance } of out) {
    const had = best.get(group.key)
    if (!had || distance < had.distance) best.set(group.key, { group, distance })
    if (had) report.allies.narrowed.push(`${slug}: ${group.name} (${(had.distance <= distance ? group : had.group).ids.length} ids dropped for the closer rule)`)
  }
  const kept = [...best.values()].map((x) => x.group)
  report.allies.groups += kept.length
  for (const g of kept) report.allies.units += g.ids.length
  return kept.sort((a, b) => a.name.localeCompare(b.name))
}

// What the shared Codex: Space Marines units cost THIS Chapter. A Chapter's bundle doesn't repeat
// them (loadRosterFaction folds them in from space-marines.js), so their price can't come from
// buildUnit — but it does differ: Blood Angels pay 80 for an Assault Intercessor Squad where the
// Codex price is 75, and all four Chapters with a Repulsor Executioner pay 230 against the Codex's
// 255. The MFM records those under the Chapter's own "Space Marines" subfaction, which is exactly
// how `pointsOverrides` in src/data/datasheets/<chapter>.js is built — same idea, same source, so
// the roster and the datasheet page quote the same number.
//
// Emitted only where the Chapter price differs, keyed by MODEL COUNT rather than by bracket index:
// loadRosterFaction applies it to a `sizes` array it didn't build and mustn't assume the shape of.
function chapterUnitPoints(mfmFaction, smMfm, sharedIds, smIdMap, nameToDsId) {
  const sub = (mfmFaction?.subfactions || []).find((s) => norm(s.name) === 'space marines')
  if (!sub) return null
  const chapter = mfmPrices(sub.units)
  const codex = mfmPrices(smMfm?.units)
  const shared = new Set(sharedIds)
  const out = {}
  for (const [name, prices] of chapter) {
    const id = smIdMap.get(nameToDsId.get(name))
    if (!id || !shared.has(id)) continue
    const diff = {}
    for (const [models, p] of prices) if (codex.get(name)?.get(models)?.base !== p.base) diff[models] = p.base
    if (Object.keys(diff).length) out[id] = diff
  }
  return Object.keys(out).length ? out : null
}

function buildUnit(bd, idMap, fx, kwIndex, prices) {
  const minis = (minisByDs.get(bd.id) || []).slice().sort((a, b) => a.displayOrder - b.displayOrder)
  const miniIdx = new Map(minis.map((m, i) => [m.id, i]))
  const kws = bd.keywords || []
  const linkedId = idMap.get(bd.id)
  const flags = {}
  if (keyword(kws, 'Character')) flags.char = 1
  if (keyword(kws, 'Epic Hero')) flags.epic = 1
  if (minis.some((m) => m.isSupremeCommander)) flags.supreme = 1
  if (minis.some((m) => m.canBeNonCharacterWarlord)) flags.nonCharWarlordOk = 1
  if (minis.length && minis.every((m) => m.cannotBeWarlord)) flags.noWarlord = 1
  if (minis.length && minis.every((m) => m.excludedFromEnhancements)) flags.noEnh = 1

  // A datasheet can flag several compositions `default` (appdata groups by
  // referenceGroupingKeywordId); the editor pre-selects exactly one, so keep the flag only
  // on the first default-marked bracket.
  let defaultTaken = false
  const mfmSteps = []
  const comps = compByDs.get(bd.id) || []
  // Only when the two lists line up exactly — same length, same points, same model total. A
  // datasheet that fails any of those keeps today's behaviour (no `comp`, every reader falls back)
  // rather than getting a breakdown that might belong to a different bracket.
  const compsUsable = minis.length > 1 && comps.length === (bd.points || []).length
  const priced = prices?.get(normApost(bd.name))
  if (!priced) report.price.noUnit.push(`${bd.name}`)
  const rows = (bd.points || []).map((p, i) => {
    const [min, max] = parseModels(p.models)
    const s = { pts: p.points, per: [min, max] }
    if (p.default) s.default = 1
    if (compsUsable) {
      const rows = (compMinis.get(comps[i].id) || []).filter((r) => miniIdx.has(r.miniatureId))
      const sum = rows.reduce((a, r) => [a[0] + r.min, a[1] + r.max], [0, 0])
      if (rows.length && comps[i].points === p.points && sum[0] === min && sum[1] === max) {
        // `[miniatureIndex, min, max]`, max dropped when it equals min — most rows are fixed.
        s.comp = rows
          .map((r) => (r.min === r.max ? [miniIdx.get(r.miniatureId), r.min] : [miniIdx.get(r.miniatureId), r.min, r.max]))
          .sort((a, b) => a[0] - b[0])
        report.comp.brackets++
      } else report.comp.rejected.push(`${bd.name} #${i}: ${min}-${max}@${p.points} vs ${sum[0]}-${sum[1]}@${comps[i].points}`)
    }
    return s
  })
  const sizes = pickPrices(rows, priced, bd.name, mfmSteps)
  for (const s of sizes) {
    if (s.default && defaultTaken) delete s.default
    else if (s.default) defaultTaken = true
  }
  if (sizes.some((x) => x.comp)) report.comp.units++


  const unit = {
    id: linkedId || slugify(bd.name),
    sid: bd.id,
    name: bd.name,
    kws,
    flags,
    sizes,
  }
  if (linkedId) unit.linked = 1
  const step = stepByDs.get(bd.id)
  if (step) unit.step = step
  // The copy tax stays appdata's (`datasheet_points_step` knows WHICH copy it starts at, which the
  // MFM only implies through its "1st-2nd"/"3rd+" notes). Cross-checked against the surcharge those
  // notes describe, so a disagreement is reported rather than quietly shipped on top of an MFM base.
  const mfmStep = mfmSteps.length && mfmSteps.every((n) => n === mfmSteps[0]) ? mfmSteps[0] : null
  if (mfmStep != null && (step?.pts ?? 0) !== mfmStep) {
    report.price.stepDrift.push(`${bd.name}: appdata +${step?.pts ?? 0}, MFM +${mfmStep}`)
  }
  if (condBattlelineDs.has(bd.id)) unit.condBattleline = 1

  // The group id lives on the raw datasheet row, not in the faction bundle.
  const allegGroup = allegGroups.get(dsById.get(bd.id)?.allegianceAbilityGroupId)
  if (allegGroup) {
    const opts = (allegByGroup.get(allegGroup.id) || [])
      .sort((a, b) => a.displayOrder - b.displayOrder)
      .map((a) => {
        const o = { n: enOf(a).name }
        const kwId = allegKw.get(`${bd.id}|${a.id}`)
        const kw = kwId && kwName.get(kwId)
        if (kw && kw !== o.n) o.kw = kw
        if (a.requiresWargearItemId) o.wg = fx.item(a.requiresWargearItemId)
        return o
      })
      .filter((o) => o.n)
    if (opts.length) {
      // `det` is the detachment NAME because that is what a roster stores (see useRosters); absent
      // means the choice always applies. `req` = must be chosen, `max` = cap across the army.
      const alleg = { g: slugify(enOf(allegGroup).name || 'allegiance'), t: enOf(allegGroup).name || '', o: opts }
      const detOwner = allegGroup.detachmentId && detById.get(allegGroup.detachmentId)
      if (detOwner) alleg.det = enOf(detOwner).name
      if (allegGroup.isMandatory) alleg.req = 1
      if (allegGroup.maxRosterLimit) alleg.max = allegGroup.maxRosterLimit
      if (allegGroup.minRosterLimit) alleg.min = allegGroup.minRosterLimit
      unit.alleg = alleg
      report.alleg.units++
      report.alleg.kinds.add(`${alleg.g}${alleg.det ? ` (${alleg.det})` : ''}`)
    }
  }

  const groups = bgByLeader.get(bd.id) || []
  const leads = []
  const leadKw = []
  for (const g of groups) {
    let targets = bgDatasheets.get(g.id) || []
    if (!targets.length && bgKeywords.has(g.id)) {
      // Resolved against THIS faction's datasheets here, and the KEYWORDS themselves are emitted
      // as well (`leadKw`), because a resolved id cannot travel: Inquisitor Draxus leads "any
      // IMPERIUM BATTLELINE INFANTRY unit", and as an ally in an Adeptus Mechanicus army the unit
      // she joins is a Skitarii Vanguard that her own bundle has never heard of. The runtime
      // answers the keyword question against whatever is actually in the list (rosterEngine's
      // leadTypeFor).
      const kw = { kw: bgKeywords.get(g.id).filter(Boolean), type: g.bodyguardType }
      if (g.requiredDetachmentId) kw.reqDet = g.requiredDetachmentId
      if (g.excludedDetachmentId) kw.exclDet = g.excludedDetachmentId
      if (kw.kw.length) leadKw.push(kw)
      const want = bgKeywords.get(g.id).map(norm).filter(Boolean)
      targets = (kwIndex ? want.map((k) => kwIndex.get(k) || []).reduce((a, b) => a.filter((x) => b.includes(x)), want.length ? kwIndex.get(want[0]) || [] : []) : [])
        .filter((id) => id !== bd.id)
      if (targets.length) report.leadKw.resolved += targets.length
      else report.leadKw.unresolved.push(`${bd.name} → ${bgKeywords.get(g.id).join(' + ')}`)
    }
    for (const targetDsId of targets) {
      const lead = { to: idMap.get(targetDsId) || slugify(enOf(dsById.get(targetDsId)).name || ''), type: g.bodyguardType }
      if (g.requiredDetachmentId) lead.reqDet = g.requiredDetachmentId
      if (g.excludedDetachmentId) lead.exclDet = g.excludedDetachmentId
      leads.push(lead)
    }
  }
  // Deduped: a keyword group ("any Imperium Battleline Infantry unit") and a listed group can name
  // the same unit, and the picker would offer it twice.
  const seenLead = new Set()
  const uniqueLeads = leads.filter((l) => {
    const k = `${l.to}|${l.type}|${l.reqDet || ''}|${l.exclDet || ''}`
    return seenLead.has(k) ? false : (seenLead.add(k), true)
  })
  if (uniqueLeads.length) unit.leads = uniqueLeads
  if (leadKw.length) unit.leadKw = leadKw

  // Miniatures (for labelling gear/loadout groups). A single-profile unit needs no list.
  if (minis.length > 1) unit.minis = minis.map((m) => ({ n: enOf(m).name }))

  // Default loadout: what each miniature starts equipped with.
  const fixItem = (uuid) => {
    const to = LOADOUT_ITEM_FIXES[bd.id]?.[uuid]
    if (!to) return uuid
    report.loadoutFixed.push(`${bd.name}: ${wgItemName.get(uuid)} → ${wgItemName.get(to)}`)
    return to
  }
  const defaults = []
  for (const b of bmlByDs.get(bd.id) || []) {
    const items = b.opts
      .map((o) => [woById.get(o.wargearOptionId)?.wargearItemId, o.count])
      .filter(([uuid]) => uuid)
      .map(([uuid, count]) => [fx.item(fixItem(uuid)), count])
    if (items.length) defaults.push([miniIdx.get(b.miniatureId) ?? 0, items])
  }
  // Whether the counts below are PER MODEL (base_miniature_loadout's own reading) or the TOTAL the
  // profile fields (a "Default Wargear" group's) — the two tables count differently, and only the
  // per-copy reading further down has to tell them apart.
  let defaultsAreTotals = false
  if (!defaults.length) {
    for (const [m, items] of staticLoadout(bd.id, miniIdx)) defaults.push([m, items.map(([uuid, c]) => [fx.item(fixItem(uuid)), c])])
    if (defaults.length) { report.staticDefaults++; defaultsAreTotals = true }
  } else {
    // The two tables can disagree, and where they do it is the loadout ROW that is short: a
    // Servitor Battleclade's Gun Servitors carry a heavy bolter and a heavy arc rifle between them
    // and the row records neither, an Archon loses its Shadowfield, Inquisitor Coteaz his
    // psyber-eagle. Seven miniatures game-wide, one of them the Death Company Dreadnought whose row
    // names another datasheet's weapons outright (LOADOUT_ITEM_FIXES above). So anything the
    // "Default Wargear" group names and the row does not is added to it.
    //
    // The two tables also COUNT differently: a row is per model ("Servo-claw 1", twice over), the
    // group is the total the profile fields ("Servo-claw 2", "Heavy bolter 1" — one of the two Gun
    // Servitors has it). A quantity that cannot be divided among the models is therefore marked as
    // a TOTAL with a third element, which is how the editor and the export know not to multiply it.
    const compOf = (m) => {
      const size = bd.points?.length ? (unit.sizes || []).find((x) => x.default) || (unit.sizes || [])[0] : null
      return (size?.comp || []).find(([mi]) => mi === m)?.[1] || 1
    }
    for (const [m, items] of staticLoadout(bd.id, miniIdx)) {
      const at = defaults.find(([mi]) => mi === m)
      if (!at) { defaults.push([m, items.map(([uuid, c]) => [fx.item(fixItem(uuid)), c])]); continue }
      const have = new Set(at[1].map(([id]) => id))
      for (const [uuid, c] of items) {
        const id = fx.item(fixItem(uuid))
        if (have.has(id)) continue
        const models = compOf(m)
        at[1].push(models > 1 ? [id, c, 1] : [id, c])
        report.defaultsMerged.push(`${bd.name} / ${enOf((minisByDs.get(bd.id) || []).find((x) => (miniIdx.get(x.id) ?? 0) === m)).name || m}: ${wgItemName.get(uuid)}${models > 1 ? ` (${c} for the profile)` : ''}`)
      }
    }
  }
  if (defaults.length) unit.defaults = defaults

  // Wargear option groups: the atomic "replace/add one of {…}" choices. Drop the redundant
  // "Default Wargear" groups (base loadout already carries those) — keep real choices, with
  // their per-option points (0 when free) and default flag. Built as raw drafts first (original
  // instructionText + item UUIDs kept around) because the cross-group linking pass below needs
  // to read prose and resolve item names *before* everything gets interned to ints. Sorted by
  // the group's own displayOrder (same field already used for the group's OPTIONS below) — was
  // previously left in raw table order, which doesn't match wh40k-appdata's own intended
  // presentation: e.g. Necron Overlord's Resurrection Orb toggle (a non-weapon add-on) has a
  // higher displayOrder than its tachyon-arrow-replacement weapon group, so it should render
  // BELOW that weapon choice, not above it.
  let drafts = []
  for (const g of (wogByDs.get(bd.id) || []).slice().sort((a, b) => a.displayOrder - b.displayOrder)) {
    const text = (enOf(g).instructionText || '').trim()
    if (!text || isDefaultGroup(g)) continue
    const rawOpts = (woByGroup.get(g.id) || []).sort((a, b) => a.displayOrder - b.displayOrder)
    if (!rawOpts.length) continue
    drafts.push({
      m: miniIdx.get(g.miniatureId) ?? 0,
      miniId: g.miniatureId,
      text,
      in: rawOpts[0]?.inputType || 'checkbox',
      opts: rawOpts.map((o) => ({ uuid: o.wargearItemId, pts: o.points || 0, def: o.defaultValue || 0 })),
    })
  }
  linkWargearConditions(bd.id, drafts)
  linkWargearBundles(bd.id, bd.name, drafts, report.bundle)
  // Before the limits: two identical groups are exactly what makes a limited set ambiguous, so
  // folding them first lets its cap land on the one group that remains.
  drafts = mergeMiniatureDuplicates(drafts, report.limit)
  linkWargearLimits(bd.id, bd.name, miniIdx, drafts, report.limit)
  // Where appdata records no limited-choice set at all, the instruction is the only statement of
  // the allowance there is — and it is often a real cap: "This model can be equipped with up to two
  // of the following, but cannot take duplicates" (a Grand Master in Nemesis Dreadknight, which
  // takes a Sublimator AND a heavy psycannon at 15 points each). Without it the group had no cap,
  // and validateRoster's conservative fallback — one pick per model of that profile — called a
  // legal two-weapon Dreadknight illegal. Read only where the prose states a plain number
  // (proseAllowance already refuses "for every 5 models" and "any number of"), and never over a
  // cap appdata itself gave.
  for (const d of drafts) {
    if (d.lim) continue
    const said = proseAllowance(d.text)
    if (!said) continue
    const dup = /cannot take duplicates/i.test(d.text) ? 1 : 0
    d.lim = [dup ? [0, said, dup] : [0, said]]
    report.limit.fromProse++
  }
  // A swap a model may make ONCE PER COPY of the weapon it gives up: "Each of this model's
  // shuriken catapults can be replaced with 1 flamer" (a Wraithlord carries two), "Any number of
  // this model's dark lances can each be replaced with 1 disintegrator cannon" (a Ravager carries
  // three), "This model's big shootas can each be replaced with one of the following" (a Deff
  // Dread). The allowance is nowhere in the sentence and nowhere in appdata either — it is how
  // many of that weapon the printed loadout gives the model — so validateRoster's one-pick-per-
  // model fallback called every one of those ordinary builds illegal and the editor's stepper
  // stopped at one. `cp` records the copies per MODEL; the engine multiplies by the models of that
  // profile, which is what "each model can have each shuriken cannon it is equipped with replaced"
  // (War Walkers, 2 models × 2 cannons) needs.
  //
  // A bundled swap is not this and must not be read as it: "This model's 2 twin heavy flamers can
  // be replaced with 2 twin heavy bolters" is ONE pick that grants two items (44 groups corpus-
  // wide, against 6 per-copy ones), so the option granting exactly one item is what tells them
  // apart — together with the word "each", which every per-copy wording has and no bundled one does.
  const grantCount = (o) => (o.items ? o.items.reduce((n, [, c]) => n + (c || 1), 0) : 1)
  for (const d of drafts) {
    if (d.lim || !d.rep?.length || !/\beach\b/i.test(d.text.split('\n')[0])) continue
    if (!d.opts.every((o) => grantCount(o) === 1)) continue
    const row = defaults.find(([m]) => m === d.m)?.[1] || []
    // A count that is the profile's TOTAL rather than one model's has to be divided by the models
    // that profile fields, or a Crisis Starscythe's "2 burst cannons" — one each for its two
    // Shas'ui — would read as two per model and hand every model a swap it doesn't have.
    const bracket = (unit.sizes || []).find((x) => x.default) || (unit.sizes || [])[0]
    const perProfile = (bracket?.comp || []).find(([mi]) => mi === d.m)?.[1] ?? (bracket?.per?.[0] ?? 1)
    const copies = Math.min(...d.rep.map((uuid) => {
      const hit = row.find(([id]) => id === fx.item(uuid))
      if (!hit) return 1
      const n = hit[1] || 1
      const total = defaultsAreTotals || hit.length > 2
      if (!total) return n
      return perProfile > 0 && n % perProfile === 0 ? n / perProfile : 1
    }))
    if (copies > 1) { d.cp = copies; report.limit.perCopy++ }
  }
  const gear = []
  const gearIndex = new Map() // draft -> its final index in `gear`
  drafts.forEach((d, i) => gearIndex.set(d, i))
  for (const d of drafts) {
    const grp = {
      // No `m` on a unit-wide group (see mergeMiniatureDuplicates) — it belongs to no single
      // miniature, and the editor labels a group with its miniature's name when it has one.
      ...(d.all ? { all: 1 } : { m: d.m }),
      t: fx.text(d.text),
      in: d.in,
      o: d.opts.map((o) => {
        // Slot 0 is the item id, or — when the option is a bundle or carries a quantity — the
        // full `[[id, count], …]` set (see linkWargearBundles). rosterEngine's optionItems()
        // is the one reader of that polymorphism; nothing else should unpack slot 0 itself.
        const head = o.items ? o.items.map(([uuid, n]) => [fx.item(uuid), n]) : fx.item(o.uuid)
        const e = [head, o.pts, o.def]
        while (e.length > 1 && e[e.length - 1] === 0) e.pop() // trim trailing zeros
        return e
      }),
    }
    if (d.lim) grp.lim = d.lim
    if (d.cp) grp.cp = d.cp
    if (d.rep?.length) grp.rep = d.rep.map((uuid) => fx.item(uuid))
    // How many models one ticked option takes the swap away from. A stepper says so itself; a
    // CHECKBOX is one yes/no, and one tick means one model — "1 model's boltgun can be replaced
    // with one of the following" arms a single Battle Sister, not all nine. Only the "all models /
    // any number of" wording means the whole profile, so that reading is the one flagged (4 groups
    // corpus-wide) and the other 575 take the per-model default.
    if (d.rep?.length && d.in !== 'stepper' && /^\s*(?:all models|any number of)\b/i.test(d.text)) grp.repall = 1
    if (d.cond) grp.cond = [gearIndex.get(d.cond.sibling), d.cond.active ? 1 : 0]
    gear.push(grp)
  }
  if (gear.length) unit.gear = gear
  return unit
}

// A handful of "enhancements" are, per their own rules text, not a player pick at all: Necrons'
// Pantheon of Woe and Imperial Agents' Veiled Blade Elimination Force both read "each <unit> from
// your army has the relevant <ability>... and you must increase the points cost of each of those
// units" — automatic and mandatory for every eligible datasheet, not a once-per-army slot. The
// source data still models them as detachment enhancements (that's how the card is laid out), but
// with a broken requirement: enhancement_required_keyword_group_keyword points at "DNU" ("do not
// use"), an orphaned internal GW keyword attached to no datasheet, so as generated these can never
// legally be taken by anyone. Each is actually locked to one exact datasheet ("X model only" in
// its rules text), which already carries a matching name keyword — substitute the real
// requirement and flag it mandatory here. (rosterEngine.js's enhEligible treats an exact-name-
// keyword requirement as an override for the unit's general noEnh/epic-without-epicOk gates,
// since being locked to one specific datasheet is already maximally restrictive; enhancementPoints
// applies a mandatory enhancement automatically instead of waiting for entry.enh.)
// Typographic apostrophe (’, U+2019) — matches the datasheet names as extracted from appdata
// (see CLAUDE.md's RU-transliteration note: the source consistently uses ’, never a straight ').
