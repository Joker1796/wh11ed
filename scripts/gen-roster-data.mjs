// Generate the roster-builder's derived data layer from wh40k-appdata (the private,
// authoritative dump of the official GW app — see CLAUDE.md `sourceId`). Like the mfm /
// datasheet data already in the repo, this emits only structural facts needed to *build and
// cost an army list* — unit names, keywords, points brackets, copy-tax steps, detachments,
// enhancement eligibility, leader attachments — with NO rules prose, so it's the same class
// of derived data that already ships publicly.
//
// Usage:  node scripts/gen-roster-data.mjs        (all factions)
//         node scripts/gen-roster-data.mjs --check (report only, write nothing — used by `npm run sync`)
//
// Sources per faction: the faction BUNDLE (factions/<appSlug>.json) gives membership +
// keywords + points brackets + the detachment/enhancement list (already faction-scoped and
// name-parsed); the raw TABLES supply what the bundle omits — miniature warlord flags, the
// datasheet_points_step copy-tax, leader (bodyguard) attachments, dynamic-Battleline
// conditional keywords, and enhancement eligibility groups. Wargear options are their own,
// larger pass — groups, mutual-exclusion links and bundled options; see the WARGEAR note.
//
// Output (each file headed `// Generated by gen-roster-data.mjs — do not edit`):
//   src/data/roster/core.js        — battle sizes (points / DP / enhancement+duplicate limits)
//   src/data/roster/<slug>.js      — one per faction
//   src/data/roster/index.js       — loadRosterFaction(slug) lazy loader
//
// Linked units: a unit whose appdata datasheet id maps (via src/data/sourceIds.json's `ds:`
// entries) to a wh11ed datasheet slug carries `linked:true` + that id, so the editor can
// deep-link to the unit's datasheet page. Unmatched units get a slugified id and no link.

