const normApost = (s) => (s || '').toLowerCase().replace(/[’‘]/g, "'")

function buildEnhancement(e, nameToDsId, idMap) {
  const name = enOf(e).name
  const enh = { name, pts: e.basePointsCost, type: e.enhancementType }
  if (e.cannotBeWarlord) enh.notWarlord = 1
  if (!e.isIncludedInEnhancementLimit) enh.uncounted = 1
  if (e.isEquipableByEpicHero) enh.epicOk = 1
  if (e.isEquipableByNonCharacterUnit) enh.nonCharOk = 1
  if (e.limit && e.limit !== 1) enh.limit = e.limit
  // eligibility: OR of groups, each an AND of faction-keywords + keywords.
  const req = []
  for (const gid of reqGroupsByEnh.get(e.id) || []) {
    const g = {}
    const fac = (reqGroupFac.get(gid) || []).filter(Boolean)
    const kw = (reqGroupKw.get(gid) || []).filter(Boolean)
    if (fac.length) g.fac = fac
    if (kw.length) g.kw = kw
    if (fac.length || kw.length) req.push(g)
  }
  if (req.length) enh.req = req
  const excl = (exclKwByEnh.get(e.id) || []).filter(Boolean)
  if (excl.length) enh.exclKw = excl
  if (ENH_LOCK_FIXES[name]) {
    const ids = ENH_LOCK_FIXES[name].map((n) => nameToDsId.get(normApost(n))).filter(Boolean)
    // Conservative: only apply if EVERY named target resolved — a partial/failed resolution
    // (e.g. a future appdata rename) falls back to the existing (too-broad) faction-keyword
    // req rather than silently locking to the wrong subset.
    if (ids.length === ENH_LOCK_FIXES[name].length) enh.lockDs = ids
  }
  if (ENH_REQ_FIXES[name]) {
    enh.req = [{ kw: ENH_REQ_FIXES[name] }]
    enh.mandatory = 1
  }
  // Attach targets this enhancement grants its bearer, resolved to this faction's own unit ids
  // (a target on another faction's datasheet has nothing to attach to in this roster and drops).
  const attach = (enhAttachByEnh.get(e.id) || [])
    .map((a) => ({ to: idMap.get(a.datasheetId), type: a.type }))
    .filter((a) => a.to)
  if (attach.length) enh.attach = attach
  return enh
}

function buildDetachment(bdet, idMap, mfmDet, nameToDsId) { // idMap also reaches buildEnhancement
  // The Detachment-Points cost + Force Disposition come from mfm (what the tracker shows), not
  // appdata's detachmentPointsCost — those disagree (appdata is 0 for standard detachments).
  const mfm = mfmDet.get(norm(bdet.name))
  const det = { name: bdet.name, sid: bdet.id, dp: mfm?.dp ?? bdet.detachmentPointsCost ?? 0 }
  if (mfm?.forceDisposition) det.fd = mfm.forceDisposition
  const excl = (detExcluded.get(bdet.id) || []).map((id) => idMap.get(id) || slugify(enOf(dsById.get(id)).name || '')).filter(Boolean)
  if (excl.length) det.excludedUnits = excl
  const linked = (detLinked.get(bdet.id) || []).map((r) => {
    const l = { unit: idMap.get(r.datasheetId) || slugify(enOf(dsById.get(r.datasheetId)).name || ''), count: r.count }
    if (r.isWarlord) l.warlord = 1
    return l
  })
  if (linked.length) det.linkedUnits = linked
  const resolveMinis = (miniIds) => miniIds
    .map((mm) => { const ds = miniToDs.get(mm); return ds ? (idMap.get(ds) || slugify(enOf(dsById.get(ds)).name || '')) : null })
    .filter(Boolean)
  const mandUnits = resolveMinis(detMandWarlord.get(bdet.id) || [])
  if (mandUnits.length) det.mandWarlord = mandUnits
  const grantedUnits = resolveMinis(detGrantedWarlord.get(bdet.id) || [])
  if (grantedUnits.length) det.grantedWarlord = grantedUnits
  const enhancements = (enhByDet.get(bdet.id) || [])
    .filter((e) => !e.isCombatPatrol)
    .sort((a, b) => a.displayOrder - b.displayOrder)
    .map((e) => buildEnhancement(e, nameToDsId, idMap))
  det.enhancements = enhancements
  return det
}

// The same "must increase the points cost" mandatory ability (see ENH_REQ_FIXES) is ALSO present
// on the datasheet's own points brackets — the bundle lists a second bracket, same composition
// (`per` unchanged), priced exactly base + the enhancement's points. That's not a real unit-size
// choice (verified: the delta matches the matching enhancement's points to the point, for all 6
// known cases), so surfacing it as one in the editor lets a player "buy" the ability twice — once
// via that bracket, once via the always-applied mandatory enhancement. Strip the redundant
// bracket here; enhancementPoints (rosterEngine.js) is the single place the surcharge is added.
function stripMandatoryPriceBrackets(units, detachments) {
  const enhPtsByTargetKw = new Map()
  for (const det of detachments) {
    for (const e of det.enhancements) {
      if (e.mandatory && e.req?.[0]?.kw?.[0]) enhPtsByTargetKw.set(e.req[0].kw[0], e.pts)
    }
  }
  if (!enhPtsByTargetKw.size) return
  for (const u of units) {
    const bump = enhPtsByTargetKw.get(u.name)
    if (bump == null || u.sizes.length < 2) continue
    const base = u.sizes.reduce((min, s) => (s.pts < min.pts ? s : min), u.sizes[0])
    u.sizes = u.sizes.filter((s) => s === base || !(s.pts === base.pts + bump && s.per[0] === base.per[0] && s.per[1] === base.per[1]))
  }
}

const HEAD = '// Generated by gen-roster-data.mjs — do not edit. Re-run `npm run roster:data`.\n'
const stableJson = (obj) => JSON.stringify(obj, null, 2)

async function genFaction(slug) {
  const appSlug = SLUG_MAP[slug] || slug
  const bundle = loadJson(path.join(APPDATA, 'factions', `${appSlug}.json`))
  if (!bundle) { report.missingBundle.push(slug); return }
  const idMap = unitIdMap(slug)

  // mfm detachment map (name → { dp, forceDisposition }) — the tracker's numbers.
  const mfmMod = await loadModule(path.join(ROOT, 'src/data/mfm', `${slug}.js`))
  const mfmFaction = mfmMod?.default
  const mfmDet = new Map((mfmFaction?.detachments || []).map((d) => [norm(d.name), d]))

  // Name -> datasheet id, scoped to THIS faction's own bundle (before the points-filter below —
  // an ENH_LOCK_FIXES target should resolve even if the unit itself isn't a buildable line entry)
  // so a name shared across sub-factions (Helbrute/Maulerfiend — one datasheet per Chaos Legion
  // codex) resolves to the copy this faction actually has, not some other book's. A Chapter's own
  // bundle doesn't repeat the Codex: Space Marines units it shares (see the SM-Chapter dedup in
  // CLAUDE.md) — seed from the SM bundle first so a Chapter-specific enhancement targeting a
  // plain shared unit (Dark Angels' "Entreaty of Perpetual Ardour" → "Hellblaster Squad", not the
  // Chapter's own boxed-set-exclusive "Vengeful Brethren Hellblaster Squad") still resolves; the
  // Chapter's own entries are added after, so a name it DOES override still wins.
  const nameToDsId = new Map()
  if (isChapter(slug)) {
    const smBundle = loadJson(path.join(APPDATA, 'factions', `${SLUG_MAP['space-marines']}.json`))
    for (const d of smBundle?.datasheets || []) nameToDsId.set(normApost(d.name), d.id)
  }
  for (const d of bundle.datasheets || []) nameToDsId.set(normApost(d.name), d.id)

  // A handful of datasheets carry no points/composition (special epic heroes or
  // detachment-only variants) — not buildable matched-play line entries, so drop them.
  const bundleUnits = (bundle.datasheets || []).filter((d) => {
    if (cpDatasheetIds.has(d.id)) return false
    if (!(d.points && d.points.length)) { report.noPoints.push(`${slug}: ${d.name}`); return false }
    return true
  })
  const units = bundleUnits.map((bd) => buildUnit(bd, idMap, fx)).sort((a, b) => a.name.localeCompare(b.name))
  const detachments = (bundle.detachments || [])
    .filter((d) => !d.isCombatPatrol && !cpDatasheetIds.has(d.id))
    .map((bdet) => buildDetachment(bdet, idMap, mfmDet, nameToDsId))
    .sort((a, b) => a.name.localeCompare(b.name))
  stripMandatoryPriceBrackets(units, detachments)

  report.factions++
  report.units += units.length
  for (const u of units) { if (u.linked) report.linked++; else report.unlinked.push(`${slug}: ${u.name}`) }

  const data = { slug, name: enOf(bundle.faction).name || bundle.faction?.name || slug, units, detachments }
  // SM-Chapter fold: a Chapter's bundle lists only its own units; the shared Adeptus Astartes
  // pool lives in space-marines.js. Reuse the exact `sharedUnitIds` the datasheet layer already
  // computed (data/datasheets/<chapter>.js) so the roster shows the same unit list as the rules
  // pages. loadRosterFaction() folds them in at load time.
  if (isChapter(slug)) {
    const dsMod = await loadModule(path.join(ROOT, 'src/data/datasheets', `${slug}.js`))
    const shared = dsMod?.sharedUnitIds || []
    if (shared.length) data.sharedUnitIds = shared
  }
  const body = `${HEAD}export default ${stableJson(data)}\n`
  fs.writeFileSync(path.join(OUT, `${slug}.js`), body)
}

function genItems() {
  const items = {}
  for (const [uuid, id] of itemIds) items[id] = wgItemName.get(uuid) || ''
  const texts = {}
  for (const [s, id] of textIds) texts[id] = s
  const data = { items, texts }
  fs.writeFileSync(path.join(OUT, 'items.js'), `${HEAD}// Shared wargear item names + group instruction texts, interned across all factions.\nexport default ${stableJson(data)}\n`)
}

function genCore() {
  const sizes = table('battle_size')
    .map((b) => ({ id: slugify(enOf(b).name), name: enOf(b).name, points: b.pointsLimit, dp: b.detachmentPointsLimit, enhLimit: b.enhancementLimit, dupLimit: b.duplicateUnitLimit }))
    .sort((a, b) => a.points - b.points)
  const data = { formatVersion: 1, battleSizes: sizes }
  fs.writeFileSync(path.join(OUT, 'core.js'), `${HEAD}export default ${stableJson(data)}\n`)
}

function genIndex() {
  const body = `${HEAD}// Lazy per-faction roster data. Each faction file is a chunk of its own so the roster
// editor only pulls the faction being built (PWA entry-chunk stays clean — see CLAUDE.md).
// Glob only the faction files — exclude core/items/index and the test file (the latter pulls
// in node: builtins and would break the browser build once this loader is bundled).
const loaders = import.meta.glob(['./*.js', '!./core.js', '!./items.js', '!./index.js', '!./*.test.js'], { import: 'default' })

const load = (slug) => {
  const loader = loaders[\`./\${slug}.js\`]
  return loader ? loader() : Promise.resolve(null)
}

// Load a faction's roster data, folding the shared Adeptus Astartes pool into an SM Chapter
// (data.sharedUnitIds → space-marines units), so callers see one flat unit list. Folded units
// keep their own ids and resolve against the shared items/texts dicts (see ./items.js).
export async function loadRosterFaction(slug) {
  const data = await load(slug)
  if (!data) return null
  if (!data.sharedUnitIds?.length) return data
  const sm = await load('space-marines')
  const idSet = new Set(data.sharedUnitIds)
  const shared = (sm?.units || []).filter((u) => idSet.has(u.id)).map((u) => ({ ...u, shared: 1 }))
  const units = [...data.units, ...shared].sort((a, b) => a.name.localeCompare(b.name))
  return { ...data, units }
}

export { default as rosterCore } from './core.js'
export { default as rosterItems } from './items.js'
`
  fs.writeFileSync(path.join(OUT, 'index.js'), body)
}

