const slugify = (s) => norm(s).replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

// Parse a bundle points `models` field: a number (5) or a range string ("6-10") → [min,max].
function parseModels(models) {
  if (typeof models === 'number') return [models, models]
  const m = String(models).match(/(\d+)\s*-\s*(\d+)/)
  if (m) return [Number(m[1]), Number(m[2])]
  const n = Number(models)
  return Number.isFinite(n) ? [n, n] : [1, 1]
}

