// Generate the roster-builder's derived data layer from wh40k-appdata (the private,
// authoritative dump of the official GW app — see CLAUDE.md `sourceId`). Like the mfm /
// datasheet data already in the repo, this emits only structural facts needed to *build and
// cost an army list* — unit names, keywords, points brackets, copy-tax steps, detachments,
// enhancement eligibility, leader attachments — with NO rules prose, so it's the same class
// of derived data that already ships publicly.
//
// Usage:  node scripts/gen-roster-data.mjs        (all factions)
//         node scripts/gen-roster-data.mjs <slug> [<slug> ...]
//
// Sources per faction: the faction BUNDLE (factions/<appSlug>.json) gives membership +
// keywords + points brackets + the detachment/enhancement list (already faction-scoped and
// name-parsed); the raw TABLES supply what the bundle omits — miniature warlord flags, the
// datasheet_points_step copy-tax, leader (bodyguard) attachments, dynamic-Battleline
// conditional keywords, and enhancement eligibility groups. Wargear options are a separate,
// larger pass (gen-roster-data emits units without gear for now — see the WARGEAR note).
//
// Output (each file headed `// Generated by gen-roster-data.mjs — do not edit`):
//   src/data/roster/core.js        — battle sizes (points / DP / enhancement+duplicate limits)
//   src/data/roster/<slug>.js      — one per faction
//   src/data/roster/index.js       — loadRosterFaction(slug) lazy loader
//
// Linked units: a unit whose appdata datasheet id maps (via src/data/sourceIds.json's `ds:`
// entries) to a wh11ed datasheet slug carries `linked:true` + that id, so the editor can
// deep-link to the unit's datasheet page. Unmatched units get a slugified id and no link.

import fs from 'node:fs'
import path from 'node:path'
import { ROOT, APPDATA, SLUG_MAP, norm, loadJson, loadModule } from './lib/sync-common.mjs'

const T = path.join(APPDATA, 'tables')
const OUT = path.join(ROOT, 'src/data/roster')
const table = (name) => loadJson(path.join(T, `${name}.json`)) || []
const enOf = (o) => o?.localisations?.en || {}
const slugify = (s) => norm(s).replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

// Parse a bundle points `models` field: a number (5) or a range string ("6-10") → [min,max].
function parseModels(models) {
  if (typeof models === 'number') return [models, models]
  const m = String(models).match(/(\d+)\s*-\s*(\d+)/)
  if (m) return [Number(m[1]), Number(m[2])]
  const n = Number(models)
  return Number.isFinite(n) ? [n, n] : [1, 1]
}

// ---- Raw-table lookups (built once) ----------------------------------------------------

const publications = table('publication')
const cpPubIds = new Set(publications.filter((p) => p.isCombatPatrol).map((p) => p.id))
const datasheets = table('datasheet')
const dsById = new Map(datasheets.map((d) => [d.id, d]))
const cpDatasheetIds = new Set(datasheets.filter((d) => cpPubIds.has(d.publicationId)).map((d) => d.id))

// miniature warlord/enhancement flags, grouped by datasheet.
const minisByDs = new Map()
for (const m of table('miniature')) {
  if (!minisByDs.has(m.datasheetId)) minisByDs.set(m.datasheetId, [])
  minisByDs.get(m.datasheetId).push(m)
}

// copy-tax: one step row per datasheet (verified in Phase 0 — always ≤1). `at` is the copy
// index at which the surcharge starts, `pts` the flat surcharge on that and every later copy.
const stepByDs = new Map(table('datasheet_points_step').map((s) => [s.datasheetId, { at: s.stepAt, pts: s.stepPoints }]))

// leaders: bodyguard groups keyed by the LEADER datasheet, each listing the units it can join.
const bgDatasheets = new Map() // groupId -> [datasheetId]
for (const r of table('datasheet_bodyguard_group_datasheet')) {
  if (!bgDatasheets.has(r.datasheetBodyguardGroupId)) bgDatasheets.set(r.datasheetBodyguardGroupId, [])
  bgDatasheets.get(r.datasheetBodyguardGroupId).push(r.datasheetId)
}
const bgByLeader = new Map() // leader datasheetId -> [group]
for (const g of table('datasheet_bodyguard_group')) {
  if (!bgByLeader.has(g.datasheetId)) bgByLeader.set(g.datasheetId, [])
  bgByLeader.get(g.datasheetId).push(g)
}

// dynamic Battleline (and other conditional keywords) — datasheets that gain a keyword under
// a condition. We only surface that the unit CAN be Battleline (for the ×2 duplicate rule).
const condBattlelineDs = new Set()
{
  const battlelineKwIds = new Set(table('keyword').filter((k) => norm(enOf(k).name) === 'battleline').map((k) => k.id))
  for (const c of table('conditional_keyword')) if (battlelineKwIds.has(c.keywordId) && c.datasheetId) condBattlelineDs.add(c.datasheetId)
}

// enhancements grouped by detachment (+ eligibility groups / excluded keywords).
const kwName = new Map(table('keyword').map((k) => [k.id, enOf(k).name]))
const fkwName = new Map(table('faction_keyword').map((k) => [k.id, enOf(k).name]))
const enhByDet = new Map()
for (const e of table('enhancement')) {
  if (!enhByDet.has(e.detachmentId)) enhByDet.set(e.detachmentId, [])
  enhByDet.get(e.detachmentId).push(e)
}
const reqGroupFac = new Map() // groupId -> [factionKeyword name]
for (const r of table('enhancement_required_keyword_group_faction_keyword')) {
  const k = r.enhancementRequiredKeywordGroupId
  if (!reqGroupFac.has(k)) reqGroupFac.set(k, [])
  reqGroupFac.get(k).push(fkwName.get(r.factionKeywordId))
}
const reqGroupKw = new Map() // groupId -> [keyword name]
for (const r of table('enhancement_required_keyword_group_keyword')) {
  const k = r.enhancementRequiredKeywordGroupId
  if (!reqGroupKw.has(k)) reqGroupKw.set(k, [])
  reqGroupKw.get(k).push(kwName.get(r.keywordId))
}
const reqGroupsByEnh = new Map() // enhancementId -> [groupId]
for (const g of table('enhancement_required_keyword_group')) {
  if (!reqGroupsByEnh.has(g.enhancementId)) reqGroupsByEnh.set(g.enhancementId, [])
  reqGroupsByEnh.get(g.enhancementId).push(g.id)
}
const exclKwByEnh = new Map() // enhancementId -> [keyword name]
for (const r of table('enhancement_excluded_keyword')) {
  if (!exclKwByEnh.has(r.enhancementId)) exclKwByEnh.set(r.enhancementId, [])
  exclKwByEnh.get(r.enhancementId).push(kwName.get(r.keywordId))
}

// detachment structural constraints.
const detExcluded = new Map() // detachmentId -> [datasheetId]
for (const r of table('detachment_excluded_datasheet')) {
  if (!detExcluded.has(r.detachmentId)) detExcluded.set(r.detachmentId, [])
  detExcluded.get(r.detachmentId).push(r.datasheetId)
}
const detLinked = new Map() // detachmentId -> [{datasheetId,count,isWarlord}]
for (const r of table('detachment_linked_datasheet')) {
  if (!detLinked.has(r.detachmentId)) detLinked.set(r.detachmentId, [])
  detLinked.get(r.detachmentId).push(r)
}
const detMandWarlord = new Map(table('detachment_mandatory_warlord_miniature').map((r) => [r.detachmentId, r.miniatureId]))
const miniToDs = new Map(table('miniature').map((m) => [m.id, m.datasheetId]))

// ---- Per-faction generation ------------------------------------------------------------

const report = { factions: 0, units: 0, linked: 0, unlinked: [], missingBundle: [], noPoints: [] }

// Invert sourceIds.json for a faction: appdata datasheet UUID -> wh11ed datasheet slug.
function unitIdMap(slug) {
  const all = loadJson(path.join(ROOT, 'src/data/sourceIds.json')) || {}
  const map = new Map()
  const add = (s) => { for (const [k, uuid] of Object.entries(all[s] || {})) if (k.startsWith('ds:')) map.set(uuid, k.slice(3)) }
  add(slug)
  if (slug !== 'space-marines' && SLUG_MAP[slug] === undefined && /* chapters share the SM pool */ isChapter(slug)) add('space-marines')
  return map
}
const CHAPTERS = new Set(['black-templars', 'blood-angels', 'dark-angels', 'deathwatch', 'space-wolves'])
const isChapter = (slug) => CHAPTERS.has(slug)

function keyword(kws, name) {
  const n = name.toLowerCase()
  return (kws || []).some((k) => k.toLowerCase() === n)
}

function buildUnit(bd, idMap) {
  const ds = dsById.get(bd.id)
  const minis = minisByDs.get(bd.id) || []
  const kws = bd.keywords || []
  const linkedId = idMap.get(bd.id)
  const flags = {}
  if (keyword(kws, 'Character')) flags.char = 1
  if (keyword(kws, 'Epic Hero')) flags.epic = 1
  if (minis.some((m) => m.isSupremeCommander)) flags.supreme = 1
  if (minis.some((m) => m.canBeNonCharacterWarlord)) flags.nonCharWarlordOk = 1
  if (minis.length && minis.every((m) => m.cannotBeWarlord)) flags.noWarlord = 1
  if (minis.length && minis.every((m) => m.excludedFromEnhancements)) flags.noEnh = 1

  // A datasheet can flag several compositions `default` (appdata groups by
  // referenceGroupingKeywordId); the editor pre-selects exactly one, so keep the flag only
  // on the first default-marked bracket.
  let defaultTaken = false
  const sizes = (bd.points || []).map((p) => {
    const [min, max] = parseModels(p.models)
    const s = { pts: p.points, per: [min, max] }
    if (p.default && !defaultTaken) { s.default = 1; defaultTaken = true }
    return s
  })

  const unit = {
    id: linkedId || slugify(bd.name),
    sid: bd.id,
    name: bd.name,
    kws,
    flags,
    sizes,
  }
  if (linkedId) unit.linked = 1
  const step = stepByDs.get(bd.id)
  if (step) unit.step = step
  if (condBattlelineDs.has(bd.id)) unit.condBattleline = 1

  const groups = bgByLeader.get(bd.id) || []
  const leads = []
  for (const g of groups) {
    for (const targetDsId of bgDatasheets.get(g.id) || []) {
      const lead = { to: idMap.get(targetDsId) || slugify(enOf(dsById.get(targetDsId)).name || ''), type: g.bodyguardType }
      if (g.requiredDetachmentId) lead.reqDet = g.requiredDetachmentId
      if (g.excludedDetachmentId) lead.exclDet = g.excludedDetachmentId
      leads.push(lead)
    }
  }
  if (leads.length) unit.leads = leads
  return unit
}

function buildEnhancement(e) {
  const enh = { name: enOf(e).name, pts: e.basePointsCost, type: e.enhancementType }
  if (e.cannotBeWarlord) enh.notWarlord = 1
  if (!e.isIncludedInEnhancementLimit) enh.uncounted = 1
  if (e.isEquipableByEpicHero) enh.epicOk = 1
  if (e.isEquipableByNonCharacterUnit) enh.nonCharOk = 1
  if (e.limit && e.limit !== 1) enh.limit = e.limit
  // eligibility: OR of groups, each an AND of faction-keywords + keywords.
  const req = []
  for (const gid of reqGroupsByEnh.get(e.id) || []) {
    const g = {}
    const fac = (reqGroupFac.get(gid) || []).filter(Boolean)
    const kw = (reqGroupKw.get(gid) || []).filter(Boolean)
    if (fac.length) g.fac = fac
    if (kw.length) g.kw = kw
    if (fac.length || kw.length) req.push(g)
  }
  if (req.length) enh.req = req
  const excl = (exclKwByEnh.get(e.id) || []).filter(Boolean)
  if (excl.length) enh.exclKw = excl
  return enh
}

function buildDetachment(bdet, idMap) {
  const det = { name: bdet.name, sid: bdet.id, dp: bdet.detachmentPointsCost ?? bdet.pointsCost ?? 0 }
  const excl = (detExcluded.get(bdet.id) || []).map((id) => idMap.get(id) || slugify(enOf(dsById.get(id)).name || '')).filter(Boolean)
  if (excl.length) det.excludedUnits = excl
  const linked = (detLinked.get(bdet.id) || []).map((r) => {
    const l = { unit: idMap.get(r.datasheetId) || slugify(enOf(dsById.get(r.datasheetId)).name || ''), count: r.count }
    if (r.isWarlord) l.warlord = 1
    return l
  })
  if (linked.length) det.linkedUnits = linked
  const mandMini = detMandWarlord.get(bdet.id)
  if (mandMini) {
    const mandDs = miniToDs.get(mandMini)
    if (mandDs) det.mandWarlord = idMap.get(mandDs) || slugify(enOf(dsById.get(mandDs)).name || '')
  }
  const enhancements = (enhByDet.get(bdet.id) || [])
    .filter((e) => !e.isCombatPatrol)
    .sort((a, b) => a.displayOrder - b.displayOrder)
    .map(buildEnhancement)
  det.enhancements = enhancements
  return det
}

const HEAD = '// Generated by gen-roster-data.mjs — do not edit. Re-run `npm run roster:data`.\n'
const stableJson = (obj) => JSON.stringify(obj, null, 2)

async function genFaction(slug) {
  const appSlug = SLUG_MAP[slug] || slug
  const bundle = loadJson(path.join(APPDATA, 'factions', `${appSlug}.json`))
  if (!bundle) { report.missingBundle.push(slug); return }
  const idMap = unitIdMap(slug)

  // A handful of datasheets carry no points/composition (special epic heroes or
  // detachment-only variants) — not buildable matched-play line entries, so drop them.
  const bundleUnits = (bundle.datasheets || []).filter((d) => {
    if (cpDatasheetIds.has(d.id)) return false
    if (!(d.points && d.points.length)) { report.noPoints.push(`${slug}: ${d.name}`); return false }
    return true
  })
  const units = bundleUnits.map((bd) => buildUnit(bd, idMap)).sort((a, b) => a.name.localeCompare(b.name))
  const detachments = (bundle.detachments || [])
    .filter((d) => !d.isCombatPatrol && !cpDatasheetIds.has(d.id))
    .map((bdet) => buildDetachment(bdet, idMap))
    .sort((a, b) => a.name.localeCompare(b.name))

  report.factions++
  report.units += units.length
  for (const u of units) { if (u.linked) report.linked++; else report.unlinked.push(`${slug}: ${u.name}`) }

  const data = { slug, name: enOf(bundle.faction).name || bundle.faction?.name || slug, units, detachments }
  const body = `${HEAD}export default ${stableJson(data)}\n`
  fs.writeFileSync(path.join(OUT, `${slug}.js`), body)
}

function genCore() {
  const sizes = table('battle_size')
    .map((b) => ({ id: slugify(enOf(b).name), name: enOf(b).name, points: b.pointsLimit, dp: b.detachmentPointsLimit, enhLimit: b.enhancementLimit, dupLimit: b.duplicateUnitLimit }))
    .sort((a, b) => a.points - b.points)
  const data = { formatVersion: 1, battleSizes: sizes }
  fs.writeFileSync(path.join(OUT, 'core.js'), `${HEAD}export default ${stableJson(data)}\n`)
}

function genIndex(slugs) {
  const body = `${HEAD}// Lazy per-faction roster data. Each file is a chunk of its own so the roster editor
// only pulls the faction being built (PWA entry-chunk stays clean — see CLAUDE.md).
const loaders = import.meta.glob('./*.js', { import: 'default' })

export function loadRosterFaction(slug) {
  const loader = loaders[\`./\${slug}.js\`]
  return loader ? loader() : Promise.resolve(null)
}

export { default as rosterCore } from './core.js'
`
  fs.writeFileSync(path.join(OUT, 'index.js'), body)
}

// ---- Run -------------------------------------------------------------------------------

const args = process.argv.slice(2)
let slugs = args
if (!slugs.length) {
  slugs = fs.readdirSync(path.join(ROOT, 'src/data/factions'))
    .filter((f) => f.endsWith('.js') && f !== 'index.js')
    .map((f) => f.replace(/\.js$/, ''))
}
fs.mkdirSync(OUT, { recursive: true })
genCore()
for (const slug of slugs) await genFaction(slug)
genIndex(slugs.filter((s) => !report.missingBundle.includes(s)))

console.log(`\nroster data: ${report.factions} factions, ${report.units} units (${report.linked} linked, ${report.unlinked.length} unlinked)`)
if (report.missingBundle.length) console.log(`  no appdata bundle (skipped): ${report.missingBundle.join(', ')}`)
if (report.noPoints.length) console.log(`  dropped (no points/composition): ${report.noPoints.join(', ')}`)
if (report.unlinked.length) {
  console.log(`  unlinked units (no datasheet page — slugified id, no deep link):`)
  for (const u of report.unlinked.slice(0, 40)) console.log(`    - ${u}`)
  if (report.unlinked.length > 40) console.log(`    … +${report.unlinked.length - 40} more`)
}
