// Footnotes under a per-model group that say what ONE model may hold, written as `excl`: lists of
// option indexes of which each model holds at most one — so together they are at most the unit's
// model count, and the same round-robin argument as PER_MODEL_BUDGET keeps that exact. One
// footnote in the corpus says this within one group: Broadside's "* No model can be equipped with
// both a twin plasma rifle and twin smart missile system" → the pair is one set. (Legends Crisis'
// starred items reach across two groups and are the unit's `pm`, pack-roster.mjs's perModelRules.)
// Run on the finished units, pack Legends included. A footnote whose options cannot all be found is
// reported and writes nothing.
function oneEachPerModel(slug, units) {
  const texts = new Map([...textIds].map(([t, id]) => [id, t]))
  const nameOf = new Map([...itemIds].map(([uuid, id]) => [id, norm(wgItemName.get(uuid) || packItemNames.get(uuid) || '')]))
  for (const u of units) {
    for (const g of u.gear || []) {
      const t = texts.get(g.t) || ''
      const names = (o) => (Array.isArray(o[0]) ? o[0].map(([id]) => id) : [o[0]]).map((id) => nameOf.get(id))
      const at = (name) => g.o.findIndex((o) => names(o).includes(norm(name)))
      const sets = []
      const both = /no model can be equipped with both (?:an? )?(.+?) and (?:an? )?(.+?)\.?\s*$/im.exec(t)
      if (both) sets.push([at(both[1]), at(both[2])])
      if (!sets.length) continue
      if (sets.some((x) => x.some((i) => i < 0))) { report.limit.perModelBudget.push(`${slug}/${u.name}: a footnote names an option the group lacks — nothing written`); continue }
      g.excl = sets
      report.limit.perModelBudget.push(`${u.name}: one per model ${JSON.stringify(sets)}`)
    }
  }
}

// A model's limit across SEVERAL groups, from the footnotes that state it (`xpm`, rosterEngine's
// wargearXpmOver/Room; an audit of every instruction, 2026-10-07 — none of these was enforced):
//   "This model cannot have duplicates of these pieces of wargear." / "* Maximum 1 per model." —
//     each STARRED item at most once, wherever the model's groups offer it (Tau Commanders: the
//     burst-cannon swap and "up to three of the following"; a Champion's two pistol-or-weapon swaps)
//   "A model cannot be equipped with more than one X or more than one Y." (Knight Destrier)
//   "cannot be equipped with both A and B … more than 1 A … more than 1 B" (Hive Tyrant)
//   "A model can only take one of these options" / "These options cannot be taken on the same
//     model" / "You cannot select both X and Y for the same model" — the starred groups together at
//     most one per model, plus the groups of any item the sentence forbids alongside (Pioneers)
//   "For each X* this model is equipped with … That X cannot then be replaced." — the group and
//     every swap of X together at most the X the model holds (Helbrute).
// Units with `pm` (the Legends Crisis Battlesuits) already carry their own reading and are skipped.
function crossGroupPerModel(slug, units) {
  const texts = new Map([...textIds].map(([t, id]) => [id, t]))
  const nameOf = new Map([...itemIds].map(([uuid, id]) => [id, norm(wgItemName.get(uuid) || packItemNames.get(uuid) || '')]))
  const idOfName = (u, name) => { const n = norm(name); for (const g of u.gear || []) for (const o of g.o) { const ids = Array.isArray(o[0]) ? o[0].map(([id]) => id) : [o[0]]; for (const id of ids) if (nameOf.get(id) === n || nameOf.get(id) === n.replace(/s$/, '')) return id } return null }
  const single = (o) => (Array.isArray(o[0]) ? (o[0].length === 1 ? o[0][0][0] : null) : o[0])
  const pairsOf = (u, name, m) => {
    const n = norm(name)
    const out = []
    u.gear.forEach((g, gi) => { if (m != null && (g.all || (g.m ?? 0) !== m)) return; g.o.forEach((o, oi) => { const id = single(o); const nm = id != null && nameOf.get(id); if (nm && (nm === n || nm === n.replace(/s$/, ''))) out.push([gi, oi]) }) })
    return out
  }
  for (const u of units) {
    if (u.pm || !u.gear?.length) continue
    const xpm = []
    const push = (set, why) => { if (set.s.length) { xpm.push(set); report.limit.perModelBudget.push(`${u.name}: across groups — ${why}`) } }
    u.gear.forEach((g, gi) => {
      const t = texts.get(g.t) || ''
      const lines = t.split('\n').map((l) => l.trim()).filter(Boolean)
      const foot = lines.filter((l) => /^\*/.test(l)).join(' ')
      if (!foot) return
      const m = g.all ? null : g.m ?? 0
      if (/cannot have duplicates of these|maximum 1 per model/i.test(foot)) {
        for (const l of lines) { const b = l.match(/^[◦•▪■▫]\s*(?:1\s+)?(.+?)\*\s*$/); if (b) push({ s: pairsOf(u, b[1], m), k: 1 }, `one ${b[1]}`) }
      }
      const more = foot.match(/more than one (.+?) or more than one (.+?)\.?\*?\s*$/i)
      if (more) for (const nm of [more[1], more[2]]) push({ s: pairsOf(u, nm, m), k: 1 }, `one ${nm}`)
      const both = foot.match(/cannot be equipped with both (?:an? )?(.+?) and (?:an? )?(.+?)\./i)
      if (both && /more than 1/i.test(foot)) {
        push({ s: [...pairsOf(u, both[1], m), ...pairsOf(u, both[2], m)], k: 1 }, `one of ${both[1]} / ${both[2]}`)
      }
      if (/only take one of these options|cannot be taken on the same model|cannot select both .+ for the same model/i.test(foot)) {
        // The groups "these options" means: those carrying the same footnote, and a starred group
        // with no footnote of its own (Spectrus prints it under the second of two starred lines).
        // A starred group whose star points at a DIFFERENT footnote is not one of them (Krieg's
        // special weapons, "*" = once per unit, beside its "**" medi-pack and vox-caster).
        const footOf = (ht) => ht.split('\n').map((l) => l.trim()).filter((l) => /^\*/.test(l)).join(' ')
        const starred = u.gear.map((h, hi) => [h, hi]).filter(([h]) => { const ht = texts.get(h.t) || ''; const f2 = footOf(ht); return f2 === foot || (!f2 && ht.split('\n')[0].includes('*')) }).map(([, hi]) => hi)
        const with_ = foot.match(/cannot be equipped with (?:an? )?(.+?) or (?:an? )?(.+?)\.?\s*$/i)
        const extra = with_ ? [...pairsOf(u, with_[1], null), ...pairsOf(u, with_[2], null)].map(([hi]) => hi) : []
        const groups = [...new Set([...starred, ...extra])]
        if (!xpm.some((x) => JSON.stringify(x.s) === JSON.stringify(groups.map((hi) => [hi])))) push({ s: groups.map((hi) => [hi]), k: 1 }, `one of groups ${groups.join('/')}`)
        // Several "■ 1 model … can be equipped with 1 X" lines in ONE group are separate allowances,
        // one model each — not a one-of: the Pioneers may take the comms array AND the scanner.
        const allowances = lines.filter((l) => /^[■▪◦•]\s*1 model\b/i.test(l)).length
        if (allowances > 1 && !g.lim) { g.lim = [[0, allowances, 1]]; report.limit.perModelBudget.push(`${u.name}: ${allowances} separate one-model allowances in one group`) }
      }
      const each = lines[0].match(/^for each (.+?)\*? this model is equipped with/i)
      if (each && /cannot then be replaced/i.test(foot)) {
        const id = idOfName(u, each[1])
        if (id != null) {
          const swaps = u.gear.map((h, hi) => [h, hi]).filter(([h, hi]) => hi !== gi && h.rep?.includes(id)).map(([, hi]) => [hi])
          push({ s: [[gi], ...swaps], item: id }, `for each ${each[1]}`)
        }
      }
    })
    // One entry per distinct set (a footnote repeated under two groups names the same set twice).
    const seen = new Set()
    const uniq = xpm.filter((x) => { const k = JSON.stringify(x); if (seen.has(k)) return false; seen.add(k); return true })
    if (uniq.length) u.xpm = uniq
  }
}

// MIRROR_ATTACH for the Faction Pack Legends. The rule ("If a CHARACTER unit with the Leader
// ability (excluding Epic Heroes) can be attached to a Legionaries unit, it can be attached to this
// unit instead") is applied while the appdata units are built, and the Legends join the faction
// after — so a Chaos Lord on Disc of Tzeentch, who may lead Legionaries, could not lead the Nemesis
// Claw beside them (found 2026-10-07 by the datasheets' "Led by" lists). Same rule, same reading:
// at the type the borrowed attachment has, gated as it is, never for an Epic Hero where it says so.
function mirrorPackLeads(slug, pack) {
  if (!pack.length) return
  const idMap = unitIdMap(slug)
  for (const u of pack) {
    if (!u.leads?.length) continue
    for (const m of MIRROR_ATTACH) {
      const to = idMap.get(m.to)
      if (!to || to === u.id || u.leads.some((l) => l.to === to)) continue
      if (m.noEpic && u.flags?.epic) continue
      if (m.need.length && !m.need.some((k) => (u.kws || []).some((x) => norm(x) === norm(k)))) continue
      const from = new Set([...m.from].map((uuid) => idMap.get(uuid)).filter(Boolean))
      const via = u.leads.find((l) => from.has(l.to))
      if (!via) continue
      const lead = { to, type: via.type }
      if (via.reqDet) lead.reqDet = via.reqDet
      if (via.exclDet) lead.exclDet = via.exclDet
      u.leads.push(lead)
      report.mirror.added.push(`${u.name} (Legends) → ${to}`)
    }
  }
}

// "Led by" / "Supported by" for a BODYGUARD unit's datasheet page (owner, 2026-10-07): the reverse
// of every leader's `leads`, per faction, so the datasheet shows who may join the unit the way a
// leader's shows whom it may join. Read from the roster layer rather than from the printed "can be
// attached to" lists, because the roster already holds what those lists miss: the "attached to
// this unit instead" mirrors (9 links appdata does not record), the Faction Pack Legends, and the
// attachments an enhancement grants. One small file per faction (src/data/ledBy/<slug>.js), loaded
// with the page. A lead gated on a Detachment carries it — `in` (only there) or `out` (not there);
// the CSM pairs that state one attachment twice, required-inside and excluded-outside, cancel out.
// A keyword attachment (an Inquisitor's "Imperium Battleline Infantry") is not listed by name.
function genLedBy() {
  const bySlug = new Map(built.map(({ slug, data }) => [slug, data]))
  const sm = bySlug.get('space-marines')
  fs.mkdirSync(path.join(OUT, '../ledBy'), { recursive: true })
  const index = []
  for (const { slug, data } of built) {
    const shared = new Set(data.sharedUnitIds || [])
    const pool = [...data.units, ...(sm && slug !== 'space-marines' ? sm.units.filter((u) => shared.has(u.id)) : [])]
    const ids = new Set(pool.map((u) => u.id))
    const dets = [...(data.detachments || []), ...(sm && slug !== 'space-marines' ? sm.detachments || [] : [])]
    const detName = new Map(dets.filter((d) => d.sid).map((d) => [d.sid, d.name]))
    const out = {}
    const add = (to, row) => { (out[to] ||= []).push(row) }
    for (const u of pool) {
      const byTarget = new Map()
      for (const l of u.leads || []) {
        if (!ids.has(l.to) || l.to === u.id) continue
        const k = `${l.to}|${l.type}`
        if (!byTarget.has(k)) byTarget.set(k, [])
        byTarget.get(k).push(l)
      }
      for (const [k, ls] of byTarget) {
        const [to, type] = k.split('|')
        // Any ungated statement, or "inside D" beside "outside D" for the same D, is "always".
        // Otherwise the Detachments it needs (several possible), or the one it is barred from.
        let note = null
        if (!ls.some((l) => !l.reqDet && !l.exclDet)) {
          const reqs = new Set(ls.map((l) => l.reqDet).filter(Boolean))
          const excls = new Set(ls.map((l) => l.exclDet).filter(Boolean))
          const always = [...excls].some((d) => reqs.has(d))
          if (!always && reqs.size) note = { in: [...reqs].map((d) => detName.get(d)).filter(Boolean).sort() }
          else if (!always && excls.size) note = { out: [...excls].map((d) => detName.get(d)).filter(Boolean).sort() }
          if (note && !(note.in || note.out).length) note = null
        }
        add(to, note ? [u.name, type, note] : [u.name, type])
      }
    }
    // A Detachment's enhancement that lets its bearer join a unit (Abhuman Detail → Ogryns), with
    // the characters that may take it (`by`) — asked of the roster's own rule, so the page and the
    // builder cannot disagree on who that is.
    for (const d of data.detachments || []) for (const e of d.enhancements || []) {
      const to = (e.attach || []).filter((a) => ids.has(a.to))
      if (!to.length) continue
      const by = [...new Set(pool.filter((u) => enhEligible(e, u)).map((u) => u.name))].sort()
      for (const a of to) add(a.to, [e.name.replace(/\s*\((?:Upgrade|Ulgrade)\)$/i, ''), a.type, { enh: 1, det: d.name, by }])
    }
    const keys = Object.keys(out).sort()
    if (!keys.length) continue
    const sorted = Object.fromEntries(keys.map((k) => [k, out[k].sort((a, b) => (a[1] === b[1] ? a[0].localeCompare(b[0]) : a[1] === 'leader' ? -1 : 1))]))
    writeOut(`../ledBy/${slug}.js`, `${HEAD}// bodyguard datasheet id -> [name, 'leader' | 'support', note?] of the characters that may join it.\nexport default ${stableJson(sorted)}\n`)
    index.push(slug)
  }
  report.ledBy = index.length
}

