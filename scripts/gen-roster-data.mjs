// Any instruction that describes a swap, in either voice appdata uses. The rep parser below
// resolves them; `--check` fails on one it could not, because a group that gives nothing up is
// a model carrying both weapons and a limit with no stock behind it. Written once, read twice.
const SWAP_SHAPED = /replaced with|\bcan\s+(?:each\s+)?replace\s+(?:its|their|his|her|the)\b/i

// A handful of wargear groups depend on ANOTHER group on the same datasheet+miniature — e.g.
// Necron Overlord's Resurrection Orb is only on offer after giving up the default tachyon arrow,
// and several Chaos Daemon units offer a daemonic-icon/instrument-of-Chaos pair that are
// mutually exclusive. wh40k-appdata has no structural field linking two `wargear_option_group`
// rows for this — the relationship lives only in prose ("if [not] equipped with X", "…can be
// replaced with…") — so this parses it conservatively: an unresolved phrase or an ambiguous
// sibling match just leaves the group unconstrained (today's already-correct behaviour for the
// ~1100 other datasheets), never a wrong link. Mutates `drafts` in place, adding `rep`
// (item UUIDs this group replaces, for defaultLoadoutLines' default-vs-swap accounting) and
// `cond` (`{ sibling: <draft>, active }` — this group is only live once the sibling's own
// "has a deviation recorded" state matches `active`; see rosterEngine.js wargearGroupLive) to
// whichever drafts resolve.
// The starting gear of a datasheet that has no `base_miniature_loadout` row: appdata records it as
// a wargear_option_group whose instruction is literally "Default Wargear", one per miniature. 144
// datasheets are in that shape (136 with such a group), and reading only the loadout table left
// them with NO default loadout at all — no "starts equipped with" line in the editor and nothing
// for Tier A's weapon trim to subtract from. Returns the same `[[miniatureIndex, [[uuid, count]]]]`
// shape as the loadout table so the caller can't tell the two sources apart; count is 1, which is
// all a wargear_option can express.
// Which groups are that starting gear. Nearly all of them SAY so — the instruction is literally
// "Default Wargear", 899 groups — but four state it in prose instead ("One other Navis Armsman is
// equipped with:", "One Voidsman is equipped with:", the Tesseract Vault's "Powers of the C'tan"),
// and appdata marks their options the same way either title does: every one of them a default.
// Read as choices, those four became a group of alternatives capped at one, and a legal list came
// out illegal — the Breachers' second armsman carries a heavy shotgun AND an Endurant Shield AND a
// close combat weapon, which is three picks in a group that allows one. So the test is the SHAPE:
// a group every option of which is a default is not a choice, whatever it calls itself.
function isDefaultGroup(g) {
  const text = (enOf(g).instructionText || '').trim().toLowerCase()
  if (text === 'default wargear' || text === 'defualt wargear') return true
  const opts = woByGroup.get(g.id) || []
  return opts.length > 1 && opts.every((o) => o.defaultValue > 0)
}

function staticLoadout(datasheetId, miniIdx) {
  const idx = miniIdx || new Map((minisByDs.get(datasheetId) || []).slice()
    .sort((a, b) => a.displayOrder - b.displayOrder).map((m, i) => [m.id, i]))
  // One entry per miniature, the counts of all its default groups ADDED: a profile can be split
  // over several groups — the Breachers' Navis Armsmen are three (the las-volley one, the heavy
  // shotgun one, "every other model"), each naming a close combat weapon, 1 + 1 + 7. Returned
  // one entry per group until 2026-09-28, the caller kept the first group's count and dropped the
  // other two as "already there": nine armsmen, one close combat weapon.
  const byMini = new Map()
  for (const g of wogByDs.get(datasheetId) || []) {
    if (!isDefaultGroup(g)) continue
    const m = idx.get(g.miniatureId) ?? 0
    const acc = byMini.get(m) || new Map()
    for (const o of (woByGroup.get(g.id) || []).sort((a, b) => a.displayOrder - b.displayOrder)) {
      if (!o.wargearItemId) continue
      acc.set(o.wargearItemId, (acc.get(o.wargearItemId) || 0) + (o.defaultValue > 0 ? o.defaultValue : 1))
    }
    if (acc.size) byMini.set(m, acc)
  }
  return [...byMini].map(([m, acc]) => [m, [...acc]])
}

function linkWargearConditions(datasheetId, drafts) {
  if (!drafts.length) return
  const repStats = report.rep

  // Item names known to THIS datasheet only — defaults plus every draft's own options — so a
  // same-named item belonging to some unrelated unit elsewhere can never match. Keyed through
  // norm(), not toLowerCase(): appdata types these names by hand, so the same weapon appears with
  // a curly apostrophe here and a U+2010 hyphen there ("multi‐laser", "hot‐shot lascarbine") — the
  // same class of silent no-op that apostrophes caused in enhancements and ë in Votann detachments.
  const nameToUuid = new Map()
  // The same names again with every apostrophe, hyphen and space removed. appdata spells one
  // item two ways across its own tables — the prose says "kustom-mega blasta" where the item
  // table says "Kustom mega-blasta" — and this index is what lets the two meet. A key that two
  // different items would share is poisoned to null rather than resolving to whichever came last.
  const canonToUuid = new Map()
  const canon = (s) => s.replace(/[^a-z0-9]/g, '')
  const remember = (uuid) => {
    const n = norm(wgItemName.get(uuid) || '')
    if (!n) return
    nameToUuid.set(n, uuid)
    const c = canon(n)
    canonToUuid.set(c, canonToUuid.has(c) && canonToUuid.get(c) !== uuid ? null : uuid)
  }
  // What each PROFILE starts with, by miniature id. Two of the readings below need it: an
  // instruction naming a weapon category ("its ranged weapon") and one naming two alternatives
  // ("its power sword or shuriken rifle") are both answered by looking at what the profile
  // actually holds — the datasheet knows, even though the sentence doesn't say.
  //
  // 144 datasheets have no base_miniature_loadout row at all — for 136 of them the starting gear
  // is a "Default Wargear" option group instead (see staticLoadout), and those groups are dropped
  // before the drafts are built, so their items have to be collected here too or a swap on one of
  // them ("this model's heavy bolt pistol can be replaced with…") resolves nothing. Same test as
  // staticLoadout uses — by SHAPE, not by title: the Breachers' las-volley is named only by a
  // group that says "One Navis Armsman is equipped with:", and reading that group as a choice is
  // what left "1 Navis Armsman's Navis las-volley can be replaced with…" replacing nothing.
  const defaultsByMini = new Map()
  const addDefault = (miniatureId, uuid) => {
    if (!uuid) return
    if (!defaultsByMini.has(miniatureId)) defaultsByMini.set(miniatureId, new Set())
    defaultsByMini.get(miniatureId).add(uuid)
    remember(uuid)
  }
  for (const b of bmlByDs.get(datasheetId) || []) {
    for (const o of b.opts) addDefault(b.miniatureId, woById.get(o.wargearOptionId)?.wargearItemId)
  }
  for (const g of wogByDs.get(datasheetId) || []) {
    if (!isDefaultGroup(g)) continue
    for (const o of woByGroup.get(g.id) || []) addDefault(g.miniatureId, o.wargearItemId)
  }
  for (const d of drafts) for (const o of d.opts) remember(o.uuid)

  // One name out of the prose. The prose counts and pluralises what the item table does not
  // ("this model's 2 twin heavy flamers" vs the item "Twin heavy flamer"), so both are stripped
  // before the lookup — a leading quantity, then a trailing plural if the exact name missed.
  const resolveItem = (raw, miniId) => {
    const n0 = norm(raw).replace(/^\d+\s+/, '')
    const n = PROSE_NAME_FIXES[enOf(dsById.get(datasheetId)).name]?.[n0] || n0
    // "-s" before "-es": stripping greedily turns "dark lances" into "dark lanc", not "dark lance".
    const exact = nameToUuid.get(n) || nameToUuid.get(n.replace(/s$/, '')) || nameToUuid.get(n.replace(/es$/, ''))
    if (exact) return exact
    // A weapon CATEGORY rather than a name — answerable only when the profile holds exactly one
    // weapon of that type, which is the case for all three instructions written this way.
    const cat = n.match(/^(ranged|melee) weapons?$/)
    if (cat) {
      const hits = [...(defaultsByMini.get(miniId) || [])].filter((u) => wgItemTypes.get(u)?.has(cat[1]))
      return hits.length === 1 ? hits[0] : null
    }
    if (canonToUuid.get(canon(n))) return canonToUuid.get(canon(n))
    // Below here the prose and the item table disagree about the name itself, so a match is a
    // judgement, not a lookup: each of these accepts only when exactly ONE item can be meant.
    // A one-character difference at equal length — "absolver bolt pistol" for "Absolvor bolt
    // pistol". Equal length is what keeps it from reaching a genuinely different weapon.
    const typo = [...nameToUuid].filter(([k]) => k.length === n.length && k !== n
      && [...k].filter((ch, i) => ch !== n[i]).length === 1)
    if (typo.length === 1) return typo[0][1]
    // A name the prose has prefixed with one adjective — "plague combi-bolter" for the item
    // "Combi-bolter". Exactly one leading word, because anything longer is a phrase naming more
    // than one item ("condemnor bolt pistol and null mace", "bolter or ion blaster") and matching
    // its tail would silently answer with the last weapon named instead of all of them. That one
    // word also has to be an adjective and not an article or possessive: "its bolt shotgun" is a
    // fresh clause the split missed, and reading it as a name would answer half a sentence.
    const suffix = [...nameToUuid].filter(([k]) => n.endsWith(` ${k}`)
      && /^(?!(?:a|an|the|its|their|his|her|one|each)$)[a-z0-9'-]+$/.test(n.slice(0, -k.length - 1)))
    if (suffix.length === 1) return suffix[0][1]
    return null
  }

  // "X or Y" names ONE of two items as the thing given up. The sentence doesn't say which — but
  // the profile usually does, because it holds only one of them; that's why the option exists in
  // the first place. Two of these are genuinely ambiguous (the profile holds both) and stay
  // unresolved. Note the answer is only right for the FIRST such swap: a model that already
  // traded X for Y through an earlier group has moved on, and static data can't follow it.
  const resolveAlternatives = (chunk, miniId) => {
    const alts = chunk.split(/\s+or\s+/i).map((s) => s.trim()).filter(Boolean)
    if (alts.length < 2) return null
    const uuids = alts.map((a) => resolveItem(a, miniId))
    if (!uuids.every(Boolean)) return null
    const held = [...new Set(uuids)].filter((u) => defaultsByMini.get(miniId)?.has(u))
    return held.length === 1 ? held[0] : null
  }

  // What is given up is the PROFILE's own item, and the prose may name it by the tail of its name:
  // "The Fire Dragon Exarch's Dragon fusion gun can be replaced with…" gives up the Exarch's
  // "Exarch's Dragon fusion gun", not the troopers' "Dragon fusion gun" an exact lookup lands on;
  // a Magna-grapple Dreadnought's "Furioso fists" are its "Twin Furioso fists". Matched to another
  // profile's item, the swap took nothing away and the old weapon stayed on the card beside the
  // new one (found 2026-10-05 sweeping every swap). So a resolved item the profile does not hold
  // yields to the ONE item it does hold whose name ends with the phrase.
  const heldByTail = (chunk, miniId) => {
    const n = norm(chunk).replace(/^\d+\s+/, '')
    const forms = [n, n.replace(/s$/, ''), n.replace(/es$/, '')]
    const hits = [...(defaultsByMini.get(miniId) || [])].filter((u) => {
      const k = norm(wgItemName.get(u) || '')
      return forms.some((f) => f && (k === f || k.endsWith(` ${f}`) || k.replace(/s$/, '').endsWith(` ${f}`)))
    })
    return hits.length === 1 ? hits[0] : null
  }
  // Not when the unit hands the item out through its own options: the Wracks' Acothyst gives up
  // the single "torturer's tool" an earlier swap left it, and that is the item meant.
  const optionUuids = new Set(drafts.flatMap((d) => d.opts.map((o) => o.uuid)))
  const resolveChunk = (chunk, miniId) => {
    const u = resolveItem(chunk, miniId)
    if (u && (defaultsByMini.get(miniId)?.has(u) || optionUuids.has(u))) return u
    return heldByTail(chunk, miniId) || u || resolveAlternatives(chunk, miniId)
  }

  // …and the case it leaves: a profile that holds BOTH, because its models are not alike. "2 Havocs
  // are equipped with a Havoc autocannon, 2 with a Havoc lascannon", then "any number of Havocs can
  // each have their Havoc autocannon or Havoc lascannon replaced" — each pick gives up whichever of
  // the two that model carries. Static data cannot say which model takes the pick, so the group
  // records both with `alt`: the engine spends a pick on one of them, never on both. Left unread
  // until 2026-10-03, the group gave up nothing and four heavy bolters sat beside the four heavy
  // weapons they replaced (a player's report). The whole phrase must be the alternatives — nothing
  // joined to them by "and" or a comma — and every one of them printed on the profile.
  const resolveHeldAlternatives = (phrase, miniId) => {
    if (/,|\sand\s/i.test(phrase)) return null
    const alts = phrase.split(/\s+or\s+/i).map((s) => s.trim()).filter(Boolean)
    if (alts.length < 2) return null
    const uuids = [...new Set(alts.map((a) => resolveItem(a, miniId)))]
    if (uuids.length !== alts.length || !uuids.every((u) => u && defaultsByMini.get(miniId)?.has(u))) return null
    return uuids
  }

  // A phrase into the set of items it names. Commas always separate; "and" may or may not, since
  // an item can BE called "Cult claws and knife" — so every way of splitting on "and" is tried,
  // fewest pieces first, and the first reading where every piece is a real item wins. Fewest-first
  // is what keeps a compound name whole ("autopistol and cult claws and knife" is two items, not
  // three, and only one of the four readings resolves).
  const resolveConjunction = (part, miniId) => {
    const segs = part.split(/\s+and\s+/i)
    if (segs.length === 1) { const u = resolveChunk(part, miniId); return u ? [u] : null }
    if (segs.length > 5) return null
    const masks = [...Array(1 << (segs.length - 1)).keys()]
      .sort((a, b) => (a.toString(2).split('1').length) - (b.toString(2).split('1').length))
    for (const mask of masks) {
      const chunks = []
      let cur = segs[0]
      for (let i = 0; i < segs.length - 1; i++) {
        if (mask & (1 << i)) { chunks.push(cur); cur = segs[i + 1] } else cur += ` and ${segs[i + 1]}`
      }
      chunks.push(cur)
      const uuids = chunks.map((c) => resolveChunk(c, miniId))
      if (uuids.every(Boolean)) return uuids
    }
    return null
  }

  const resolvePhrase = (phrase, miniId) => {
    const out = []
    for (const part of phrase.split(/\s*,\s*/).map((s) => s.trim()).filter(Boolean)) {
      const got = resolveConjunction(part, miniId)
      if (!got) return null
      out.push(...got)
    }
    return out.length ? out : null
  }

  // What each draft REPLACES, from its own "…'s X[, Y and Z] can be replaced with…" prose.
  // Three shapes of possessive, because appdata writes all three: "model's", "models'" (plural,
  // no second s) and the bare pronoun.
  const REP_RE = /(?:'s|’s|s’|\bhis\b|\bher\b|\btheir\b|\bits\b)\s+((?:\d+\s+)?[a-z][a-z0-9' ’‐‑–,-]*?)\s*(?:can\s+(?:each\s+)?be\s+|be\s+|is\s+|are\s+)?replaced with/i
  // …and once, corpus-wide, with no possessive at all: "Each model can have each shuriken cannon
  // it is equipped with replaced with one of the following".
  const HAVE_RE = /\bhave\s+(?:each|its|their|the|1|one)\s+((?:\d+\s+)?[a-z][a-z0-9' ’‐‑–,-]*?)\s+(?:it is|they are|this model is|that model is)\s+equipped with\s+replaced with/i
  // …and the ACTIVE voice, which appdata writes just as readily: "1 Raptor can replace their
  // Astartes chainsword with 1 mutations". Nothing read that shape until 2026-09-23, so 29 groups
  // across 11 factions declared no `rep`: the weapon stayed on the model beside the one that
  // replaced it, and the stock rule — a model cannot give the same item up twice — had nothing to
  // count, so a ten-Raptor squad offered two mutations with one chainsword left to trade.
  // …and "can each replace ONE OF their macro-scalpels with" (the Talos, 2026-10-07): the item is
  // still named, one copy of it goes — `rc` below.
  const ACTIVE_RE = /\bcan\s+(?:each\s+)?replace\s+(?:one of\s+)?(?:its|their|his|her|the)\s+((?:\d+\s+)?[a-z][a-z0-9' ’‐‑–,-]*?)\s+with\b/i

  // One group, two swaps: appdata files "For every 5 models in this unit: ◦ 1 Raider's boltgun can
  // be replaced with 1 meltagun ◦ 1 Raider's reaver's blade can be replaced with 1 power fist" as a
  // single group of two options, and the reading below takes the FIRST possessive for both — so the
  // power fist replaced the boltgun and ten reaver's blades stayed on the card (a player's report,
  // 2026-10-04). Each bullet is its own allowance over its own weapon, so the group is split into
  // one draft per bullet, each written as the comma form of its head ("For every 5 models in this
  // unit, 1 Raider's boltgun…"), which the scaled and conditional limit readers already know.
  // Only where every bullet names a DIFFERENT weapon given up and every option belongs to exactly
  // one bullet — bullets that all give up the same weapon (Vespid's "If this unit contains 10
  // models: ◦ … neutron blaster with 1 T'au flamer ◦ … neutron blaster with 1 neutron grenade
  // launcher") are one stock and stay one group.
  const SPLIT_HEAD = /^(for every \d+ models? in (?:this|the) unit|if this unit contains \d+(?: or (?:fewer|more))? models?):$/i
  const valueNames = (line, name) => new RegExp(`\\b${reEsc(norm(name))}(?:e?s)?\\b`).test(norm(line.split(VALUE_SPLIT).pop()))
  for (let i = drafts.length - 1; i >= 0; i--) {
    const d = drafts[i]
    const lines = d.text.split('\n').map((l) => l.trim()).filter(Boolean)
    const head = SPLIT_HEAD.exec(lines[0] || '')
    if (!head || lines.length < 3 || !lines.slice(1).every((l) => BULLET_RE.test(l))) continue
    const bullets = lines.slice(1).map((l) => l.replace(BULLET_RE, ''))
    const reps = bullets.map((b) => { const m = b.match(REP_RE) || b.match(ACTIVE_RE); return m && resolvePhrase(m[1], d.miniId) })
    if (!reps.every(Boolean) || new Set(reps.map((r) => r.slice().sort().join('+'))).size !== bullets.length) continue
    const owner = d.opts.map((o) => bullets.filter((b) => valueNames(b, wgItemName.get(o.uuid) || '')).length === 1 ? bullets.findIndex((b) => valueNames(b, wgItemName.get(o.uuid) || '')) : -1)
    if (owner.includes(-1) || bullets.some((_, bi) => !owner.includes(bi))) continue
    const parts = bullets.map((b, bi) => ({ ...d, text: `${head[1]}, ${b}`, opts: d.opts.filter((_, oi) => owner[oi] === bi) }))
    drafts.splice(i, 1, ...parts)
    repStats.split.push(`${enOf(dsById.get(datasheetId)).name}: ${bullets.length} swaps — ${lines[0]}`)
  }

  for (const d of drafts) {
    // A sentence can carry more than one possessive before the swap — "The Celestian Insidiant's
    // Superior's condemnor bolt pistol" — and the first one starts a phrase that names no item.
    // So walk them from the left and keep the first candidate that resolves COMPLETELY; a partial
    // resolve is rejected rather than trimmed, since half a set is a wrong subtraction.
    let from = 0, m, last = null
    while ((m = d.text.slice(from).match(REP_RE))) {
      last = m
      const uuids = resolvePhrase(m[1], d.miniId)
      if (uuids) { d.rep = uuids; repStats.resolved++; break }
      from += d.text.slice(from).indexOf(m[0]) + 2
    }
    for (const RE of [HAVE_RE, ACTIVE_RE]) {
      if (d.rep || !(m = d.text.match(RE))) continue
      last = m
      const uuids = resolvePhrase(m[1], d.miniId)
      if (uuids) { d.rep = uuids; repStats.resolved++ }
    }
    if (!d.rep && last) {
      const uuids = resolveHeldAlternatives(last[1], d.miniId)
      if (uuids) { d.rep = uuids; d.alt = true; repStats.resolved++ }
    }
    if (d.rep) continue
    if (last) repStats.unresolved.push(`${enOf(dsById.get(datasheetId)).name}: ${last[1].trim()}`)
    else if (SWAP_SHAPED.test(d.text)) repStats.noMatch.push(`${enOf(dsById.get(datasheetId)).name}: ${d.text.split('\n')[0].slice(0, 80)}`)
  }

  // What each draft KEEPS LOCKED: "(that model's boltgun cannot be replaced)" — 36 instructions
  // across 18 factions, in three shapes: an addition ("1 Battle Sister equipped with 1 boltgun can
  // be equipped with 1 simulacrum imperialis"), a footnote on an option that hands the item back
  // ("1 cyclone missile launcher and 1 storm bolter*"), and a swap that locks a SECOND item (the
  // Raptors' plasma pistol, after which "these models' Astartes chainswords cannot be replaced").
  // All three mean one thing to the stock rule: the model still carries the item, and no other
  // group may take it. Nothing read the clause until 2026-09-24, so four Raptors with two plasma
  // pistols could still trade all four chainswords. "This weapon cannot be replaced" (the Chimera's
  // new heavy bolter) names no item the model started with and is left alone.
  for (const d of drafts) {
    const keep = []
    for (const m of d.text.matchAll(KEEP_RE)) {
      const uuids = resolvePhrase(m[1], d.miniId)
      if (uuids) keep.push(...uuids)
      else report.keep.unresolved.push(`${enOf(dsById.get(datasheetId)).name}: ${m[1].trim()}`)
    }
    if (keep.length) { d.keep = [...new Set(keep)]; report.keep.resolved++ }
  }

  // What each draft is CONDITIONED on, from "[if …] not equipped with X" / "equipped with X".
  const NOT_EQ_RE = /\bnot equipped with (?:a |an |1 |one )?([a-z][a-z' ’-]*?)(?:[,.]|\s+(?:it|its|can)\b)/i
  const EQ_RE = /\bequipped with (?:a |an |1 |one )?([a-z][a-z' ’-]*?)(?:[,.]|\s+(?:it|its|can)\b)/i
  for (const d of drafts) {
    let negated = true
    let m = d.text.match(NOT_EQ_RE)
    if (!m) { negated = false; m = d.text.match(EQ_RE) }
    if (!m) continue
    const uuid = nameToUuid.get(m[1].trim().toLowerCase())
    if (!uuid) continue

    // Case (a): the item is exactly another group's sole toggle option — mutual exclusion.
    const toggleSibling = drafts.find((s) => s !== d && s.m === d.m && s.opts.length === 1 && s.opts[0].uuid === uuid)
    if (toggleSibling) { d.cond = { sibling: toggleSibling, active: !negated }; continue }

    // Case (b): a sibling group's own `rep` shows it replaces this exact item — this group is
    // only live once that sibling has actually been picked away from its default.
    const repSibling = drafts.find((s) => s !== d && s.m === d.m && s.rep?.includes(uuid))
    if (repSibling) { d.cond = { sibling: repSibling, active: negated }; continue }

    // Case (c): the item is not the model's to start with, and exactly one sibling group hands it
    // out — "If the Helliarch is equipped with 1 splinter pistol, it can be equipped with 1
    // hellglaive", where only the swap for "1 splinter pistol and 1 power weapon" brings a pistol.
    // Unread until 2026-09-30, the hellglaive could be taken with no swap at all.
    if (negated || defaultsByMini.get(d.miniId)?.has(uuid)) continue
    const givers = drafts.filter((s) => s !== d && s.m === d.m && s.opts.some((o) => o.uuid === uuid))
    if (givers.length === 1) d.cond = { sibling: givers[0], active: true }
  }
}

// ---- Wargear bundles -------------------------------------------------------------------
// A `wargear_option` row carries exactly ONE item, but an option is often a PAIR — "1 model's
// twin torturer's tools can be replaced with 1 hexrifle and 1 torturer's tool". The pairing
// exists in appdata only in the group's own instruction prose, so it is parsed from there and
// then VERIFIED against structure: `loadout_choice` enumerates the complete legal loadouts per
// miniature (1145 of 1146 datasheets have them), so every set the prose yields must fit inside
// one of them. Prose alone would be a guess; prose checked against the enumeration is not.
//
// Fail-open throughout — a group whose statements don't all resolve, or whose sets the
// enumeration doesn't back, is emitted exactly as appdata lists it (one item per option), which
// is today's behaviour. Never a guessed pair.
const lcItemsByChoice = new Map()
for (const r of table('loadout_choice_wargear_item')) {
  if (!lcItemsByChoice.has(r.loadoutChoiceId)) lcItemsByChoice.set(r.loadoutChoiceId, [])
  lcItemsByChoice.get(r.loadoutChoiceId).push(r.wargearItemId)
}
const lcSetById = new Map(table('loadout_choice_set').map((s) => [s.id, s]))
const legalLoadouts = new Map() // `${datasheetId}|${miniatureId}` -> [Set(itemUuid), …]
for (const c of table('loadout_choice')) {
  const set = lcSetById.get(c.loadoutChoiceSetId)
  if (!set) continue
  const key = `${set.datasheetId}|${set.miniatureId || ''}`
  if (!legalLoadouts.has(key)) legalLoadouts.set(key, [])
  legalLoadouts.get(key).push(new Set(lcItemsByChoice.get(c.id) || []))
}

// Four markers are in use (◦ 348 lines, ■/▫ 5 each, • 2) — and one list has no marker at all,
// just a head line ending in ':' with an option per line (Grey Knights' Brotherhood Terminator
// Squad). A trailing '*' line is a footnote about the options, not one of them.
const BULLET_RE = /^[◦•■▫]\s*/
const FOOTNOTE_RE = /^\*/
// The value half of a statement. Everything before it names what is GIVEN UP, which repeats item
// names the group also offers ("twin torturer's tools" contains "torturer's tool") — reading the
// whole sentence would pick those up as part of the new loadout.
const VALUE_SPLIT = /\b(?:replaced with|replaced by|equipped with)\b/i
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// Two spellings of one word, differing by a single letter. appdata's instruction prose is typed
// by hand and its item rows are not, so a group can name its own option slightly wrong — the
// Venatari lance is replaced with "1 kinetic destroyer and 1 tarsus buckler", and the item is the
// Tarsis buckler. Exact-only matching reads that sentence as naming ONE item, so the pair is
// emitted as two independent options: the editor lets a model take half of a swap it has to take
// whole, and each half claims the swap's points refund (6 Venatari came out 5 points light).
// Deliberately narrow — one word of the name, five letters or more, everything else identical —
// and the pair it produces still has to sit inside an enumerated legal loadout to be used.
function within1(a, b) {
  if (Math.abs(a.length - b.length) > 1) return false
  let i = 0, j = 0, edits = 0
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) { i++; j++; continue }
    if (++edits > 1) return false
    if (a.length > b.length) i++
    else if (a.length < b.length) j++
    else { i++; j++ }
  }
  return edits + (a.length - i) + (b.length - j) <= 1
}
// A plural is not a misspelling: the prose writes "1 powerblades" for the Powerblades and
// "1 powerblade array" for the Powerblade array, and counting the missing 's' as the one allowed
// difference would let the second bullet claim the first one's item too.
const samePlural = (a, b) => a === b || a.replace(/s$/, '') === b.replace(/s$/, '')
function nearName(words, name) {
  const want = name.split(' ')
  if (words.length !== want.length) return false
  let off = 0
  for (let k = 0; k < want.length; k++) {
    if (samePlural(words[k], want[k])) continue
    if (++off > 1 || want[k].length < 5 || !within1(words[k], want[k])) return false
  }
  return off === 1
}

// appdata types its instruction prose by hand and its item rows separately, so the same weapon is
// spelled with a plain hyphen in one table and a U+2010 one in the other — the Tempestus Command
// Squad's medi-pack bullet reads "1 hot‐shot lasgun, 1 hot‐shot laspistol and 1 medi‐pack" while
// every one of those items is stored with an ASCII hyphen. Character-level only and
// length-preserving, so the match offsets that order the set stay meaningful; `norm` is not usable
// here because it also strips a trailing "(...)", which belongs to names and not to sentences.
// …and one row breaks a hyphenated name across a space ("1 neo- volkite pistol" on the Space
// Marine Lieutenant, found by a player 2026-09-18): a hyphen glued to the letter before it and
// followed by whitespace is that typo, never a spaced dash (" - "), so the space goes.
const flatText = (s) => (s || '').toLowerCase().replace(/[’‘`]/g, "'").replace(/[‐‑–—]/g, '-').replace(/(?<=[a-z])-\s+(?=[a-z])/g, '-')

// The group's own items named in one statement, in order, with the count written in front of
// them ("2 Mortifier flamers"). Longest name first so a name containing another ("master-crafted
// power weapon" vs "power weapon") wins the match.
function itemsNamedIn(rawClause, rawVocab) {
  const clause = flatText(rawClause)
  const vocab = rawVocab.map((v) => ({ uuid: v.uuid, name: flatText(v.name) }))
  const sorted = [...vocab].sort((a, b) => b.name.length - a.name.length)
  const re = new RegExp(`(?:(\\d+)\\s+)?\\b(${sorted.map((v) => reEsc(v.name)).join('|')})(?:e?s)?\\b`, 'gi')
  const out = []
  for (const m of clause.matchAll(re)) {
    const hit = sorted.find((v) => v.name === m[2].toLowerCase())
    if (!hit || out.some(([uuid]) => uuid === hit.uuid)) continue
    out.push([hit.uuid, Number(m[1]) || 1, m.index])
  }
  // Second chance for the options the sentence still hasn't named, one misspelled word apart.
  const toks = [...clause.toLowerCase().matchAll(/[a-z\u2019'-]+|\d+/g)]
  for (const v of sorted) {
    if (out.some(([uuid]) => uuid === v.uuid)) continue
    const len = v.name.split(' ').length
    for (let i = 0; i + len <= toks.length; i++) {
      const win = toks.slice(i, i + len)
      if (!nearName(win.map((t) => t[0]), v.name)) continue
      out.push([v.uuid, Number(i > 0 && /^\d+$/.test(toks[i - 1][0]) ? toks[i - 1][0] : 0) || 1, win[0].index])
      break
    }
  }
  out.sort((a, b) => a[2] - b[2])
  return out.map(([uuid, n]) => [uuid, n])
}

// "Any number of models can each have their Power Fist and Storm Bolter replaced with one of the
// following: 1 Storm Bolter and 1 Chainfist, 1 Storm Bolter and 1 Power Weapon, …" — appdata lists
// the options item by item (the GW app's picker does too), the bundle reader pairs them back up,
// and an item of the given-up pair that no option of the sentence names is left over as an option
// of its own. The app refuses that pick ("Invalid wargear selected", checked in the app
// 2026-10-07): a Deathwatch Terminator holding a power fist and nothing else is no loadout. Dropped
// only in a group that has bundles, only for an item it gives up among two or more, and only when
// the value half of the sentence does not name it.
// The appdata-exceptions registry's wargear-rule typos ("Lascannonss", "can be equipped 1 medi") are
// GW's text errors the datasheets already print corrected. The roster read the raw tables and kept
// them — on the Kratos the typo cost its whole group the "2 of each" counts (2026-10-07). One
// registry, applied here too, so a correction is written once and reaches every generated layer.
const TYPO_FIXES = APPDATA_EXCEPTIONS.filter((e) => e.kind === 'wargear-rule')
function fixWargearTypos(unitName, text) {
  let out = text
  for (const e of TYPO_FIXES) if (e.datasheet === unitName && out.includes(e.from)) out = out.replace(e.from, e.to)
  return out
}

function dropStockRemnants(unitName, drafts, out) {
  for (const d of drafts) {
    if (!(d.rep?.length >= 2) || !d.opts.some((o) => o.items)) continue
    const value = norm(d.text.split('\n')[0].split(VALUE_SPLIT).pop())
    const named = (uuid) => new RegExp(`\\b${reEsc(norm(wgItemName.get(uuid) || ''))}(?:e?s)?\\b`).test(value)
    const keep = d.opts.filter((o) => o.items || !d.rep.includes(o.uuid) || named(o.uuid))
    if (keep.length === d.opts.length) continue
    out.push(`${unitName}: ${d.opts.filter((o) => !keep.includes(o)).map((o) => wgItemName.get(o.uuid)).join(', ')}`)
    d.opts = keep
  }
}

// "Up to 2 Chaos Bikers can each have their combi-bolter replaced with 1 combi-weapon, OR can be
// equipped with one of the following: flamer, meltagun, plasma gun" — one group, two kinds of pick:
// the combi-weapon replaces the combi-bolter, the others are ADDED to it. `rep` is per group, so
// every pick took the combi-bolter away (a player's report f2ba4023, 2026-10-07). The added
// options become bundles that hand the item back — "Flamer + Combi-bolter", the shape the
// Terminators' "cyclone missile launcher and 1 storm bolter" already has — so the ledger keeps the
// model's combi-bolter and the shared cap of two stays one group's. One group game-wide.
const ADD_OR_SWAP = /replaced with (?:1|one) ([^,]+?),? or (?:can )?(?:be )?equipped with one of the following/i
function linkAddOrSwap(unitName, drafts, out) {
  for (const d of drafts) {
    const m = ADD_OR_SWAP.exec(d.text.split('\n')[0])
    if (!m || !d.rep?.length) continue
    const swapped = norm(m[1])
    let changed = 0
    for (const o of d.opts) {
      if (o.items || norm(wgItemName.get(o.uuid) || '') === swapped) continue
      o.items = [[o.uuid, 1], ...d.rep.map((u) => [u, 1])]
      changed++
    }
    if (changed) out.push(`${unitName}: ${changed} option(s) add to, not replace, ${d.rep.map((u) => wgItemName.get(u)).join(', ')}`)
  }
}

function linkWargearBundles(datasheetId, unitName, drafts, stats) {
  for (const d of drafts) {
    const vocab = d.opts.map((o) => ({ uuid: o.uuid, name: (wgItemName.get(o.uuid) || '').toLowerCase() }))
    if (vocab.some((v) => !v.name)) continue

    const lines = d.text.split('\n').map((l) => l.trim()).filter(Boolean)
    const bullets = lines.filter((l) => BULLET_RE.test(l))
    // With a list the statements ARE its entries: the sentence above them only introduces the
    // list ("…replaced with one of the following:") and names the items being given up.
    // Codex: Space Marines (963) also writes the list on the sentence's own line, entries split by
    // commas: "…replaced with one of the following: 1 Boltgun and 1 Storm Shield, 1 Power Weapon and
    // 1 Storm Shield". Each entry opens with its count, which is what tells a comma between entries
    // from one inside a name.
    const inline = lines.length === 1 && lines[0].match(/\bof the following[^:]*:\s*(\d.*)$/i)
    let entries = [d.text]
    if (bullets.length) entries = bullets
    else if (lines.length > 1 && /:$/.test(lines[0])) entries = lines.slice(1).filter((l) => !FOOTNOTE_RE.test(l))
    else if (inline && /,\s*\d/.test(inline[1])) entries = inline[1].split(/,\s*(?=\d)/)
    const stmts = entries.map((l) => l.replace(BULLET_RE, '').split(VALUE_SPLIT).pop())

    const sets = stmts.map((c) => itemsNamedIn(c, vocab))
    if (sets.some((set) => !set.length)) continue        // a statement nothing resolved in

    // A number in front of an item is not always a quantity: "up to 2 seeker missiles" / "up to 4
    // big shootas" state an ALLOWANCE — how many separate picks the model may take, each of one
    // item — and reading them as a set would hand the model six seeker missiles for one pick.
    // 7 groups are in that shape, and they are exactly the 7 whose prose number contradicts every
    // legal loadout in appdata. Membership still stands; only the count is dropped.
    if (/\bup to \d+\b/i.test(d.text.split('\n')[0])) for (const set of sets) for (const pair of set) pair[1] = 1

    if (!sets.some((set) => set.length > 1)) {
      // No bundle, but the prose may still say how many of the one item an option grants ("this
      // model's 2 starcannons can be replaced with 2 bright lances"). 76 groups across 22 factions
      // are in this shape and appdata has no structural count for them — `loadout_choice` records
      // the model's TOTAL of that weapon, not this option's contribution (Baneblade's twin heavy
      // bolter reads 1/3/5), so the prose is the only source. Written onto the existing options
      // in place: unlike a bundle this changes no option's INDEX, so stored picks stay valid and
      // SCHEMA_VERSION doesn't move.
      // The POINTS come with the count. appdata prices the option row per item — a Forgefiend's
      // ectoplasma cannon is 5 whether it is bought as the one that replaces the jaws or as one of
      // the two that replace the Hades autocannons — so an option granting two of them costs 10,
      // which is what the army apps print (a Forgefiend with all three cannons is 155, not 145).
      // The other bundle shape sums its member rows the same way, two lines down.
      const qty = new Map(sets.flat().map(([uuid, n]) => [uuid, n]))
      let counted = false
      for (const o of d.opts) {
        const n = qty.get(o.uuid) || 1
        if (n > 1) { o.items = [[o.uuid, n]]; o.pts = (o.pts || 0) * n; counted = true }
      }
      if (counted) stats.quantified++
      continue
    }
    // Every option appdata lists must be accounted for by the prose, or the prose is describing
    // something other than this group's option list and can't be trusted to replace it.
    // The one exception is the item being given up when appdata also lists it among the group's
    // options ("…have their Power Fist and Storm Bolter replaced with one of the following:
    // …" — Deathwatch Terminators, 963): it is named in the head of the sentence, never among the
    // entries, so it does not fail this check. It was read as a "keep it" choice and left as an
    // option of its own; the GW app refuses that pick, and dropStockRemnants removes it (2026-10-07).
    const claimed = new Set(sets.flat().map(([uuid]) => uuid))
    const head = flatText(d.text.split(VALUE_SPLIT)[0])
    const kept = d.opts.filter((o) => !claimed.has(o.uuid) && head.includes(flatText(wgItemName.get(o.uuid))))
    if (claimed.size + kept.length !== new Set(vocab.map((v) => v.uuid)).size) {
      const unnamed = vocab.filter((v) => !claimed.has(v.uuid)).map((v) => v.name)
      stats.unclaimed.push(`${unitName}: ${stmts[0].trim()}${unnamed.length ? ` (never named: ${unnamed.join(', ')})` : ''}`)
      continue
    }

    const legal = legalLoadouts.get(`${datasheetId}|${d.miniId || ''}`) || []
    const backed = sets.every((set) => set.length < 2
      || legal.some((choice) => set.every(([uuid]) => choice.has(uuid))))
    if (!backed) { stats.unbacked.push(`${unitName}: ${stmts[0].trim()}`); continue }

    const byUuid = new Map(d.opts.map((o) => [o.uuid, o]))
    d.opts = [...kept, ...sets.map((set) => {
      const members = set.map(([uuid]) => byUuid.get(uuid)).filter(Boolean)
      return {
        uuid: set[0][0],
        pts: members.reduce((n, o) => n + (o.pts || 0), 0),
        def: members.length && members.every((o) => o.def) ? 1 : 0,
        items: set,
      }
    })]
    stats.rewritten++
  }
}

// ---- One bullet, recorded once per miniature -------------------------------------------
// A datasheet's wargear bullet that talks about the UNIT ("Any number of models can each have
// their hallowed mace replaced…", "For every 5 models in this unit, 1 model's…") is stored by
// appdata once per MINIATURE profile — as a checkbox on the single leader model and a stepper on
// the rank-and-file one — because its option groups hang off miniatures, not off the datasheet.
// Rendered straight, that is the same instruction twice (reported on Drukhari Wracks), and worse
// than cosmetic: each copy carries its own allowance, so the choice can be taken twice.
//
// The two are folded into one unit-wide group. Matching on the exact instruction TEXT plus the
// exact option sets is what makes this safe: a leader with a genuinely separate allowance is
// always worded differently ("The Sister Superior's boltgun…"), so it never collides. 99 pairs
// across 50 units, and in every one of them the two copies agree on what they replace.
function mergeMiniatureDuplicates(drafts, stats) {
  const byKey = new Map()
  for (const d of drafts) {
    // Whitespace-insensitive: the two copies of one bullet are typed twice into appdata and do
    // differ by a stray trailing space (Deathwatch Terminator Squad), which is not a difference
    // in meaning. Line ORDER still counts — a reordered option list is a different statement.
    const k = `${d.text.replace(/\s+/g, ' ').trim()}||${d.opts.map((o) => (o.items ? o.items.map(([u]) => u) : [o.uuid]).slice().sort().join('+')).sort().join('/')}`
    if (!byKey.has(k)) byKey.set(k, [])
    byKey.get(k).push(d)
  }
  const dropped = new Map() // dropped draft -> the one that survives
  for (const list of byKey.values()) {
    if (list.length < 2) continue
    // Two copies on the SAME miniature would be two real allowances, not one bullet recorded
    // twice — leave those alone.
    if (new Set(list.map((d) => d.m)).size !== list.length) continue
    const keep = list.find((d) => d.in === 'stepper') || list[0]
    keep.all = 1 // unit-wide: no miniature owns it, and the count runs over the whole squad
    for (const d of list) if (d !== keep) dropped.set(d, keep)
    stats.merged += list.length - 1
  }
  if (!dropped.size) return drafts
  // A sibling condition points at a draft object; if that object is one of the dropped copies,
  // it has to follow the survivor or the dependent group would never go live.
  for (const d of drafts) if (d.cond && dropped.has(d.cond.sibling)) d.cond.sibling = dropped.get(d.cond.sibling)
  return drafts.filter((d) => !dropped.has(d))
}

// ---- Per-group pick limits -------------------------------------------------------------
// How MANY models in a squad may take an option is not in `wargear_option_group` either — it is
// its own family: `limited_wargear_choice_set` (per datasheet, sometimes per miniature) holds
// the same choices again, and `wargear_limit` gives the cap as a step table keyed by unit size
// ({modelCount: 5, choiceLimit: 1}, {modelCount: 10, choiceLimit: 2} = "for every 5 models,
// 1 model"). Without it the editor guesses from prose — "Up to 4 Dominions can each…" reads as
// no cap at all, "For every 5 models, up to 2 Seraphim" as one — and a wrong cap here is not
// cosmetic: a paid option's points are multiplied by the count, so it misprices the army.
//
// Matched by ITEM SETS, not by name or order: a limited set is attached to a group only when its
// choices are exactly that group's options (and its miniature, when it names one) and no other
// group on the unit is an equally good match. Sets that enumerate combinations ACROSS groups —
// 82 of 345, the Battle Sisters "2 models may take one of these specials/heavies" pools — match
// nothing and are left alone, exactly like every other fail-open path here.
const lwcItems = new Map()
for (const r of table('limited_wargear_choice_wargear_item')) {
  if (!lwcItems.has(r.limitedWargearChoiceId)) lwcItems.set(r.limitedWargearChoiceId, [])
  lwcItems.get(r.limitedWargearChoiceId).push(r)
}
const lwcBySet = new Map()
for (const c of table('limited_wargear_choice')) {
  if (!lwcBySet.has(c.limitedWargearChoiceSetId)) lwcBySet.set(c.limitedWargearChoiceSetId, [])
  lwcBySet.get(c.limitedWargearChoiceSetId).push(c)
}
const wgLimitsBySet = new Map()
for (const l of table('wargear_limit')) {
  if (!wgLimitsBySet.has(l.limitedWargearChoiceSetId)) wgLimitsBySet.set(l.limitedWargearChoiceSetId, [])
  wgLimitsBySet.get(l.limitedWargearChoiceSetId).push(l)
}
const limitedSetsByDs = new Map()
for (const s of table('limited_wargear_choice_set')) {
  if (!limitedSetsByDs.has(s.datasheetId)) limitedSetsByDs.set(s.datasheetId, [])
  limitedSetsByDs.get(s.datasheetId).push(s)
}

// An option / choice as a comparable key: its item uuids, order-independent, counts ignored
// (the two families disagree on quantity often enough that requiring it would lose real matches;
// the count is taken FROM the limited set once matched).
const itemsKey = (uuids) => [...new Set(uuids)].sort().join('|')
const groupKey = (opts) => opts.map((o) => itemsKey((o.items || [[o.uuid]]).map(([u]) => u))).sort().join('#')
const optUuids = (o) => new Set((o.items || [[o.uuid]]).map(([u]) => u))

// One-to-one assignment of every choice to a DISTINCT option that contains it. Kuhn's algorithm
// rather than a greedy pass: two choices sharing their only candidate is exactly the shape a
// greedy gets wrong, and getting it wrong here means handing a group a cap that isn't its own.
function coversOneToOne(choices, opts) {
  if (choices.length !== opts.length) return false
  const sets = opts.map(optUuids)
  const takenBy = new Array(sets.length).fill(-1)
  const assign = (ci, seen) => {
    for (let oi = 0; oi < sets.length; oi++) {
      if (seen.has(oi) || !choices[ci].every((u) => sets[oi].has(u))) continue
      seen.add(oi)
      if (takenBy[oi] === -1 || assign(takenBy[oi], seen)) { takenBy[oi] = ci; return true }
    }
    return false
  }
  return choices.every((_, ci) => assign(ci, new Set()))
}

// The allowance the instruction states, or null when it doesn't state one plainly. Deliberately
// narrow: anything scaled ("for every 5 models") or conditional ("if this unit contains 10
// models") is left to the step table, which expresses those properly; this only reads the flat
// "up to 2 Dominions…" / "1 model's boltgun…" forms, which is where a wrong match would show up.
const WORD_NUM = { one: 1, two: 2, three: 3, four: 4, five: 5 }
// The scaled form proseAllowance refuses, read into `lim`'s own step-table shape further down.
// The comma is load-bearing: "For every 5 models in this unit:" followed by bullets is a list of
// SEPARATE allowances, not one shared number.
const SCALED_ALLOWANCE = /for every (\d+) models? in (?:this|the) unit,\s*(?:up to )?(\d+|one|two|three|four|five)\b/i
function proseAllowance(text, optCount = 0) {
  const t = text.split('\n')[0]
  if (/\bfor every \d+\b|\bif this unit contains\b|\bany number of\b/i.test(t)) return null
  const up = t.match(/\bup to (\d+|one|two|three|four|five)\b/i)
  if (up) return WORD_NUM[up[1].toLowerCase()] || Number(up[1])
  const lead = t.match(/^\s*(\d+|one|two|three|four|five)\b/i)
  if (lead) return WORD_NUM[lead[1].toLowerCase()] || Number(lead[1])
  // "…can be equipped with ANY of the following:" — every option is on offer at once, one of
  // each, and the sentence names no number because the list itself is the number. Without this
  // the group had no cap and read as a one-of: a Battlewagon could not take both a grabbin' klaw
  // and a wreckin' ball in the editor, and a list that did was reported illegal on import.
  // "Two DIFFERENT weapons from the following list" (a Devastator/Tactical Sergeant giving up
  // both his bolt pistol and boltgun) is the same shape with the number spelled out.
  if (/\bany of the following\b/i.test(t) && optCount > 1) return optCount
  const diff = t.match(/\b(one|two|three|four|five) different weapons\b/i)
  if (diff) return WORD_NUM[diff[1].toLowerCase()]
  return null
}
// Wordings that let the model take several of the group but never the same one twice.
// ("cannot take duplicates" is often a footnote below the instruction, so it is read from the
// whole text; the other two are statements of the allowance itself and only count in it.)
// ("duplicates are not allowed" is the parenthetical form, six groups; `can take duplicates` is
// the OPPOSITE statement and must not be read as one of these.)
// "You cannot select the same option more than once" is the Raptors' spelling of it (2026-09-19,
// a player took two meltaguns from a group that allows one of each).
const proseNoDuplicates = (text) =>
  /cannot take duplicates|duplicates are not allowed|cannot select the same option more than once/i.test(text) ||
  /\bany of the following\b|\bdifferent weapons\b/i.test(text.split('\n')[0])

// The allowance that only exists at a unit size: "If this unit contains 10 models, up to 2
// additional Raptors can each…", "If this unit contains 10 models, 1 Corsair Voidscarred's power
// sword can be replaced…", and the block form over its own bullets —
//
//   If this unit contains 10 models:
//   ◦ 1 Vespid Stingwing can replace its neutron blaster with 1 T'au flamer.
//   ◦ 1 Vespid Stingwing can replace its neutron blaster with 1 neutron grenade launcher.
//
// where each bullet is a separate allowance (one model each, three models in all), and the
// Troupe's two-block form ("9 or fewer models: up to two … / 10 or more models: up to four …").
// proseAllowance refuses all of these on purpose (the number is conditional), and appdata's set
// either does not exist or matches two identical groups — so these fell through to the editor,
// which drew the multi-option ones as a one-of radio and offered every one of them at any size:
// a 10-model Raptor squad could take one extra special weapon where the datasheet allows two, a
// 5-model one could take it at all. Returns `lim` rows — `[threshold, picks, dup?]` — or null
// where the text is not this shape or a bullet cannot be read; `optCount` tells the block form
// whether its bullets ARE the options (then each bullet's number caps its own option, which the
// dup slot expresses exactly when they all say the same number) or merely restate them.
const COND_HEAD = /^if this unit contains (\d+)( or fewer| or more)? models?(,|:)\s*(.*)$/i
function proseConditionalAllowance(text, optCount = 0) {
  const blocks = text.split(/\n\s*\n/)
  const rows = []
  for (const block of blocks) {
    const lines = block.split('\n').map((l) => l.trim()).filter(Boolean)
    const head = lines[0] && COND_HEAD.exec(lines[0])
    if (!head) return null
    const at = head[2]?.trim() === 'or fewer' ? 0 : Number(head[1])
    const dupSaid = proseNoDuplicates(block) ? 1 : 0
    if (head[3] === ',') {
      // One sentence: "up to 2 additional X can each…", "1 X's Y can be replaced…". The lines
      // after it, if any, are the options and say nothing about the allowance.
      const n = proseAllowance(head[4].replace(/\badditional\b/i, ''), optCount)
      if (n == null) return null
      rows.push(dupSaid ? [at, n, dupSaid] : [at, n])
      continue
    }
    // A colon: the bullets under it are the allowances, one number each.
    const bullets = lines.slice(1).map((l) => l.replace(/^[◦▪•*-]\s*/, ''))
    if (!bullets.length) return null
    const each = bullets.map((b) => proseAllowance(b))
    if (each.some((n) => n == null)) return null
    const total = each.reduce((a, b) => a + b, 0)
    const same = each.every((n) => n === each[0])
    if (optCount === bullets.length && same) rows.push([at, total, each[0]])
    else if (dupSaid) rows.push([at, total, 1])
    else rows.push([at, total])
  }
  if (!rows.length) return null
  rows.sort((a, b) => a[0] - b[0])
  // Two blocks cannot claim the same threshold, and every row must state a real allowance.
  if (rows.some((r, i) => r[1] < 1 || (i && r[0] === rows[i - 1][0]))) return null
  return rows
}

function linkWargearLimits(datasheetId, unitName, miniIdx, drafts, stats) {
  const sets = limitedSetsByDs.get(datasheetId) || []
  if (!sets.length) return
  for (const set of sets) {
    const choices = (lwcBySet.get(set.id) || []).map((c) => lwcItems.get(c.id) || [])
    if (!choices.length) continue
    const wantKey = choices.map((its) => itemsKey(its.map((i) => i.wargearItemId))).sort().join('#')
    const wantMini = set.miniatureId == null ? null : miniIdx.get(set.miniatureId)

    const onMini = (d) => wantMini == null || d.m === wantMini
    let hits = drafts.filter((d) => groupKey(d.opts) === wantKey && onMini(d))
    // A set and a group can describe the same picks and still not key the same, because the two
    // families disagree about BUNDLES: the Legionaries' special-weapon group offers "1 plasma
    // pistol and 1 Astartes chainsword" as one pick (the prose says so, and it is why appdata's
    // ten option rows became nine options), while the set records that pick as the plasma pistol
    // alone. Keying on equality lost the cap outright and the group fell back to one pick for the
    // whole unit — a 10-model squad could take one special weapon where the datasheet allows two.
    // So a second pass matches each choice to an option that CONTAINS it, one-to-one, and runs
    // only where the exact pass found nothing: an already-ambiguous set stays ambiguous.
    if (!hits.length) {
      const wantItems = choices.map((its) => its.map((i) => i.wargearItemId))
      hits = drafts.filter((d) => onMini(d) && coversOneToOne(wantItems, d.opts))
      if (hits.length === 1) stats.bundled++
    }
    // Several identical groups (the same choice repeated per miniature) — no way to tell which
    // one the set means, so neither gets a cap it might not have.
    if (hits.length !== 1) { stats[hits.length ? 'ambiguous' : 'unmatched']++; continue }
    const d = hits[0]
    if (d.lim) { stats.ambiguous++; continue }

    // `[modelCount, choiceLimit]`, plus the duplicate cap as a third slot when there is one —
    // it belongs to the threshold, not to the set (Cadian Shock Troops: 2 picks / 1 of a kind at
    // 10 models, 4 picks / 2 of a kind at 20), so hoisting it to the group would misread half
    // the brackets.
    // appdata leaves `duplicateLimit` empty on sets whose own instruction states the rule in
    // words ("…one of the following (duplicates are not allowed)"), so the prose fills it in where
    // the table says nothing — otherwise a 10-model squad allowed two picks could take the same
    // weapon twice. Never over a duplicate cap appdata itself gave.
    const dupSaid = proseNoDuplicates(d.text) ? 1 : 0
    const limits = (wgLimitsBySet.get(set.id) || [])
      .map((l) => (l.duplicateLimit > 0 || dupSaid
        ? [l.modelCount || 0, l.choiceLimit, l.duplicateLimit > 0 ? l.duplicateLimit : dupSaid]
        : [l.modelCount || 0, l.choiceLimit]))
      .filter(([, n]) => n > 0)
      .sort((a, b) => a[0] - b[0])
    if (!limits.length) continue
    // Cross-check against the instruction. Two GW sources describing the same allowance can
    // disagree, and a set matches by ITEMS — so a set that really describes a different, wider
    // allowance over the same weapons would attach here and quietly hand out extra models
    // (Blood Angels' Death Company Marines with Jump Packs: prose "1 model's Astartes chainsword
    // can be replaced with one of the following", limits 2/3). Where the prose states a plain
    // allowance, it has to agree, or the group keeps the no-cap behaviour — which for a
    // one-of group IS "one model", the conservative reading.
    const said = proseAllowance(d.text)
    if (said != null && said !== limits[0][1]) { stats.conflict.push(`${unitName}: prose ${said} vs appdata ${limits[0][1]} — ${d.text.split('\n')[0].slice(0, 70)}`); continue }
    d.lim = limits

    // The quantity per option lives here too — "2 inferno pistols", where wargear_option knows
    // only the item. Applied only where the option doesn't already carry its own count.
    const byKey = new Map(choices.map((its) => [itemsKey(its.map((i) => i.wargearItemId)), its]))
    for (const o of d.opts) {
      const its = byKey.get(itemsKey((o.items || [[o.uuid]]).map(([u]) => u)))
      if (!its || its.every((i) => (i.count || 1) === 1)) continue
      o.items = its.map((i) => [i.wargearItemId, i.count || 1])
      stats.counted++
    }
    stats.limited++
  }
}

// ── What a unit costs ─────────────────────────────────────────────────────────────────────────
// The BRACKETS are appdata's (model counts + the per-miniature composition behind them); the
// PRICE of each is the Munitorum Field Manual's, read from the same scraped modules the datasheet
// pages already use (src/data/mfm/*.js — see scrape-mfm.py / sync-mfm-points.mjs).
//
// Not a preference between two equal sources: appdata records SEVERAL price rows per datasheet —
// one per Chapter (Blood Angels pay 80 for an Assault Intercessor Squad where the Codex price is
// 75), and for Imperial Agents one per allied context (Draxus 75 in her own army, 110 as an ally).
// Mapped straight onto `sizes` those became unit-SIZE choices: two identical "5 models" pills at
// different prices, the first one arbitrarily pre-selected, and the roster quoting a different
// number than the unit's own datasheet page. Pricing every bracket from one source collapses them
// back into one pill (the fold below does it, once the only thing that differed is gone) and puts
// the builder back in step with the rest of the app.
//
// A copy-tax tier ("1st-2nd" / "3rd+") is a NOTE on an MFM row, not a bracket of its own: the base
// price is the first tier and the surcharge stays `datasheet_points_step` (appdata's own field),
// which this cross-checks and reports on.
// The MFM prints some of a faction's OWN datasheets in a separate section — Aeldari's Harlequins
// and Ynnari, the Chaos legion sections, Space Marines' named-character chapters — and those are
// units of this army like any other. Two kinds of subfaction are not: a Chapter's "Space Marines"
// section (the shared Codex pool, folded in at load time and priced by `unitPoints`) and Imperial
// Agents' "(allied)" list, which is what those units cost in SOMEBODY ELSE'S army. The faction's
// own list is appended last so it wins wherever a name appears in both. The MFM's Legends
// section (`legends`, behind the site's "Show Legends" toggle) prices the `legends: true`
// sheets — appdata's for Orks, the Faction-Pack ones elsewhere — and goes in first, so a name
// the Codex list also carries keeps the Codex price.
function ownMfmUnits(mfmFaction) {
  const extra = (mfmFaction?.subfactions || [])
    .filter((s) => norm(s.name) !== 'space marines' && !/allied/i.test(s.name))
    .flatMap((s) => s.units || [])
  return [...(mfmFaction?.legends || []), ...extra, ...(mfmFaction?.units || [])]
}

function mfmPrices(mfmUnits) {
  const byName = new Map()
  for (const u of mfmUnits || []) {
    const byModels = new Map()
    for (const o of u.options || []) {
      const n = Number(o.models)
      if (!Number.isFinite(n) || !(o.points > 0)) continue
      if (!byModels.has(n)) byModels.set(n, [])
      byModels.get(n).push(o)
    }
    if (!byModels.size) continue
    const prices = new Map()
    for (const [n, rows] of byModels) {
      const first = rows.find((r) => !r.note) || rows.find((r) => /^1st/i.test(r.note || '')) || rows[0]
      const later = rows.filter((r) => r !== first).map((r) => Number(r.points))
      prices.set(n, { base: Number(first.points), step: later.length ? Math.min(...later) - Number(first.points) : null })
    }
    byName.set(normApost(u.name), prices)
  }
  return byName
}

// One bracket per unit SIZE, priced by the MFM.
//
// appdata lists a datasheet's price rows as several parallel lists — one per Chapter, or per allied
// context — so the same size appears more than once at different prices. Those are not sizes, and
// emitting them as such is what put two identical "5 models" pills, at 80 and 75 points, in the
// editor. Rows are therefore grouped by what actually makes a bracket distinct (model range +
// per-miniature composition — Corsair Voidscarred really does have three different 7-model builds)
// and each group collapses to ONE bracket.
//
// Which of the parallel lists is this army's own? Where the MFM prices that size it says so
// outright. Where it doesn't (Imperial Agents' "7-11 models", which the MFM covers with a 6- and a
// 12-model row) the row's RANK decides: the lists are parallel, so the position that won on every
// priced size wins here too. Nothing is interpolated — a size the MFM doesn't price keeps an
// appdata number, just the one from the right list.
function pickPrices(rows, priced, name, mfmSteps) {
  const groups = new Map()
  for (const r of rows) {
    const k = `${r.per.join('-')}|${JSON.stringify(r.comp || null)}`
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(r)
  }
  const mfmOf = (r) => (priced ? priced.get(r.per[1]) ?? priced.get(r.per[0]) : null)

  const tally = new Map()
  for (const list of groups.values()) {
    const mfm = mfmOf(list[0])
    const at = mfm ? list.findIndex((r) => r.pts === mfm.base) : -1
    if (at >= 0) tally.set(at, (tally.get(at) || 0) + 1)
  }
  let rank = 0
  let best = 0
  for (const [at, n] of [...tally].sort((a, b) => a[0] - b[0])) if (n > best) { best = n; rank = at }

  const out = []
  for (const list of groups.values()) {
    const mfm = mfmOf(list[0])
    const chosen = (mfm && list.find((r) => r.pts === mfm.base)) || list[Math.min(rank, list.length - 1)]
    if (mfm) {
      chosen.pts = mfm.base
      if (mfm.step != null) mfmSteps.push(mfm.step)
    } else if (list.length > 1) {
      report.price.noBracket.push(`${name} ${list[0].per.join('-')}: kept ${chosen.pts} of ${list.map((r) => r.pts).join('/')}`)
    }
    if (chosen.pts !== list[0].pts) report.price.repriced++
    report.price.collapsed += list.length - 1
    if (list.some((r) => r.default)) chosen.default = 1
    out.push(chosen)
  }
  return out
}

// ── Allies ────────────────────────────────────────────────────────────────────────────────────
// An army can include units that do NOT have its Faction keyword: Agents of the Imperium in any
// IMPERIUM army, a Knight or a Titan, Daemons in a Chaos Space Marines army, Brood Brothers in a
// Genestealer Cults one, Harlequins in an Aeldari one. appdata models all 21 of those contexts
// structurally (`allied_faction` + six satellite tables), so nothing here is hand-written: which
// armies may take the group, which datasheets it offers, how many of each keyword per battle size,
// what the combined points may reach, and which Detachment (if any) unlocks it.
//
// Two shapes come out of that, and the difference matters to the loader:
//  - CROSS-FACTION — the units live in another faction's bundle (Draxus is in imperial-agents.js).
//    Their ids are emitted NAMESPACED, `<source slug>:<unit id>`, because a bare id is only unique
//    within a bundle: Astra Militarum and Imperial Agents each have their own `ministorum-priest`
//    datasheet, and an AM army can ally the Agents one. The prefix is also how the runtime knows
//    which bundle to load and which faction's datasheet page a unit links to. One group can even
//    mix sources — the Chaos Space Marines' cult-legion group takes one datasheet from each of
//    Emperor's Children, Death Guard, Thousand Sons and World Eaters — so the source is per id.
//  - IN-BUNDLE (appdata's `isSiblingFaction`, plus Drukhari's Harlequins) — the units are already
//    in this faction's own file (Blood Legions are in world-eaters.js, Harlequins in aeldari.js).
//    Ids stay bare; the group exists only to carry the limits that apply to them.
//
// What the group does NOT carry is the warlord/enhancement ban, because it isn't uniform: the
// cross-faction rules all end "None of these models can be your WARLORD, and they cannot be given
// Enhancements", while Aeldari's Harlequins have no such sentence and Ynnari units are exactly
// what the Devoted of Ynnead Detachment's Enhancements are for. `canTakeEnhancements` is appdata's
// own field and is emitted as `enh`; the rest is the runtime's rule (see rosterValidation.js).
const alliedRows = table('allied_faction')
const fkParentOf = new Map(table('faction_keyword').map((k) => [k.id, k.parentFactionKeywordId]))
const bsSlug = new Map(table('battle_size').map((b) => [b.id, slugify(enOf(b).name)]))
const groupBy = (rows, key) => {
  const m = new Map()
  for (const r of rows) {
    if (!m.has(r[key])) m.set(r[key], [])
    m.get(r[key]).push(r)
  }
  return m
}
const alliedTakers = groupBy(table('faction_keyword_allied_faction'), 'alliedFactionId')
const alliedParents = groupBy(table('allied_faction_parent_faction_keyword'), 'alliedFactionId')
const alliedSheets = groupBy(table('allied_faction_datasheet'), 'alliedFactionId')
const alliedKeywords = groupBy(table('allied_faction_keyword'), 'alliedFactionId')
// "For each INQUISITOR unit you include in your army, you can include one INQUISITORIAL AGENTS unit
// that does not count towards the number of RETINUE units" — appdata records it as a slotless
// group on one keyword cap: every unit carrying ALL the donor keywords frees one unit carrying the
// receiver keywords from that cap. Unread until 2026-10-03, when auditing Agents of the Imperium:
// a legal Inquisitor + Inquisitorial Agents + two Retinue units read as over the Retinue limit.
const slotlessByCap = groupBy(table('allied_faction_keyword_slotless_keyword_group'), 'alliedFactionKeywordId')
const slotlessDonors = groupBy(table('allied_faction_keyword_slotless_keyword_group_donor_keyword'), 'alliedFactionKeywordSlotlessKeywordGroupId')
const slotlessReceivers = groupBy(table('allied_faction_keyword_slotless_keyword_group_receiver_keyword'), 'alliedFactionKeywordSlotlessKeywordGroupId')
const alliedPoints = groupBy(table('allied_faction_points_limit'), 'alliedFactionId')
const alliedDets = groupBy(table('allied_faction_required_detachment'), 'alliedFactionId')

// datasheet uuid -> [our faction slug, our unit id]. sourceIds.json is the same map the datasheet
// pages are keyed by, and a datasheet appears under exactly one faction there (1039 of them, no
// duplicates), so this resolves an allied datasheet to the bundle that actually holds it.
const unitBySheet = new Map()
{
  const all = loadJson(path.join(ROOT, 'src/data/sourceIds.json')) || {}
  for (const [slug, entries] of Object.entries(all)) {
    for (const [k, uuid] of Object.entries(entries)) if (k.startsWith('ds:')) unitBySheet.set(uuid, [slug, k.slice(3)])
  }
}

// Is this faction (or a faction it is a chapter/subfaction of) allowed to take the group? Takers
// are recorded at whatever level the rule is written — "Adeptus Astartes" for the Codex armies,
// "Dark Angels" where a Chapter is named — so walk up the keyword's parents.
function fkChain(id) {
  const out = []
  for (let cur = id, n = 0; cur && n < 8; cur = fkParentOf.get(cur), n++) out.push(cur)
  return out
}

// What the group's units cost as ALLIES. The MFM prints a second, dearer list for Agents of the
// Imperium ("Agents of the Imperium (allied)": Draxus 75 in her own army, 110 in somebody else's)
// and ownMfmUnits deliberately ignores it when pricing that faction's own bundle. Same mechanism
// as a Chapter's `unitPoints`: model count -> points, emitted only where it differs, applied by
// loadRosterFaction to a `sizes` array built elsewhere.
const alliedPriceCache = new Map()
async function alliedPricesOf(slug) {
  if (alliedPriceCache.has(slug)) return alliedPriceCache.get(slug)
  const mfm = (await loadModule(path.join(ROOT, 'src/data/mfm', `${slug}.js`)))?.default
  const sub = (mfm?.subfactions || []).find((s) => /allied/i.test(s.name))
  let out = null
  if (sub) {
    const allied = mfmPrices(sub.units)
    const own = mfmPrices(ownMfmUnits(mfm))
    out = new Map()
    for (const [name, prices] of allied) {
      const diff = {}
      for (const [models, p] of prices) if (own.get(name)?.get(models)?.base !== p.base) diff[models] = p.base
      out.set(name, { diff, priced: prices })
    }
  }
  alliedPriceCache.set(slug, out)
  return out
}

// The allied price of a size the MFM's allied list does not print. appdata keeps a datasheet's
// allied prices as a parallel list of compositions marked with a grouping keyword (IMPERIUM, for
// Agents of the Imperium in another Imperium army), and the MFM prints only some of its sizes:
// Inquisitorial Agents are 6 and 12 models there, while appdata also prices 7-11 — 100 in the
// Agents' own army, 120 as allies. Without this the allied 7-11 kept the native 100 (found on
// 2026-10-03, auditing Agents of the Imperium). Same rule as pickPrices: the MFM wins wherever it
// speaks, and appdata answers only where it is silent — keyed by the size's largest model count,
// which is what the client's repriced() reads first.
function alliedCompositionPrices(datasheetId, priced, native) {
  const extra = {}
  for (const c of compByDs.get(datasheetId) || []) {
    if (!c.referenceGroupingKeywordId || !(c.points > 0)) continue
    const rows = compMinis.get(c.id) || []
    if (!rows.length) continue
    const min = rows.reduce((a, r) => a + r.min, 0)
    const max = rows.reduce((a, r) => a + r.max, 0)
    if (priced?.has(min) || priced?.has(max)) continue
    const own = native?.sizes?.find((z) => z.per[0] === min && z.per[1] === max)
    if (own && own.pts !== c.points) extra[max] = c.points
  }
  return extra
}

async function alliesFor(factionKeywordId, ownUnitIds, slug) {
  const chain = fkChain(factionKeywordId)
  const mine = new Map(chain.map((id, i) => [id, i]))     // keyword -> how far up the chain it is
  const out = []
  for (const af of alliedRows) {
    const takers = (alliedTakers.get(af.id) || []).filter((t) => mine.has(t.factionKeywordId))
    if (!takers.length) continue
    // How specifically this army is named: 0 when the rule names the faction itself, higher when it
    // names a parent. Deathwatch is offered the Agents of the Imperium list twice — the general one
    // (written for ADEPTUS ASTARTES) and its own, which is that list minus the five Deathwatch
    // datasheets its own bundle already has. Both are real rows; the one written FOR this army is
    // the one that applies, and emitting both would also print the group twice on screen.
    const distance = Math.min(...takers.map((t) => mine.get(t.factionKeywordId)))
    const names = (alliedParents.get(af.id) || []).map((p) => fkwName.get(p.factionKeywordId)).filter(Boolean)
    const group = { key: slugify(names.join(' ')), name: names.join(' / ') }
    const ids = []
    const missing = []
    const up = {}
    for (const row of alliedSheets.get(af.id) || []) {
      const found = unitBySheet.get(row.datasheetId)
      if (!found) { missing.push(enOf(dsById.get(row.datasheetId)).name || row.datasheetId); continue }
      const [srcSlug, unitId] = found
      if (srcSlug === slug) {
        // Already in this bundle (a sibling faction, or a Chapter's own copy) — bare id.
        if (ownUnitIds.has(unitId)) ids.push(unitId)
        else missing.push(`${unitId} (not a buildable entry)`)
        continue
      }
      const id = `${srcSlug}:${unitId}`
      ids.push(id)
      const prices = await alliedPricesOf(srcSlug)
      const hit = prices?.get(normApost(enOf(dsById.get(row.datasheetId)).name || ''))
      const native = (await loadModule(path.join(ROOT, 'src/data/roster', `${srcSlug}.js`)))?.default?.units?.find((u) => u.id === unitId)
      const diff = { ...(hit?.diff || {}), ...(hit ? alliedCompositionPrices(row.datasheetId, hit.priced, native) : {}) }
      if (Object.keys(diff).length) up[id] = diff
    }
    if (!ids.length) { report.allies.empty.push(`${slug}: ${group.name}`); continue }
    group.ids = ids.sort()
    // Keyword caps ("up to 3 ARMIGER models"), per battle size. `mutex` is appdata's
    // isMutuallyExclusiveKeywordLimit — the Knight/Titan rule reads "either one TITANIC model OR
    // up to three ARMIGER models", so the caps are alternatives, not a budget each.
    const lim = {}
    for (const r of alliedKeywords.get(af.id) || []) {
      const kw = kwName.get(r.keywordId)
      const size = bsSlug.get(r.battleSizeId)
      if (!kw || !size) continue
      lim[kw] = lim[kw] || {}
      lim[kw][size] = r.limitCount
    }
    if (Object.keys(lim).length) group.lim = lim
    // `free`: [{ kw, donor: [keywords], recv: [keywords] }] — see slotlessByCap. One per rule, not per
    // battle size: appdata repeats each group on every size's row of the same cap.
    const free = new Map()
    for (const r of alliedKeywords.get(af.id) || []) {
      for (const g of slotlessByCap.get(r.id) || []) {
        const donor = (slotlessDonors.get(g.id) || []).map((d) => kwName.get(d.keywordId)).filter(Boolean).sort()
        const recv = (slotlessReceivers.get(g.id) || []).map((d) => kwName.get(d.keywordId)).filter(Boolean).sort()
        const kw = kwName.get(r.keywordId)
        if (kw && donor.length && recv.length) free.set(`${kw}|${donor}|${recv}`, { kw, donor, recv })
      }
    }
    if (free.size) group.free = [...free.values()]
    if (af.isMutuallyExclusiveKeywordLimit) group.mutex = 1
    const pts = {}
    for (const r of alliedPoints.get(af.id) || []) if (bsSlug.get(r.battleSizeId)) pts[bsSlug.get(r.battleSizeId)] = r.pointsLimit
    if (Object.keys(pts).length) group.pts = pts
    const dets = (alliedDets.get(af.id) || []).map((r) => enOf(detById.get(r.detachmentId)).name).filter(Boolean).sort()
    if (dets.length) group.dets = dets
    if (af.canTakeEnhancements) group.enh = 1
    if (Object.keys(up).length) group.up = up
    if (missing.length) report.allies.missing.push(`${slug}/${group.name}: ${missing.join(', ')}`)
    out.push({ group, distance })
  }
  const best = new Map()
  for (const { group, distance } of out) {
    const had = best.get(group.key)
    if (!had || distance < had.distance) best.set(group.key, { group, distance })
    if (had) report.allies.narrowed.push(`${slug}: ${group.name} (${(had.distance <= distance ? group : had.group).ids.length} ids dropped for the closer rule)`)
  }
  const kept = [...best.values()].map((x) => x.group)
  report.allies.groups += kept.length
  for (const g of kept) report.allies.units += g.ids.length
  return kept.sort((a, b) => a.name.localeCompare(b.name))
}

// What the shared Codex: Space Marines units cost THIS Chapter. A Chapter's bundle doesn't repeat
// them (loadRosterFaction folds them in from space-marines.js), so their price can't come from
// buildUnit — but it does differ: Blood Angels pay 80 for an Assault Intercessor Squad where the
// Codex price is 75, and all four Chapters with a Repulsor Executioner pay 230 against the Codex's
// 255. The MFM records those under the Chapter's own "Space Marines" subfaction, which is exactly
// how `pointsOverrides` in src/data/datasheets/<chapter>.js is built — same idea, same source, so
// the roster and the datasheet page quote the same number.
//
// Emitted only where the Chapter price differs, keyed by MODEL COUNT rather than by bracket index:
// loadRosterFaction applies it to a `sizes` array it didn't build and mustn't assume the shape of.
function chapterUnitPoints(mfmFaction, smMfm, sharedIds, smIdMap, nameToDsId) {
  const sub = (mfmFaction?.subfactions || []).find((s) => norm(s.name) === 'space marines')
  if (!sub) return null
  const chapter = mfmPrices(sub.units)
  const codex = mfmPrices(smMfm?.units)
  const shared = new Set(sharedIds)
  const out = {}
  for (const [name, prices] of chapter) {
    const id = smIdMap.get(nameToDsId.get(name))
    if (!id || !shared.has(id)) continue
    const diff = {}
    for (const [models, p] of prices) if (codex.get(name)?.get(models)?.base !== p.base) diff[models] = p.base
    if (Object.keys(diff).length) out[id] = diff
  }
  return Object.keys(out).length ? out : null
}

function buildUnit(bd, idMap, fx, kwIndex, prices) {
  const minis = (minisByDs.get(bd.id) || []).slice().sort((a, b) => a.displayOrder - b.displayOrder)
  const miniIdx = new Map(minis.map((m, i) => [m.id, i]))
  const kws = bd.keywords || []
  const linkedId = idMap.get(bd.id)
  const flags = {}
  if (keyword(kws, 'Character')) flags.char = 1
  if (keyword(kws, 'Epic Hero')) flags.epic = 1
  // A Legends sheet is listed alongside everything else and marked, not hidden — the flag is what
  // the badge and the filter read. First shipped by GW in data version 946 (Legends: Orks).
  if (bd.isLegends) flags.legends = 1
  if (minis.some((m) => m.isSupremeCommander)) flags.supreme = 1
  if (minis.some((m) => m.canBeNonCharacterWarlord)) flags.nonCharWarlordOk = 1
  if (minis.length && minis.every((m) => m.cannotBeWarlord)) flags.noWarlord = 1
  if (minis.length && minis.every((m) => m.excludedFromEnhancements)) flags.noEnh = 1
  // …and it may join a unit that already has a Leader (see alongsideDs above).
  if (alongsideDs.has(bd.id)) flags.alongside = 1
  const hosts = hostsByDs.get(bd.id)

  // A datasheet can flag several compositions `default` (appdata groups by
  // referenceGroupingKeywordId); the editor pre-selects exactly one, so keep the flag only
  // on the first default-marked bracket.
  let defaultTaken = false
  const mfmSteps = []
  const comps = compByDs.get(bd.id) || []
  // Only when the two lists line up exactly — same length, same points, same model total. A
  // datasheet that fails any of those keeps today's behaviour (no `comp`, every reader falls back)
  // rather than getting a breakdown that might belong to a different bracket.
  const compsUsable = minis.length > 1 && comps.length === (bd.points || []).length
  const priced = prices?.get(normApost(bd.name))
  if (!priced) report.price.noUnit.push(`${bd.name}`)
  const rows = (bd.points || []).map((p, i) => {
    const [min, max] = parseModels(p.models)
    const s = { pts: p.points, per: [min, max] }
    if (p.default) s.default = 1
    if (compsUsable) {
      const rows = (compMinis.get(comps[i].id) || []).filter((r) => miniIdx.has(r.miniatureId))
      const sum = rows.reduce((a, r) => [a[0] + r.min, a[1] + r.max], [0, 0])
      if (rows.length && comps[i].points === p.points && sum[0] === min && sum[1] === max) {
        // `[miniatureIndex, min, max]`, max dropped when it equals min — most rows are fixed.
        s.comp = rows
          .map((r) => (r.min === r.max ? [miniIdx.get(r.miniatureId), r.min] : [miniIdx.get(r.miniatureId), r.min, r.max]))
          .sort((a, b) => a[0] - b[0])
        report.comp.brackets++
      } else report.comp.rejected.push(`${bd.name} #${i}: ${min}-${max}@${p.points} vs ${sum[0]}-${sum[1]}@${comps[i].points}`)
    }
    return s
  })
  const sizes = pickPrices(rows, priced, bd.name, mfmSteps)
  for (const s of sizes) {
    if (s.default && defaultTaken) delete s.default
    else if (s.default) defaultTaken = true
  }
  if (sizes.some((x) => x.comp)) report.comp.units++


  const unit = {
    id: linkedId || slugify(bd.name),
    sid: bd.id,
    name: bd.name,
    kws,
    flags,
    sizes,
  }
  if (linkedId) unit.linked = 1
  const step = stepByDs.get(bd.id)
  if (step) unit.step = step
  // The copy tax stays appdata's (`datasheet_points_step` knows WHICH copy it starts at, which the
  // MFM only implies through its "1st-2nd"/"3rd+" notes). Cross-checked against the surcharge those
  // notes describe, so a disagreement is reported rather than quietly shipped on top of an MFM base.
  const mfmStep = mfmSteps.length && mfmSteps.every((n) => n === mfmSteps[0]) ? mfmSteps[0] : null
  if (mfmStep != null && (step?.pts ?? 0) !== mfmStep) {
    report.price.stepDrift.push(`${bd.name}: appdata +${step?.pts ?? 0}, MFM +${mfmStep}`)
  }
  if (condBattlelineDs.has(bd.id)) unit.condBattleline = 1

  // The group id lives on the raw datasheet row, not in the faction bundle.
  const allegGroup = allegGroups.get(dsById.get(bd.id)?.allegianceAbilityGroupId)
  if (allegGroup) {
    const opts = (allegByGroup.get(allegGroup.id) || [])
      .sort((a, b) => a.displayOrder - b.displayOrder)
      .map((a) => {
        const o = { n: enOf(a).name }
        const kwId = allegKw.get(`${bd.id}|${a.id}`)
        const kw = kwId && kwName.get(kwId)
        if (kw && kw !== o.n) o.kw = kw
        if (a.requiresWargearItemId) o.wg = fx.item(a.requiresWargearItemId)
        return o
      })
      .filter((o) => o.n)
    if (opts.length) {
      // `det` is the detachment NAME because that is what a roster stores (see useRosters); absent
      // means the choice always applies. `req` = must be chosen, `max` = cap across the army.
      const alleg = { g: slugify(enOf(allegGroup).name || 'allegiance'), t: enOf(allegGroup).name || '', o: opts }
      const detOwner = allegGroup.detachmentId && detById.get(allegGroup.detachmentId)
      if (detOwner) alleg.det = enOf(detOwner).name
      if (allegGroup.isMandatory) alleg.req = 1
      if (allegGroup.maxRosterLimit) alleg.max = allegGroup.maxRosterLimit
      if (allegGroup.minRosterLimit) alleg.min = allegGroup.minRosterLimit
      unit.alleg = alleg
      report.alleg.units++
      report.alleg.kinds.add(`${alleg.g}${alleg.det ? ` (${alleg.det})` : ''}`)
    }
  }

  const groups = bgByLeader.get(bd.id) || []
  const leads = []
  const rawTargets = new Map()   // appdata datasheet uuid -> the lead built for it
  const leadKw = []
  for (const g of groups) {
    let targets = bgDatasheets.get(g.id) || []
    if (!targets.length && bgKeywords.has(g.id)) {
      // Resolved against THIS faction's datasheets here, and the KEYWORDS themselves are emitted
      // as well (`leadKw`), because a resolved id cannot travel: Inquisitor Draxus leads "any
      // IMPERIUM BATTLELINE INFANTRY unit", and as an ally in an Adeptus Mechanicus army the unit
      // she joins is a Skitarii Vanguard that her own bundle has never heard of. The runtime
      // answers the keyword question against whatever is actually in the list (rosterEngine's
      // leadTypeFor).
      const kw = { kw: bgKeywords.get(g.id).filter(Boolean), type: g.bodyguardType }
      if (g.requiredDetachmentId) kw.reqDet = g.requiredDetachmentId
      if (g.excludedDetachmentId) kw.exclDet = g.excludedDetachmentId
      if (kw.kw.length) leadKw.push(kw)
      const want = bgKeywords.get(g.id).map(norm).filter(Boolean)
      targets = (kwIndex ? want.map((k) => kwIndex.get(k) || []).reduce((a, b) => a.filter((x) => b.includes(x)), want.length ? kwIndex.get(want[0]) || [] : []) : [])
        .filter((id) => id !== bd.id)
      if (targets.length) report.leadKw.resolved += targets.length
      else report.leadKw.unresolved.push(`${bd.name} → ${bgKeywords.get(g.id).join(' + ')}`)
    }
    for (const targetDsId of targets) {
      const lead = { to: idMap.get(targetDsId) || slugify(enOf(dsById.get(targetDsId)).name || ''), type: g.bodyguardType }
      if (g.requiredDetachmentId) lead.reqDet = g.requiredDetachmentId
      if (g.excludedDetachmentId) lead.exclDet = g.excludedDetachmentId
      leads.push(lead)
      // …kept by appdata uuid as well, for the mirror rules below: they ask which units this one
      // may join, and a name is not what identifies those.
      if (!rawTargets.has(targetDsId)) rawTargets.set(targetDsId, lead)
    }
  }

  // A unit that says "whoever may join THAT unit may join me instead" (MIRROR_ATTACH). Only within
  // this bundle — the leads are ids in it — and only at the type the original attachment had: a
  // Support unit borrowed by the rule is still Support. appdata carries most of these links itself;
  // this fills the ones it does not, and adds nothing where it already has them.
  for (const m of MIRROR_ATTACH) {
    if (m.to === bd.id) continue
    const to = idMap.get(m.to)
    if (!to || leads.some((l) => l.to === to)) continue
    if (m.noEpic && flags.epic) continue
    if (m.need.length && !m.need.some((k) => keyword(kws, k))) continue
    const via = [...m.from].map((uuid) => rawTargets.get(uuid)).find(Boolean)
    if (!via) continue
    const lead = { to, type: via.type }
    if (via.reqDet) lead.reqDet = via.reqDet
    if (via.exclDet) lead.exclDet = via.exclDet
    leads.push(lead)
    report.mirror.added.push(`${bd.name} → ${to}`)
  }
  // Deduped: a keyword group ("any Imperium Battleline Infantry unit") and a listed group can name
  // the same unit, and the picker would offer it twice.
  const seenLead = new Set()
  const uniqueLeads = leads.filter((l) => {
    const k = `${l.to}|${l.type}|${l.reqDet || ''}|${l.exclDet || ''}`
    return seenLead.has(k) ? false : (seenLead.add(k), true)
  })
  if (hosts) unit.hosts = hosts
  if (uniqueLeads.length) unit.leads = uniqueLeads
  if (leadKw.length) unit.leadKw = leadKw

  // Miniatures (for labelling gear/loadout groups). A single-profile unit needs no list.
  if (minis.length > 1) unit.minis = minis.map((m) => ({ n: enOf(m).name }))

  // The models one profile fields at its default bracket — the divisor for a profile-total count,
  // and the same reading the per-copy pass below takes.
  const profileModels = (m) => {
    const bracket = (unit.sizes || []).find((x) => x.default) || (unit.sizes || [])[0]
    return (bracket?.comp || []).find(([mi]) => mi === m)?.[1] ?? (bracket?.per?.[0] ?? 1)
  }
  // Default loadout: what each miniature starts equipped with.
  const fixItem = (uuid) => {
    const to = LOADOUT_ITEM_FIXES[bd.id]?.[uuid]
    if (!to) return uuid
    report.loadoutFixed.push(`${bd.name}: ${wgItemName.get(uuid)} → ${wgItemName.get(to)}`)
    return to
  }
  const defaults = []
  for (const b of bmlByDs.get(bd.id) || []) {
    const items = b.opts
      .map((o) => [woById.get(o.wargearOptionId)?.wargearItemId, o.count])
      .filter(([uuid]) => uuid)
      .map(([uuid, count]) => [fx.item(fixItem(uuid)), count])
    if (items.length) defaults.push([miniIdx.get(b.miniatureId) ?? 0, items])
  }
  // The two tables COUNT differently: a `base_miniature_loadout` row is per model, a "Default
  // Wargear" group is the total the profile fields ("Burst cannon 2" for the two Crisis Starscythe
  // Shas'ui, one each). So a group's counts are divided by the models that profile fields, and
  // everything downstream — display, points, per-copy swaps — reads one convention: per model,
  // unless the entry carries the TOTAL marker below. Where the count doesn't divide it IS a total
  // and nothing else (a Sanctifiers Missionary's plasma gun: one of the two carries it).
  if (!defaults.length) {
    for (const [m, items] of staticLoadout(bd.id, miniIdx)) {
      const models = profileModels(m)
      defaults.push([m, items.map(([uuid, c]) => {
        const id = fx.item(fixItem(uuid))
        if (models < 2) return [id, c]
        return c % models === 0 ? [id, c / models] : [id, c, 1]
      })])
    }
    if (defaults.length) report.staticDefaults++
  } else {
    // The two tables can disagree, and where they do it is the loadout ROW that is short: a
    // Servitor Battleclade's Gun Servitors carry a heavy bolter and a heavy arc rifle between them
    // and the row records neither, an Archon loses its Shadowfield, Inquisitor Coteaz his
    // psyber-eagle. Seven miniatures game-wide, one of them the Death Company Dreadnought whose row
    // names another datasheet's weapons outright (LOADOUT_ITEM_FIXES above). So anything the
    // "Default Wargear" group names and the row does not is added to it.
    //
    // The two tables also COUNT differently: a row is per model ("Servo-claw 1", twice over), the
    // group is the total the profile fields ("Servo-claw 2", "Heavy bolter 1" — one of the two Gun
    // Servitors has it). A quantity that cannot be divided among the models is therefore marked as
    // a TOTAL with a third element, which is how the editor and the export know not to multiply it.
    const compOf = (m) => {
      const size = bd.points?.length ? (unit.sizes || []).find((x) => x.default) || (unit.sizes || [])[0] : null
      return (size?.comp || []).find(([mi]) => mi === m)?.[1] || 1
    }
    for (const [m, items] of staticLoadout(bd.id, miniIdx)) {
      const at = defaults.find(([mi]) => mi === m)
      // A profile the loadout rows skip altogether (Flash Gitz' Flash Git, Tempestus Aquilons'
      // troopers, Company Heroes' Veterans — their Kaptin/Tempestor/Ancient have a row, they do
      // not) takes the group's counts, which are PROFILE totals: divided like the no-row case
      // above. Taken raw until 2026-09-28, they were multiplied by the models a second time and
      // five Flash Gitz read "Choppa ×17".
      if (!at) {
        const models = profileModels(m)
        defaults.push([m, items.map(([uuid, c]) => {
          const id = fx.item(fixItem(uuid))
          if (models < 2) return [id, c]
          return c % models === 0 ? [id, c / models] : [id, c, 1]
        })])
        continue
      }
      const have = new Set(at[1].map(([id]) => id))
      // The row and the group can name ONE weapon by two item ids: a Nightmare Hulk's "Hideous
      // mutations" is one id in the loadout row and another in the group's "One Nightmare Hulk is
      // equipped with: belly-flamer; hideous mutations" — added as a second copy, four Hulks held
      // five (found 2026-10-05). By name, the group's item is the row's.
      const rowIdByName = new Map(at[1].map(([id]) => [norm(itemNameOfId(id)), id]))
      for (const [uuid, c] of items) {
        const named = rowIdByName.get(norm(wgItemName.get(fixItem(uuid))))
        const id = named ?? fx.item(fixItem(uuid))
        // …and the row can OVERSTATE: it describes one model, and a profile whose models are not
        // all alike gets that one model's loadout for every model. "2 Havocs are equipped with: Havoc
        // autocannon … 2 Havocs are equipped with: Havoc lascannon" has a row of autocannon ×1 for
        // the Havoc profile — four autocannons beside the group's two lascannons, a squad of six
        // heavy weapons (a player's report, 2026-10-03). Where the group counts FEWER copies than
        // the row times the models, the group's count is the profile's: per model if it divides,
        // a total if not. Two profiles game-wide, Havocs and the Voidsmen's three lasguns.
        if (have.has(id)) {
          const row = at[1].find(([i]) => i === id)
          const models = profileModels(m)
          // …and on a lone model it can UNDERSTATE: the row of a Land Raider says one Godhammer
          // lascannon where the group and the datasheet say two, and the weapon lost its "×2"
          // (found 2026-10-05 sweeping every default loadout against its datasheet text after a
          // Purifier report). For exactly ONE model the group's count is that model's, so the
          // larger count wins. Not for a profile the default bracket fields none of (a
          // Headtakers' Hunting Wolf, 0 at three models): there the group counts the wolves.
          if (!row[2] && models === 1 && c > row[1]) {
            report.defaultsMerged.push(`${bd.name}: ${wgItemName.get(uuid)} ×${c} (the loadout row said ${row[1]})`)
            row[1] = c
            continue
          }
          if (row[2] || models < 2 || c >= row[1] * models) continue
          row.splice(1, 2, ...(c % models === 0 ? [c / models] : [c, 1]))
          report.defaultsMerged.push(`${bd.name} / ${enOf((minisByDs.get(bd.id) || []).find((x) => (miniIdx.get(x.id) ?? 0) === m)).name || m}: ${wgItemName.get(uuid)} (${c} for the profile, not one per model)`)
          continue
        }
        // The group's count is the profile's, so it is divided like everywhere above: per model
        // when it divides, a total when it does not. Pushed as a total outright until 2026-10-05,
        // the Purifiers' "Nemesis force weapon 4" (the row leaves it out) stayed four at a squad of
        // nine and a psycannon swap took all four — the weapon lost its count (a player's report).
        const models = compOf(m)
        const per = models > 1 && c % models === 0
        at[1].push(models < 2 ? [id, c] : per ? [id, c / models] : [id, c, 1])
        report.defaultsMerged.push(`${bd.name} / ${enOf((minisByDs.get(bd.id) || []).find((x) => (miniIdx.get(x.id) ?? 0) === m)).name || m}: ${wgItemName.get(uuid)}${models > 1 && !per ? ` (${c} for the profile)` : ''}`)
      }
    }
  }
  // The datasheet's own words outrank both tables (owner, 2026-10-05). Where a one-profile unit's
  // composition says "This model / Every model is equipped with: 2 X" and the tables count another
  // number of X, the text's number stands: Cthonian Earthshakers carry two Autoch-pattern bolt
  // pistols each, and every table says one. Only an explicit number is read — a bare "X" says
  // nothing about a table's 2 — and only the single-line, single-profile shape, where the line
  // can mean one thing; the rest is held to the text by src/data/roster/index.test.js.
  if (defaults.length === 1 && !(minis.length > 1)) {
    const lines = [...(enOf(datasheetById.get(bd.id)).unitComposition || '').matchAll(/\*\*(?:This|Every) model is equipped with:\*\*\s*([^\n]+)/g)]
    if (lines.length === 1) {
      const key = (n) => String(n || '').toLowerCase().replace(/[\u2010\u2011]/g, '-').replace(/\s+/g, ' ').trim().replace(/s$/, '')
      const said = new Map()
      for (const part of lines[0][1].replace(/\.\s*$/, '').split(/[;,]/)) {
        const m = part.trim().match(/^(\d+)\s+(.+)$/)
        if (m) said.set(key(m[2]), Number(m[1]))
      }
      const nameOfId = (id) => { for (const [uuid, i] of itemIds) if (i === id) return wgItemName.get(uuid) }
      for (const row of defaults[0][1]) {
        const n = !row[2] && said.get(key(nameOfId(row[0])))
        if (!n || n === row[1]) continue
        report.textCount.push(`${bd.name}: ${nameOfId(row[0])} ${row[1]} → ${n}`)
        row[1] = n
      }
    }
  }
  // …and on a unit of several profiles, a line that names ONE profile exactly ("A Shade Runner is
  // equipped with: shuriken pistol; close combat weapon; paired Hekatarii blades") is that
  // profile's loadout, so an item it lists that the tables left off the profile is added — the
  // Voidscarred's three specialists had no close combat weapon (found 2026-10-05). Only an item
  // this unit already fields somewhere (so the name resolves to an id without guessing), only
  // added, never removed or recounted: a line can describe one model of a profile the tables split.
  if (defaults.length && minis.length > 1) {
    const key = (n) => String(n || '').toLowerCase().replace(/[\u2010\u2011]/g, '-').replace(/[’']/g, "'").replace(/\s+/g, ' ').trim().replace(/s$/, '')
    const profileByName = new Map(minis.map((m, i) => [key(enOf(m).name), i]))
    const nameOfId = (id) => { for (const [uuid, i] of itemIds) if (i === id) return wgItemName.get(uuid) }
    const idByName = new Map()
    for (const [, list] of defaults) for (const [id] of list) idByName.set(key(nameOfId(id)), id)
    const text = enOf(datasheetById.get(bd.id)).unitComposition || ''
    for (const [, who, list] of text.matchAll(/\*\*(?:The |A |An |Every )(.+?) (?:is|are) equipped with:\*\*\s*([^\n]+)/g)) {
      const m = profileByName.get(key(who))
      if (m == null) continue
      const row = defaults.find(([mi]) => mi === m)
      if (!row) continue
      for (const part of list.replace(/\.\s*$/, '').split(/[;,]/)) {
        const id = idByName.get(key(part.trim().replace(/^\d+\s+/, '')))
        if (id == null || row[1].some(([i]) => i === id)) continue
        row[1].push([id, Number(part.trim().match(/^(\d+)\s/)?.[1]) || 1])
        report.textCount.push(`${bd.name} / ${enOf(minis[m]).name}: + ${nameOfId(id)} (the text lists it, the tables do not)`)
      }
    }
  }
  if (defaults.length) unit.defaults = defaults

  // ── What the DEFAULT loadout costs ──────────────────────────────────────────────────────────
  // Since 11th edition a datasheet's default wargear can carry a price of its own: appdata marks a
  // Terminator Assault Squad's thunder hammer both `defaultValue` and `points: 5`, and GW's own app
  // prices a ten-model squad at 360 where the Munitorum bracket says 310. Eleven such options over
  // seven datasheets, and nothing downstream saw them — the bracket is the naked price, and
  // `wargear_option.points` was only ever read for options the player PICKS.
  //
  // Emitted as money per model (`dw: [[miniIndex, points]]`) rather than as items, because the
  // awkward part is here: a "Default Wargear" group counts the copies the whole profile fields
  // where a loadout row counts one model's, and either can be the source.
  // The engine multiplies by the models actually fielded, which the bracket cannot do — it is flat
  // across 6-10 models where the hammers are not.
  const paidDefaults = new Map()
  for (const g of wogByDs.get(bd.id) || []) {
    for (const o of woByGroup.get(g.id) || []) {
      if (!(o.points > 0) || !(o.defaultValue > 0)) continue
      paidDefaults.set(fx.item(LOADOUT_ITEM_FIXES[bd.id]?.[o.wargearItemId] || o.wargearItemId), o.points)
    }
  }
  // Per-model price of each paid default, by profile — the swap refunds below read it too.
  const paidPerMini = new Map()
  for (const [m, items] of paidDefaults.size ? defaults : []) {
    const row = new Map()
    for (const [id, c, total] of items) {
      const pts = paidDefaults.get(id)
      if (!pts) continue
      const per = total ? c / profileModels(m) : c
      // A count that doesn't divide among the profile's models is one of the loadout rows that
      // records a squad total (one of two Gun Servitors carries the heavy bolter). Charging a
      // fraction of it per model would be worse than not charging it, so it is reported instead.
      if (!Number.isInteger(per) || per < 1) { report.paidDefault.odd.push(`${bd.name}: profile ${m} has ${c} of a ${pts}pt default over ${profileModels(m)} models`); continue }
      row.set(id, per * pts)
    }
    if (row.size) paidPerMini.set(m, row)
  }
  if (paidPerMini.size) {
    unit.dw = [...paidPerMini].map(([m, row]) => [m, [...row.values()].reduce((a, b) => a + b, 0)])
    report.paidDefault.units++
  }

  // Wargear option groups: the atomic "replace/add one of {…}" choices. Drop the redundant
  // "Default Wargear" groups (base loadout already carries those) — keep real choices, with
  // their per-option points (0 when free) and default flag. Built as raw drafts first (original
  // instructionText + item UUIDs kept around) because the cross-group linking pass below needs
  // to read prose and resolve item names *before* everything gets interned to ints. Sorted by
  // the group's own displayOrder (same field already used for the group's OPTIONS below) — was
  // previously left in raw table order, which doesn't match wh40k-appdata's own intended
  // presentation: e.g. Necron Overlord's Resurrection Orb toggle (a non-weapon add-on) has a
  // higher displayOrder than its tachyon-arrow-replacement weapon group, so it should render
  // BELOW that weapon choice, not above it.
  let drafts = []
  for (const g of (wogByDs.get(bd.id) || []).slice().sort((a, b) => a.displayOrder - b.displayOrder)) {
    const text = fixWargearTypos(bd.name, (enOf(g).instructionText || '').trim())
    if (!text || isDefaultGroup(g)) continue
    const rawOpts = (woByGroup.get(g.id) || []).sort((a, b) => a.displayOrder - b.displayOrder)
    if (!rawOpts.length) continue
    drafts.push({
      m: miniIdx.get(g.miniatureId) ?? 0,
      miniId: g.miniatureId,
      text,
      in: rawOpts[0]?.inputType || 'checkbox',
      opts: rawOpts.map((o) => ({ uuid: o.wargearItemId, pts: o.points || 0, def: o.defaultValue || 0 })),
    })
  }
  linkWargearConditions(bd.id, drafts)
  linkWargearBundles(bd.id, bd.name, drafts, report.bundle)
  dropStockRemnants(bd.name, drafts, report.bundle.stockRemnant)
  linkAddOrSwap(bd.name, drafts, report.bundle.addOrSwap)
  // Before the limits: two identical groups are exactly what makes a limited set ambiguous, so
  // folding them first lets its cap land on the one group that remains.
  drafts = mergeMiniatureDuplicates(drafts, report.limit)
  linkWargearLimits(bd.id, bd.name, miniIdx, drafts, report.limit)
  // Where appdata records no limited-choice set at all, the instruction is the only statement of
  // the allowance there is — and it is often a real cap: "This model can be equipped with up to two
  // of the following, but cannot take duplicates" (a Grand Master in Nemesis Dreadknight, which
  // takes a Sublimator AND a heavy psycannon at 15 points each). Without it the group had no cap,
  // and validateRoster's conservative fallback — one pick per model of that profile — called a
  // legal two-weapon Dreadknight illegal. Read only where the prose states a plain number
  // (proseAllowance already refuses "for every 5 models" and "any number of"), and never over a
  // cap appdata itself gave.
  for (const d of drafts) {
    if (d.lim) continue
    const said = proseAllowance(d.text, d.opts.length)
    if (!said) continue
    const dup = proseNoDuplicates(d.text) ? 1 : 0
    d.lim = [dup ? [0, said, dup] : [0, said]]
    report.limit.fromProse++
  }
  // …the CONDITIONAL form ("If this unit contains 10 models, …"), which is a step table with one
  // row per block — see proseConditionalAllowance. Below its first threshold the group genuinely
  // offers nothing, which wargearGroupCap already reads as a real 0.
  for (const d of drafts) {
    if (d.lim) continue
    const rows = proseConditionalAllowance(d.text, d.opts.length)
    if (!rows) continue
    d.lim = rows
    report.limit.fromProseConditional.push(`${bd.name}: ${JSON.stringify(rows)} — ${d.text.split('\n')[0].slice(0, 70)}`)
  }
  // …and the SCALED form, which proseAllowance refuses because it is not one number: "For every 5
  // models in this unit, up to 2 models can each have their boltgun replaced with…" is a step
  // table, which is exactly what `lim` already is — one row per threshold the unit can reach.
  // Where appdata records the set this is the table it gives, and the two agree: of the 123 groups
  // whose instruction reads this way, 108 already carry appdata's own rows and only 4 disagree at
  // all (see the drift list). The 15 that don't were falling through to the EDITOR, which read
  // only the "for every 5" half of the sentence and applied it per option — so Grey Knights'
  // "up to 2 Paladins" allowed 2 of each option at 10 models where the datasheet allows 4 for the
  // group.
  //
  // A bare "For every 5 models in this unit:" over a bullet list is deliberately NOT read (the
  // comma is required): its bullets are separate allowances, one per weapon named — a Red Corsairs
  // Raider squad may swap 1 boltgun AND 1 reaver's blade per 5 models — and a single shared table
  // would cap the pair at what one of them is worth.
  for (const d of drafts) {
    const m = SCALED_ALLOWANCE.exec(d.text.split('\n')[0])
    if (!m) continue
    const per = Number(m[1])
    const many = WORD_NUM[m[2].toLowerCase()] || Number(m[2])
    const maxModels = Math.max(0, ...(unit.sizes || []).map((x) => x.per?.[1] || 0))
    const rows = []
    for (let k = 1; per && k * per <= maxModels; k++) rows.push([k * per, k * many])
    if (!rows.length) continue
    // appdata's own table wins wherever it has one — this is a reading of the prose, and the prose
    // is what the table is FOR. Where both exist they are compared instead, so a future appdata
    // change that contradicts the sentence it was written from is reported rather than swallowed.
    if (d.lim) {
      const mine = rows[rows.length - 1][1]
      const theirs = d.lim[d.lim.length - 1][1]
      if (mine !== theirs || rows.length !== d.lim.length) {
        report.limit.scaledDrift.push(`${bd.name}: prose ${JSON.stringify(rows)} vs appdata ${JSON.stringify(d.lim)} — ${d.text.split('\n')[0].slice(0, 70)}`)
      }
      continue
    }
    const dup = proseNoDuplicates(d.text) ? 1 : 0
    d.lim = dup ? rows.map(([n, c]) => [n, c, dup]) : rows
    report.limit.fromProseScaled++
  }
  // A budget PER MODEL: "Any number of models can each be equipped with up to two of the following,
  // but cannot take duplicates" (Broadside and the three Crisis Battlesuits datasheets, all T'au;
  // Fireknife and Starscythe drop the "each", which changes nothing — a squad-wide "up to two" on a
  // three-suit squad is not a thing T'au wargear does anywhere else). The single-item spelling —
  // Piranhas' "Any number of models can each be equipped with up to 2 seeker missiles" — is the
  // same budget over one option; it had fallen back to one missile per model. appdata files each as one unit-wide group with no limited-choice set,
  // so the editor offered one of each option to the whole squad: three Broadsides could not carry
  // six support systems between them, and one could be handed four. The group stores COUNTS, not
  // which model holds what, and counts are all this rule needs: M models × N picks is the budget,
  // and "no duplicates" is at most M of any one option (one per model) — any counts inside both
  // bounds can be dealt out round-robin, so the step table below is exact, one row per model count.
  // Footnotes that narrow what one model may hold are read afterwards, for these groups and the
  // pack's alike — see oneEachPerModel.
  const PER_MODEL_BUDGET = /^\s*any number of models can (?:each )?be equipped with up to (\d+|one|two|three|four|five)\b/i
  for (const d of drafts) {
    const m = PER_MODEL_BUDGET.exec(d.text.split('\n')[0])
    if (!m || d.lim) continue
    const per = WORD_NUM[m[1].toLowerCase()] || Number(m[1])
    const sizes = unit.sizes || []
    const lo = Math.min(...sizes.map((x) => x.per?.[0] ?? 1))
    const hi = Math.max(...sizes.map((x) => x.per?.[1] ?? 1))
    if (!Number.isFinite(lo) || !Number.isFinite(hi) || lo < 1) continue
    const noDup = proseNoDuplicates(d.text) && !/\bcan take duplicates\b/i.test(d.text)
    const rows = []
    for (let k = lo; k <= hi; k++) rows.push(noDup ? [k, k * per, k] : [k, k * per])
    d.lim = rows
    d.in = 'stepper'
    report.limit.perModelBudget.push(`${bd.name}: ${JSON.stringify(d.lim)} — ${d.text.split('\n')[0].slice(0, 70)}`)
  }
  // A swap a model may make ONCE PER COPY of the weapon it gives up: "Each of this model's
  // shuriken catapults can be replaced with 1 flamer" (a Wraithlord carries two), "Any number of
  // this model's dark lances can each be replaced with 1 disintegrator cannon" (a Ravager carries
  // three), "This model's big shootas can each be replaced with one of the following" (a Deff
  // Dread). The allowance is nowhere in the sentence and nowhere in appdata either — it is how
  // many of that weapon the printed loadout gives the model — so validateRoster's one-pick-per-
  // model fallback called every one of those ordinary builds illegal and the editor's stepper
  // stopped at one. `cp` records the copies per MODEL; the engine multiplies by the models of that
  // profile, which is what "each model can have each shuriken cannon it is equipped with replaced"
  // (War Walkers, 2 models × 2 cannons) needs.
  //
  // A bundled swap is not this and must not be read as it: "This model's 2 twin heavy flamers can
  // be replaced with 2 twin heavy bolters" is ONE pick that grants two items (44 groups corpus-
  // wide, against 6 per-copy ones), so the option granting exactly one item is what tells them
  // apart — together with the word "each", which every per-copy wording has and no bundled one does.
  const grantCount = (o) => (o.items ? o.items.reduce((n, [, c]) => n + (c || 1), 0) : 1)
  for (const d of drafts) {
    if (d.lim || !d.rep?.length || !/\beach\b/i.test(d.text.split('\n')[0])) continue
    // "each replace ONE OF their macro-scalpels" is one copy per model, not every copy (rc, below).
    if (/\breplace\s+one of\s+(?:its|their)\b/i.test(d.text.split('\n')[0])) continue
    if (!d.opts.every((o) => grantCount(o) === 1)) continue
    const row = defaults.find(([m]) => m === d.m)?.[1] || []
    // A count that is the profile's TOTAL rather than one model's has to be divided by the models
    // that profile fields, or a Crisis Starscythe's "2 burst cannons" — one each for its two
    // Shas'ui — would read as two per model and hand every model a swap it doesn't have.
    const bracket = (unit.sizes || []).find((x) => x.default) || (unit.sizes || [])[0]
    const perProfile = (bracket?.comp || []).find(([mi]) => mi === d.m)?.[1] ?? (bracket?.per?.[0] ?? 1)
    const copies = Math.min(...d.rep.map((uuid) => {
      const hit = row.find(([id]) => id === fx.item(uuid))
      if (!hit) return 1
      const n = hit[1] || 1
      const total = hit.length > 2
      if (!total) return n
      return perProfile > 0 && n % perProfile === 0 ? n / perProfile : 1
    }))
    if (copies > 1) { d.cp = copies; report.limit.perCopy++ }
  }
  // One copy of several: "The Nob can have their Rokkit Pistol replaced with 1 Smash Hammer" — the
  // Nob carries two rokkit pistols and the sentence names ONE (no "each", no "both", no number, the
  // item in the singular), so a pick takes one copy (`rc`, rosterEngine's pickShare) and the other
  // stays. Read as an ordinary swap it took both off the model, card and list (a player's report,
  // 2026-10-06). Only a per-model line: a profile TOTAL ("2 Havocs are equipped with…") is one copy
  // per model already, and a per-copy group (`cp`) has its own allowance.
  // "Any number of models can each replace ONE OF their macro-scalpels with one of the following"
  // says it outright: a Talos carries two and gives up one (an audit of every instruction,
  // 2026-10-07 — read as no swap at all, the model kept both and gained the new weapon).
  for (const d of drafts) {
    if (d.cp || d.rep?.length !== 1 || !/\breplace\s+one of\s+(?:its|their)\b/i.test(d.text.split('\n')[0])) continue
    d.rc = 1
    report.limit.oneCopy = (report.limit.oneCopy || 0) + 1
  }
  // "This model's 2 Heavy Bolters can be replaced with …" on a Kratos that carries FOUR (two
  // sponsons, a group each): a pick takes the two the sentence names, not all four (an audit,
  // 2026-10-07). Only where the printed loadout holds more than the number — "this model's 2
  // twin heavy flamers" on a model with exactly two is the ordinary whole swap.
  for (const d of drafts) {
    if (d.cp || d.rc || d.rep?.length !== 1) continue
    const m = d.text.split('\n')[0].match(/^this model(?:'|’)s (\d|two|three|four) /i)
    if (!m) continue
    const n = WORD_NUM[m[1].toLowerCase()] || Number(m[1])
    const id = itemIds.get(d.rep[0])
    const hit = id != null && (defaults.find(([dm]) => dm === d.m)?.[1] || []).find(([i]) => i === id)
    if (!hit || hit.length > 2 || !(hit[1] > n)) continue
    d.rc = n
    report.limit.oneCopy = (report.limit.oneCopy || 0) + 1
  }
  for (const d of drafts) {
    if (d.cp || d.lim || d.rc || d.rep?.length !== 1) continue
    const head = d.text.split('\n')[0]
    const low = head.toLowerCase()
    if (/\b(each|both|all|two|three|four|[2-9])\b/.test(low.split('replaced')[0])) continue
    // Looked up, not interned: fx.item() hands out the next id on a first call, and calling it here,
    // earlier than the groups below, renumbers items across every faction file.
    const id = itemIds.get(d.rep[0])
    const hit = id != null && (defaults.find(([m]) => m === d.m)?.[1] || []).find(([i]) => i === id)
    if (!hit || hit.length > 2 || !(hit[1] > 1)) continue
    const name = String(wgItemName.get(d.rep[0]) || '').toLowerCase()
    if (!name || !low.includes(name) || low.includes(`${name}s`) || (/y$/.test(name) && low.includes(name.replace(/y$/, 'ies')))) continue
    d.rc = 1
    report.limit.oneCopy = (report.limit.oneCopy || 0) + 1
  }
  // "Any number of Tempestus Scions can each have their hot-shot lasgun replaced with one of the
  // following" — one pick per MODEL of that profile, not one pick for the unit. appdata files it as
  // a checkbox with no limited-choice set, and the editor draws a capless multi-option checkbox as
  // a RADIO: one Scion with a meltagun and the other three stuck with lasguns, while validateRoster
  // (which falls back to the profile's model count) called four legal. A player reported exactly
  // that on 2026-09-10. The allowance is the profile's own model count — which is what the step
  // table says properly — so state it, and let the group be the stepper it always was.
  //
  // This is NOT `repall`, which is one tick reaching every model of the profile. That reading is
  // right where the profile fields a single model ("All models in this unit can each have their
  // combat knife replaced…" on a Reiver Sergeant, where the two coincide) and wrong the moment
  // several models can each pick something DIFFERENT — which is what a multi-option list means.
  // Groups whose profile count is a RANGE the player sets ("5-9 Reivers") are left alone: a step
  // table keyed on the unit's size cannot express "however many of them you took".
  //
  // The single-option spelling of the same thing — "Any number of models can each be equipped
  // with 1 bio-plasma" on Carnifexes, a checkbox in appdata — drew as one TOGGLE for the unit,
  // so two Carnifexes could carry one bio-plasma between them (2026-09-19). It is read too, but
  // only where the sentence says "any number" and nothing is given up: a single-option swap
  // ("Any number of X can each have their A replaced with 1 B") is `repall` below, one tick
  // reaching every model, and stays that.
  for (const d of drafts) {
    if (d.lim || d.in === 'stepper' || d.all || d.m == null) continue
    const first = d.text.split('\n')[0]
    if (!/\beach\b/i.test(first)) continue
    const many = d.opts.length >= 2
    if (many ? !/^\s*(?:any number of|all models)\b/i.test(first) : !/^\s*any number of\b/i.test(first)) continue
    if (many ? !d.rep?.length : d.rep?.length) continue
    const rows = []
    for (const s of unit.sizes || []) {
      const comp = (s.comp || []).find(([mi]) => mi === d.m)
      const own = comp
        ? (comp.length > 2 ? null : comp[1])
        : (s.per?.[0] === s.per?.[1] ? s.per[0] : null)
      if (own == null) { rows.length = 0; break }
      const at = s.per?.[0] ?? 0
      if (!rows.length || rows[rows.length - 1][1] !== own) rows.push([at, own])
    }
    // Nothing to fix where every bracket fields one model of the profile: a one-of radio is what
    // one model gets, and that is already what it draws.
    if (!rows.length || rows.every(([, n]) => n <= 1)) continue
    // "You cannot select the same weapon from this list more than once per unit" is the footnote
    // form of the duplicate cap, and it is the reason these lists are longer than the squad.
    const dup = /more than once per unit/i.test(d.text) || proseNoDuplicates(d.text) ? 1 : 0
    d.lim = rows.map(([n, c]) => (dup ? [n, c, dup] : [n, c]))
    d.in = 'stepper'
    report.limit.perModelEach.push(`${bd.name}: ${JSON.stringify(d.lim)} — ${first.slice(0, 70)}`)
  }
  const gear = []
  const gearIndex = new Map() // draft -> its final index in `gear`
  drafts.forEach((d, i) => gearIndex.set(d, i))
  for (const d of drafts) {
    const grp = {
      // No `m` on a unit-wide group (see mergeMiniatureDuplicates) — it belongs to no single
      // miniature, and the editor labels a group with its miniature's name when it has one.
      ...(d.all ? { all: 1 } : { m: d.m }),
      t: fx.text(d.text),
      in: d.in,
      o: d.opts.map((o) => {
        // Slot 0 is the item id, or — when the option is a bundle or carries a quantity — the
        // full `[[id, count], …]` set (see linkWargearBundles). rosterEngine's optionItems()
        // is the one reader of that polymorphism; nothing else should unpack slot 0 itself.
        const head = o.items ? o.items.map(([uuid, n]) => [fx.item(uuid), n]) : fx.item(o.uuid)
        const e = [head, o.pts, o.def]
        while (e.length > 1 && e[e.length - 1] === 0) e.pop() // trim trailing zeros
        return e
      }),
    }
    if (d.lim) grp.lim = d.lim
    if (d.cp) grp.cp = d.cp
    if (d.rc) grp.rc = d.rc
    if (d.rep?.length) grp.rep = d.rep.map((uuid) => fx.item(uuid))
    if (d.alt) grp.alt = 1
    if (d.keep?.length) grp.keep = d.keep.map((uuid) => fx.item(uuid))
    // A model that trades a paid default away stops paying for it: `dr` is what one pick in this
    // group gives back — per COPY where the group is per-copy, since that is how `n` is counted.
    if (paidPerMini.size && d.rep?.length) {
      const back = d.rep.reduce((sum, uuid) => {
        const id = fx.item(uuid)
        // A unit-wide group belongs to no profile. Every profile that carries the item prices it
        // the same on all seven datasheets, so the cheapest is both the answer and the reading that
        // can only ever undercharge.
        const seen = (d.all ? [...paidPerMini.values()] : [paidPerMini.get(d.m)])
          .map((row) => row?.get(id)).filter(Boolean)
        return sum + (seen.length ? Math.min(...seen) : 0)
      }, 0)
      const per = back / (d.cp || 1)
      if (per > 0 && Number.isInteger(per)) grp.dr = per
      else if (back > 0) report.paidDefault.odd.push(`${bd.name}: ${back}pt refund over ${d.cp} copies`)
    }
    // How many models one ticked option takes the swap away from. A stepper says so itself; a
    // CHECKBOX is one yes/no, and one tick means one model — "1 model's boltgun can be replaced
    // with one of the following" arms a single Battle Sister, not all nine. Only the "all models /
    // any number of" wording means the whole profile, so that reading is the one flagged (4 groups
    // corpus-wide) and the other 575 take the per-model default.
    if (d.rep?.length && d.in !== 'stepper' && /^\s*(?:all models|any number of)\b/i.test(d.text)) grp.repall = 1
    if (d.cond) grp.cond = [gearIndex.get(d.cond.sibling), d.cond.active ? 1 : 0]
    gear.push(grp)
  }
  if (gear.length) unit.gear = gear
  return unit
}

// A handful of "enhancements" are, per their own rules text, not a player pick at all: Necrons'
// Pantheon of Woe and Imperial Agents' Veiled Blade Elimination Force both read "each <unit> from
// your army has the relevant <ability>... and you must increase the points cost of each of those
// units" — automatic and mandatory for every eligible datasheet, not a once-per-army slot. The
// source data still models them as detachment enhancements (that's how the card is laid out), but
// with a broken requirement: enhancement_required_keyword_group_keyword points at "DNU" ("do not
// use"), an orphaned internal GW keyword attached to no datasheet, so as generated these can never
// legally be taken by anyone. Each is actually locked to one exact datasheet ("X model only" in
// its rules text), which already carries a matching name keyword — substitute the real
// requirement and flag it mandatory here. (rosterEngine.js's enhEligible treats an exact-name-
// keyword requirement as an override for the unit's general noEnh/epic-without-epicOk gates,
// since being locked to one specific datasheet is already maximally restrictive; enhancementPoints
// applies a mandatory enhancement automatically instead of waiting for entry.enh.)
// Typographic apostrophe (’, U+2019) — matches the datasheet names as extracted from appdata
// (see CLAUDE.md's RU-transliteration note: the source consistently uses ’, never a straight ').
const ENH_REQ_FIXES = {
  'Singularity Matrix': ['C’tan Shard of the Deceiver'],
  'Quantum Goad': ['C’tan Shard of the Nightbringer'],
  'Animus Damper': ['C’tan Shard of the Void Dragon'],
  'Reletavistic Tether': ['Transcendent C’tan'],
  'Decoy Targets': ['Callidus Assassin'],
  'Esoteric Explosives': ['Culexus Assassin'],
  // The other two of the four Extremis abilities, missing until 2026-10-03: an Eversor and a
  // Vindicare in a Veiled Blade army were 15 and 20 points too cheap and lacked the ability (found
  // auditing Agents of the Imperium). `--check` now fails on any enhancement still pointing at DNU.
  'Intraneural Biotech': ['Eversor Assassin'],
  'Micromelta Rounds': ['Vindicare Assassin'],
}

// Distinct from both of the above: an enhancement whose rules text reads "<unit> unit/model only"
// while appdata records neither a keyword nor a datasheet for it, so as generated it looks eligible
// on any unit of the faction. Pinned to the named sheet(s) of the CURRENT faction as `lockDs`
// (resolved through nameToDsId in genFaction), keyed by the enhancement's own `name`.
// Empty since 2026-10-07: 33 of the 36 entries here were said by appdata all along, in the
// `datasheetId` of the requirement group (see reqGroupDs), and the other three were dead — two
// enhancements GW retired and one GW spells "Nightforged Battery (Upgarde)", which this key never
// matched. A key that matches no enhancement now fails the run (unusedLockFixes below), so a
// misspelt one cannot sit here doing nothing again.
const ENH_LOCK_FIXES = {}
const usedLockFixes = new Set()
const normApost = (s) => (s || '').toLowerCase().replace(/[’‘]/g, "'")

// An Upgrade appdata caps below the muster rules' "up to three of the same Upgrade in your army".
// Every other non-Combat-Patrol Upgrade carries `limit: 3`; these are read as appdata's mistake,
// expected to be fixed by a coming data version — a list, not a rule (owner's call, 2026-10-05).
// Keyed by appdata's enhancement id, not the name: the one entry today is also misspelt, and a fix
// may well correct both.
//   - Dark Angels, Darkflight Pursuit: "Nightforged Battery (Upgarde)" — `limit: 1` at data
//     version 972; a player could not give it to a second Land Speeder Vengeance (report 2026-10-05).
// Each entry retires itself: once appdata says 3 (or the row is gone) `--check` fails and asks for
// the entry to be dropped. An uncapped-below-three Upgrade NOT on this list fails `--check` too.
const UPGRADE_LIMIT_FIXES = new Set(['4e119d31-30c8-4e94-be84-7f868ea1eb8b'])
const UPGRADE_LIMIT = 3

function buildEnhancement(e, nameToDsId, idMap) {
  const name = enOf(e).name
  const enh = { name, pts: e.basePointsCost, type: e.enhancementType }
  if (e.cannotBeWarlord) enh.notWarlord = 1
  if (!e.isIncludedInEnhancementLimit) enh.uncounted = 1
  if (e.isEquipableByEpicHero) enh.epicOk = 1
  if (e.isEquipableByNonCharacterUnit) enh.nonCharOk = 1
  let limit = e.limit
  if (e.enhancementType === 'upgrade') {
    if (UPGRADE_LIMIT_FIXES.has(e.id)) {
      if (limit === UPGRADE_LIMIT) report.upgradeLimit.retire.add(`${name}: appdata now says ${UPGRADE_LIMIT} — drop this entry`)
      else { limit = UPGRADE_LIMIT; report.upgradeLimit.fixed.add(name) }
    } else if (limit !== UPGRADE_LIMIT) report.upgradeLimit.unexplained.add(`${name} (limit ${limit}, id ${e.id})`)
  }
  if (limit && limit !== 1) enh.limit = limit
  // eligibility: OR of groups, each an AND of faction-keywords + keywords (+ the one datasheet).
  const req = []
  for (const gid of reqGroupsByEnh.get(e.id) || []) {
    const g = {}
    const fac = (reqGroupFac.get(gid) || []).filter(Boolean)
    const kw = (reqGroupKw.get(gid) || []).filter(Boolean)
    if (fac.length) g.fac = fac
    if (kw.length) g.kw = kw
    if (reqGroupDs.has(gid)) g.ds = reqGroupDs.get(gid)
    if (fac.length || kw.length || g.ds) req.push(g)
  }
  if (req.length) enh.req = req
  const excl = (exclKwByEnh.get(e.id) || []).filter(Boolean)
  if (excl.length) enh.exclKw = excl
  if (ENH_LOCK_FIXES[name]) {
    usedLockFixes.add(name)
    const ids = ENH_LOCK_FIXES[name].map((n) => nameToDsId.get(normApost(n))).filter(Boolean)
    // Conservative: only apply if EVERY named target resolved — a partial/failed resolution
    // (e.g. a future appdata rename) falls back to the existing (too-broad) faction-keyword
    // req rather than silently locking to the wrong subset.
    if (ids.length === ENH_LOCK_FIXES[name].length) enh.lockDs = ids
  }
  if (ENH_REQ_FIXES[name]) {
    enh.req = [{ kw: ENH_REQ_FIXES[name] }]
    enh.mandatory = 1
  }
  // appdata's "do not use" placeholder left in place: no datasheet carries it, so nobody can take
  // the enhancement. A new one is a gate (`--check`), not a note — two sat unnoticed until 2026-10-03.
  if ((enh.req || []).some((r) => (r.kw || []).includes('DNU'))) report.dnu.push(name)
  // Attach targets this enhancement grants its bearer, resolved to this faction's own unit ids
  // (a target on another faction's datasheet has nothing to attach to in this roster and drops).
  const attach = (enhAttachByEnh.get(e.id) || [])
    .map((a) => ({ to: idMap.get(a.datasheetId), type: a.type }))
    .filter((a) => a.to)
  if (attach.length) enh.attach = attach
  return enh
}

function buildDetachment(bdet, idMap, mfmDet, nameToDsId, facTag, slug) { // idMap also reaches buildEnhancement
  // The Detachment-Points cost + Force Disposition come from mfm (what the tracker shows), not
  // appdata's detachmentPointsCost — those disagree (appdata is 0 for standard detachments).
  const mfm = mfmDet.get(norm(bdet.name))
  const det = { name: bdet.name, sid: bdet.id, dp: mfm?.dp ?? bdet.detachmentPointsCost ?? 0 }
  // Every disposition it gives access to — two for 39 detachments (rosterEngine's dispositionCandidates).
  if (mfm?.forceDispositions?.length) det.fds = mfm.forceDispositions
  // The tag two detachments cannot share. Taken from mfm, cross-checked against appdata: a
  // disagreement means the scrape lost one (silent, and the roster then allows an illegal pair) or
  // that appdata is behind, which is the standing state of the two ONSLAUGHT detachments.
  // Three sources say it and none is complete on its own: mfm has 55, appdata's table the same 55,
  // and the hand-written faction data two more the other two lack (World Eaters' ONSLAUGHT pair,
  // read off the Faction Pack). Ours wins where they disagree; a disagreement is reported, because
  // the failure it guards against is silent — a lost tag means the editor allows an illegal pair.
  const ourTag = facTag.get(norm(bdet.name))
  const appTag = detTagByName.get(norm(bdet.name))
  const tag = ourTag || mfm?.unique || appTag
  if (tag) { det.unique = tag.toUpperCase(); report.detTag.tagged++ }
  const sources = [['ours', ourTag], ['mfm', mfm?.unique], ['appdata', appTag]]
  if (new Set(sources.map(([, v]) => norm(v))).size > 1) {
    report.detTag.drift.push(`${bdet.name}: ${sources.map(([n, v]) => `${n} ${v ? `«${v}»` : '—'}`).join(', ')}`)
  }
  // A detachment can bar a datasheet that belongs to ANOTHER faction, and the id must say so or it
  // lands on this army's own unit of the same name. Black Spear Task Force excludes the Codex:
  // Imperial Agents Watch Master — the ally you would otherwise bring alongside your own — and
  // falling back to the slugified NAME made that "watch-master", which is the Index: Deathwatch
  // datasheet this army is built around: a legal Watch Master read as illegal in every Deathwatch
  // list. Resolved through the same global map the allied ids use, so a foreign datasheet comes out
  // namespaced (`imperial-agents:watch-master`) and an own one bare.
  const exclId = (id) => {
    const own = idMap.get(id)
    if (own) return own
    const found = unitBySheet.get(id)
    if (found && found[0] !== slug) return `${found[0]}:${found[1]}`
    return found ? found[1] : slugify(enOf(dsById.get(id)).name || '')
  }
  const excl = (detExcluded.get(bdet.id) || []).map(exclId).filter(Boolean)
  if (excl.length) det.excludedUnits = excl
  const linked = (detLinked.get(bdet.id) || []).map((r) => {
    const l = { unit: idMap.get(r.datasheetId) || slugify(enOf(dsById.get(r.datasheetId)).name || ''), count: r.count }
    if (r.isWarlord) l.warlord = 1
    return l
  })
  if (linked.length) det.linkedUnits = linked
  const resolveMinis = (miniIds) => miniIds
    .map((mm) => { const ds = miniToDs.get(mm); return ds ? (idMap.get(ds) || slugify(enOf(dsById.get(ds)).name || '')) : null })
    .filter(Boolean)
  const mandUnits = resolveMinis(detMandWarlord.get(bdet.id) || [])
  if (mandUnits.length) det.mandWarlord = mandUnits
  const grantedUnits = resolveMinis(detGrantedWarlord.get(bdet.id) || [])
  if (grantedUnits.length) det.grantedWarlord = grantedUnits
  const enhancements = (enhByDet.get(bdet.id) || [])
    .filter((e) => !e.isCombatPatrol)
    .sort((a, b) => a.displayOrder - b.displayOrder)
    .map((e) => buildEnhancement(e, nameToDsId, idMap))
  det.enhancements = enhancements
  return det
}

// The same "must increase the points cost" mandatory ability (see ENH_REQ_FIXES) is ALSO present
// on the datasheet's own points brackets — the bundle lists a second bracket, same composition
// (`per` unchanged), priced exactly base + the enhancement's points. That's not a real unit-size
// choice (verified: the delta matches the matching enhancement's points to the point, for all 6
// known cases), so surfacing it as one in the editor lets a player "buy" the ability twice — once
// via that bracket, once via the always-applied mandatory enhancement. Strip the redundant
// bracket here; enhancementPoints (rosterEngine.js) is the single place the surcharge is added.
function stripMandatoryPriceBrackets(units, detachments) {
  const enhPtsByTargetKw = new Map()
  for (const det of detachments) {
    for (const e of det.enhancements) {
      if (e.mandatory && e.req?.[0]?.kw?.[0]) enhPtsByTargetKw.set(e.req[0].kw[0], e.pts)
    }
  }
  if (!enhPtsByTargetKw.size) return
  for (const u of units) {
    const bump = enhPtsByTargetKw.get(u.name)
    if (bump == null || u.sizes.length < 2) continue
    const base = u.sizes.reduce((min, s) => (s.pts < min.pts ? s : min), u.sizes[0])
    u.sizes = u.sizes.filter((s) => s === base || !(s.pts === base.pts + bump && s.per[0] === base.per[0] && s.per[1] === base.per[1]))
  }
}

const HEAD = '// Generated by gen-roster-data.mjs — do not edit. Re-run `npm run roster:data`.\n'
const stableJson = (obj) => JSON.stringify(obj, null, 2)

// `--check` regenerates everything in memory and only reports which files would change, so
// `npm run sync` can say "the roster data is stale" after an appdata bump instead of leaving the
// largest generated surface of the feature (30 faction files) silently out of date. Every write
// goes through here so no output can escape the check.
let CHECK = false
function writeOut(file, body) {
  const full = path.join(OUT, file)
  if (!CHECK) { fs.writeFileSync(full, body); return }
  let current = null
  try { current = fs.readFileSync(full, 'utf8') } catch { /* new file */ }
  if (current !== body) report.stale.push(file)
}

async function genFaction(slug) {
  const appSlug = SLUG_MAP[slug] || slug
  const bundle = loadJson(path.join(APPDATA, 'factions', `${appSlug}.json`))
  if (!bundle) { report.missingBundle.push(slug); return }
  const idMap = unitIdMap(slug)

  // mfm detachment map (name → { dp, forceDispositions }) — the tracker's numbers.
  const mfmMod = await loadModule(path.join(ROOT, 'src/data/mfm', `${slug}.js`))
  const mfmFaction = mfmMod?.default
  const mfmDet = new Map((mfmFaction?.detachments || []).map((d) => [norm(d.name), d]))
  // The MFM prints a Chapter's own detachment on the Space Marines page as often as on its own
  // (Deathwatch Support, dp 1 — it came out 0 here until 2026-10-03): a Chapter looks there second,
  // as gen-faction-rules does.
  if (isChapter(slug)) {
    const smMfm = (await loadModule(path.join(ROOT, 'src/data/mfm', 'space-marines.js')))?.default
    for (const d of smMfm?.detachments || []) if (!mfmDet.has(norm(d.name))) mfmDet.set(norm(d.name), d)
  }

  // Detachment tags as the reference pages already show them (FactionRuleView's "Unique: …").
  const facMod = await loadModule(path.join(ROOT, 'src/data/factions', `${slug}.js`))
  const facTag = new Map(((Object.values(facMod || {})[0]?.en?.detachments) || [])
    .filter((d) => d.unique).map((d) => [norm(d.name), d.unique]))

  // Name -> datasheet id, scoped to THIS faction's own bundle (before the points-filter below —
  // an ENH_LOCK_FIXES target should resolve even if the unit itself isn't a buildable line entry)
  // so a name shared across sub-factions (Helbrute/Maulerfiend — one datasheet per Chaos Legion
  // codex) resolves to the copy this faction actually has, not some other book's. A Chapter's own
  // bundle doesn't repeat the Codex: Space Marines units it shares (see the SM-Chapter dedup in
  // CLAUDE.md) — seed from the SM bundle first so a Chapter-specific enhancement targeting a
  // plain shared unit (Dark Angels' "Entreaty of Perpetual Ardour" → "Hellblaster Squad", not the
  // Chapter's own boxed-set-exclusive "Vengeful Brethren Hellblaster Squad") still resolves; the
  // Chapter's own entries are added after, so a name it DOES override still wins.
  const nameToDsId = new Map()
  if (isChapter(slug)) {
    const smBundle = loadJson(path.join(APPDATA, 'factions', `${SLUG_MAP['space-marines']}.json`))
    for (const d of smBundle?.datasheets || []) nameToDsId.set(normApost(d.name), d.id)
  }
  for (const d of bundle.datasheets || []) nameToDsId.set(normApost(d.name), d.id)

  // A handful of datasheets carry no points/composition (special epic heroes or
  // detachment-only variants) — not buildable matched-play line entries, so drop them. Their NAMES
  // are kept (`noBuild` below): a list export still prints such a profile as part of the unit it
  // comes with — the app prints "1x Sir Hekhtur" under Canis Rex, because that is who climbs out
  // when the Knight dies — and the importer has to know that its weapons belong to a profile
  // nobody can buy rather than report them as wargear it failed to place.
  const noBuild = []
  const bundleUnits = (bundle.datasheets || []).filter((d) => {
    if (cpDatasheetIds.has(d.id)) return false
    if (!(d.points && d.points.length)) { report.noPoints.push(`${slug}: ${d.name}`); noBuild.push(d.name); return false }
    return true
  })
  // Keyword -> datasheets, for the keyword-defined bodyguard groups. A Chapter's bundle doesn't
  // repeat the shared Codex: Space Marines units (same reason nameToDsId seeds from them above),
  // so Blood Angels Captain would otherwise find no Sternguard Veteran Squad to lead.
  const kwIndex = new Map()
  const indexKeywords = (list) => {
    for (const d of list) for (const k of d.keywords || []) {
      const n = norm(k)
      if (!kwIndex.has(n)) kwIndex.set(n, [])
      if (!kwIndex.get(n).includes(d.id)) kwIndex.get(n).push(d.id)
    }
  }
  if (isChapter(slug)) indexKeywords(loadJson(path.join(APPDATA, 'factions', `${SLUG_MAP['space-marines']}.json`))?.datasheets || [])
  indexKeywords(bundleUnits)
  // Prices for this faction's OWN datasheets. A Chapter's shared Codex units aren't in its bundle
  // at all (they're folded in at load time from space-marines.js) — their Chapter price is emitted
  // as `unitPoints` below instead.
  const prices = mfmPrices(ownMfmUnits(mfmFaction))
  const units = bundleUnits.map((bd) => buildUnit(bd, idMap, fx, kwIndex, prices)).sort((a, b) => a.name.localeCompare(b.name))
  // …and the unit such a sheet comes WITH: one that shares a named rule with it ("Using Sir Hekhtur"
  // on Canis Rex and on the pilot alike). `crew` lets the lists draw the pilot as a row of the unit
  // he climbs out of, without loading the datasheets (owner, 2026-10-04) — the same test the unit
  // card's `companions` applies to the full sheets.
  const ruleNames = (d) => new Set((d.rules || []).map((r) => norm(enOf(r).name || r.name || '')).filter(Boolean))
  for (const nb of (bundle.datasheets || []).filter((d) => noBuild.includes(d.name) && idMap.get(d.id))) {
    const theirs = ruleNames(nb)
    for (const bd of bundleUnits) {
      if (![...ruleNames(bd)].some((n) => theirs.has(n))) continue
      const u = units.find((x) => x.sid === bd.id)
      if (u) (u.crew ||= []).push({ id: idMap.get(nb.id), name: nb.name })
    }
  }
  // Codex: Space Marines also plays the six Codex Supplement detachments (Blade of Ultramar …), which
  // appdata ships as one-detachment "factions" of their own. Each is its Chapter's only: `chapter`
  // says whose, the same field the faction page's chapter picker reads.
  const supplements = slug === 'space-marines'
    ? SM_SUPPLEMENT_BUNDLES.flatMap((s) => {
      const b = loadJson(path.join(APPDATA, 'factions', `${s}.json`))
      return (b?.detachments || []).map((d) => ({ ...d, chapter: enOf(b.faction).name || b.faction?.name }))
    })
    : []
  // A detachment published in this faction's book is not necessarily one this army may take:
  // Deathwatch Support is printed in Codex Supplement: Deathwatch and is how every OTHER Adeptus
  // Astartes army brings the Deathwatch along — the Deathwatch itself may not field it (appdata's
  // detachment_faction_keyword, and the MFM's Deathwatch page agrees). The editor offered it to
  // Deathwatch lists until 2026-10-05. Only what the faction keyword is entitled to is offered; the
  // faction page still shows the rest, so its rules can be read where they are printed.
  const ownKw = kwByName.get(norm(enOf(bundle.faction).name || bundle.faction?.name || ''))
  const entitled = ownKw && detsByKeyword.has(ownKw) ? new Set(detsByKeyword.get(ownKw)) : null
  // It stays in the file, marked `lend`: the other armies fold it in from here (loadRosterFaction),
  // and the loader leaves it out of this army's own list.
  const lent = new Set()
  for (const d of bundle.detachments || []) {
    if (!entitled || d.isCombatPatrol || entitled.has(d.id)) continue
    lent.add(d.id)
    report.notEntitled.push(`${slug}: ${enOf(d).name || d.name}`)
  }
  const detachments = [...(bundle.detachments || []), ...supplements]
    .filter((d) => !d.isCombatPatrol && !cpDatasheetIds.has(d.id))
    .map((bdet) => {
      const det = buildDetachment(bdet, idMap, mfmDet, nameToDsId, facTag, slug)
      if (lent.has(bdet.id)) return { ...det, lend: 1 }
      return bdet.chapter ? { ...det, chapter: bdet.chapter } : det
    })
    .sort((a, b) => a.name.localeCompare(b.name))
  stripMandatoryPriceBrackets(units, detachments)

  report.factions++
  report.units += units.length
  for (const u of units) { if (u.linked) report.linked++; else report.unlinked.push(`${slug}: ${u.name}`) }

  const data = { slug, name: enOf(bundle.faction).name || bundle.faction?.name || slug, units, detachments }
  // Allied contexts this army may use (see the Allies section above). Metadata only — ids and
  // limits — so a faction file stays one chunk; loadRosterFaction pulls the source bundles.
  const allies = await alliesFor(bundle.faction?.id, new Set(units.map((u) => u.id)), slug)
  if (allies.length) data.allies = allies
  if (noBuild.length) data.noBuild = noBuild.sort()
  // SM-Chapter fold: a Chapter's bundle lists only its own units; the shared Adeptus Astartes
  // pool lives in space-marines.js. Reuse the exact `sharedUnitIds` the datasheet layer already
  // computed (data/datasheets/<chapter>.js) so the roster shows the same unit list as the rules
  // pages. loadRosterFaction() folds them in at load time.
  if (isChapter(slug)) {
    const dsMod = await loadModule(path.join(ROOT, 'src/data/datasheets', `${slug}.js`))
    const shared = dsMod?.sharedUnitIds || []
    if (shared.length) data.sharedUnitIds = shared
    const smMfm = (await loadModule(path.join(ROOT, 'src/data/mfm', 'space-marines.js')))?.default
    const over = chapterUnitPoints(mfmFaction, smMfm, shared, unitIdMap('space-marines'), nameToDsId)
    if (over) { data.unitPoints = over; report.price.chapterOverrides += Object.keys(over).length }
  }
  // The detachments of the Space Marines family this army may field from another bundle: a
  // Chapter's Codex detachments (space-marines.js), and Deathwatch Support, which the app files
  // with the Deathwatch and opens to every Adeptus Astartes army — the Space Marines included.
  // Until 2026-10-03 only the Chapters were asked, and only space-marines.js was looked in, so
  // nobody but the Deathwatch could take Deathwatch Support.
  if (isChapter(slug) || slug === 'space-marines') {
    const sharedDets = sharedDetachmentsFor(data.name, detachments)
    if (sharedDets) {
      data.sharedDetachments = sharedDets.names
      if (sharedDets.dp) data.detachmentDp = sharedDets.dp
      const from = Object.fromEntries(sharedDets.names.filter((n) => DW_DETACHMENTS.has(norm(n))).map((n) => [n, 'deathwatch']))
      if (Object.keys(from).length) data.sharedDetachmentFrom = from
      report.sharedDets += sharedDets.names.length
    }
  }
  // Written after every faction has been built (see run): the pack Legends intern their items
  // last, so the ids appdata's units carry do not move when a pack sheet is added.
  built.push({ slug, data })
}
