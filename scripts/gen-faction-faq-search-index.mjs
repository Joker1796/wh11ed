// Generate src/data/factionFaqSearchIndex.js — the compact faction FAQ/errata HEADING index the
// global search (Ctrl+K) uses to find an errata block or a question by what it names, routing to
// /factions/<slug>/faq#ffaq-<i>. Headings only (an errata header names the datasheet/rule it
// changes; a question carries its own terms) — the bodies live in factionFaq.json (420 KB) plus
// its RU overlay (610 KB), which FactionFaqView loads for one faction at a time and the search
// must not pull in whole. Same names-only trade-off as combatPatrolSearchIndex.js.
//
// Shape: [[slug, factionName, [[i, type, text, textRu | null], …]], …] — `i` is the entry's index
// in factionFaq.json's `entries` (the view's anchor id `ffaq-<i>` is built from the same index),
// `type` is 'errata' | 'qa'. Inline markup (**bold**) is stripped here so the index stays small
// and useSearch matches plain text.
//
// Run whenever factionFaq.json / factionFaqRu.json changes (`npm run faq` → `npm run faq:index`):
//   node scripts/gen-faction-faq-search-index.mjs
//   node scripts/gen-faction-faq-search-index.mjs --check    # report only; non-zero exit if stale

import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { ROOT, loadJson } from './lib/sync-common.mjs'
import { factionGroups } from '../src/data/factionsIndex.js'

const OUT = path.join(ROOT, 'src/data/factionFaqSearchIndex.js')

const plain = (s) => (s || '').replace(/\*\*(.+?)\*\*/g, '$1').replace(/\s+/g, ' ').trim()

export function run(argv = process.argv.slice(2)) {
  const CHECK = argv.includes('--check')
  const en = loadJson(path.join(ROOT, 'src/data/factionFaq.json'))
  const ruPath = path.join(ROOT, 'src/data/factionFaqRu.json')
  const ru = fs.existsSync(ruPath) ? loadJson(ruPath) : {}
  const nameOf = new Map(factionGroups.flatMap((g) => g.factions.map((f) => [f.slug, f.name])))

  const out = []
  let entries = 0
  for (const [slug, data] of Object.entries(en)) {
    if (!nameOf.has(slug)) continue
    const rows = []
    ;(data.entries || []).forEach((e, i) => {
      const text = plain(e.type === 'errata' ? e.header : e.q)
      if (!text) return
      const r = ru[slug]?.entries?.[i]
      const textRu = plain(e.type === 'errata' ? r?.header : r?.q)
      rows.push([i, e.type, text, textRu && textRu !== text ? textRu : null])
    })
    if (!rows.length) continue
    out.push([slug, nameOf.get(slug), rows])
    entries += rows.length
  }

  const body = `// Generated by scripts/gen-faction-faq-search-index.mjs — do not edit by hand.
// Compact faction FAQ/errata HEADING index for the global search (Ctrl+K):
// [[slug, factionName, [[entryIndex, 'errata' | 'qa', text, textRu | null], …]], …]. Headings
// only — the bodies stay in factionFaq.json, loaded per faction by FactionFaqView. Loaded on
// demand by useSearch.js (dynamic import) so it never rides in the entry bundle.
export const factionFaqSearchIndex = ${JSON.stringify(out)}
`
  const rel = path.relative(ROOT, OUT)
  if (CHECK) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (current !== body) {
      console.log(`  ✗ ${rel} is stale — run \`npm run faq:index\`.`)
      return 1
    }
    console.log('  in sync.')
    return 0
  }
  fs.writeFileSync(OUT, body)
  console.log(`gen-faction-faq-search-index: ${out.length} factions, ${entries} headings → ${rel}`)
  return 0
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) process.exit(run())
