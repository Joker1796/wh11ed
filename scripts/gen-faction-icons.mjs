// Generates src/data/factionIcons.js — what the app needs to know about each faction emblem in
// public/images/faction-icons/ without loading it: its path, its shape and how much ink it holds.
//
// A file is named after its faction's slug (`necrons.svg`); a redrawn emblem takes a new name, as
// every image there must (see public/images/CLAUDE.md), as `<slug>.<anything>.svg` — the part
// before the first dot is the slug. Two files for one slug is an error.
//
// `ratio` is the viewBox's width / height: a mask has no intrinsic size, so a box that wants the
// emblem's own shape takes it from here. `ink` is the share of an H×H square the drawing covers
// when drawn H tall — the emblems differ wildly in it (Chaos Daemons' thin star 0.14, Astra
// Militarum's banner 1.5), and FactionEmblem sizes a card's stamp so that every emblem puts the
// same amount of colour on it rather than the same height.
//
// `npm run faction-icons` writes the file; `-- --check` fails if it is out of date.

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { factionGroups } from '../src/data/factionsIndex.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = join(ROOT, 'public', 'images', 'faction-icons')
const OUT = join(ROOT, 'src', 'data', 'factionIcons.js')
const H = 200

const slugs = new Set(factionGroups.flatMap((g) => g.factions.map((f) => f.slug)))
const icons = {}
for (const file of (await readdir(DIR)).filter((f) => f.endsWith('.svg')).sort()) {
  const slug = file.split('.')[0]
  if (!slugs.has(slug)) throw new Error(`${file}: no faction "${slug}" in factionsIndex.js`)
  if (icons[slug]) throw new Error(`${file}: "${slug}" already has ${icons[slug].src}`)
  const svg = await readFile(join(DIR, file))
  const [, , w, h] = svg.toString().match(/viewBox="([^"]*)"/)[1].split(/\s+/).map(Number)
  const ratio = w / h
  const W = Math.round(H * ratio)
  const { data } = await sharp(svg, { density: 300 }).resize(W, H, { fit: 'fill' }).ensureAlpha().extractChannel(3).raw().toBuffer({ resolveWithObject: true })
  let alpha = 0
  for (const a of data) alpha += a / 255
  icons[slug] = { src: `/images/faction-icons/${file}`, ratio: +ratio.toFixed(2), ink: +(alpha / (H * H)).toFixed(2) }
}

const body = Object.entries(icons).map(([slug, v]) => `  '${slug}': ${JSON.stringify(v).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ').replace(/"/g, "'").replace('{', '{ ').replace(/}$/, ' }')},`).join('\n')
const out = `// GENERATED by scripts/gen-faction-icons.mjs from public/images/faction-icons/ — do not edit.\n// { slug: { src, ratio: width / height, ink: share of an H×H square covered when drawn H tall } }\nexport const factionIcons = {\n${body}\n}\n`

if (process.argv.includes('--check')) {
  const was = await readFile(OUT, 'utf8').catch(() => '')
  if (was !== out) {
    console.error('✗ faction-icons: src/data/factionIcons.js is out of date — run `npm run faction-icons`')
    process.exit(1)
  }
  console.log(`✓ faction-icons: ${Object.keys(icons).length} emblems, in sync`)
} else {
  await writeFile(OUT, out)
  console.log(`✓ faction-icons: ${Object.keys(icons).length} emblems written to src/data/factionIcons.js`)
}
