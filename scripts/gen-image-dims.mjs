// Generates an intrinsic-size map for illustrations so AppImage can reserve space
// before the image loads (no layout shift / CLS, and anchor-scroll lands correctly).
//
// Walks public/images/**/*.webp (skipping -sm copies and icons, which render via a
// plain <img>, not AppImage) and writes src/data/imageDimensions.js, keyed by the
// webp path AppImage requests (e.g. "/images/fight/overrun-fight.webp": [w, h]).
//
// Idempotent. Run after converting images: `npm run images:dims` (chained into
// `npm run images:webp`).

import { readdir, writeFile } from 'node:fs/promises'
import { join, relative, basename, extname, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const IMAGES_DIR = join(ROOT, 'public', 'images')
const OUT_FILE = join(ROOT, 'src', 'data', 'imageDimensions.js')

const rel = abs => relative(IMAGES_DIR, abs).split('\\').join('/')

// Icons render via plain <img> (not AppImage) — skip them. Mirrors iconSpec() in gen-webp.mjs.
function isIcon(name) {
  return name.startsWith('marker-') || name.startsWith('dispo-') || name.startsWith('legend-')
}

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(p)
    else if (entry.isFile()) yield p
  }
}

const dims = {}
for await (const file of walk(IMAGES_DIR)) {
  if (extname(file).toLowerCase() !== '.webp') continue
  const name = basename(file, '.webp')
  if (name.endsWith('-sm') || isIcon(name)) continue
  const meta = await sharp(file).metadata()
  if (!meta.width || !meta.height) continue
  dims[`/images/${rel(file)}`] = [meta.width, meta.height]
}

const keys = Object.keys(dims).sort()
const body = keys.map(k => `  '${k}': [${dims[k][0]}, ${dims[k][1]}],`).join('\n')
const out = `// AUTO-GENERATED by scripts/gen-image-dims.mjs — do not edit by hand.
// Intrinsic [width, height] of each illustration webp, so AppImage can reserve
// space before load (prevents layout shift / wrong anchor-scroll). Regenerate with
// \`npm run images:dims\`.

export default {
${body}
}
`

await writeFile(OUT_FILE, out)
console.log(`Wrote ${keys.length} image dimensions to ${relative(ROOT, OUT_FILE)}`)
