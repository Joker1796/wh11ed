// Generate src/data/combatPatrolSearchIndex.js — the compact Combat Patrol NAME index the
// global search (Ctrl+K) uses to find each box's detachment rule, army rule, stratagems and
// enhancements (+ each rule's h4 subheadings) by name, routing to /combat-patrol/<slug>. Same
// names-only trade-off as factionRulesIndex.js/datasheetIndex.js — combatPatrol.js (detachment
// rules + all 24 boxes' fixed-roster datasheets) is dynamic-imported by CombatPatrolFactionView
// only when a Combat Patrol page is actually visited, never statically.
//
// combatPatrol.ru is already the fully deep-overlaid RU tree (see deepOverlay.js): its
// `factions[]` preserves the EN array's order (deepOverlay maps EN→RU-or-fallback, doesn't
// reorder), so combatPatrol.en.factions[i] and combatPatrol.ru.factions[i] are always the same
// box — no separate name/slug matching needed here.
//
// Run whenever combatPatrol.js / combatPatrolRu.js changes:
//   node scripts/gen-combat-patrol-search-index.mjs

import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { ROOT } from './lib/sync-common.mjs'
import { combatPatrol } from '../src/data/combatPatrol.js'
import { slugify } from '../src/data/slugify.js'
import { extractSubheadings } from '../src/data/extractSubheadings.js'
import { h4AnchorId } from '../src/composables/anchors.js'

// See gen-faction-rules-index.mjs's identical helper for why both EN and RU bodies are needed:
// `name` always comes from the EN heading (names stay English by convention even when a RU
// translation replaces the heading outright instead of following the `### En | RU` pipe form).
function subheadings(enBody, ruBody, ruleId) {
  const enHeads = extractSubheadings(enBody)
  const ruHeads = ruBody ? extractSubheadings(ruBody) : []
  return enHeads.map((h, i) => {
    const ruHead = ruHeads[i]
    const nameRu = ruHead ? ruHead.ru || (ruHead.text !== h.text ? ruHead.text : '') : ''
    return { id: h4AnchorId(ruleId, i + 1), name: h.text, nameRu: nameRu || null }
  })
}

const out = combatPatrol.en.factions.map((f, fi) => {
  const ru = combatPatrol.ru.factions[fi]
  const ruleId = `cp-${f.slug}-rule`
  const armyRuleId = `cp-${f.slug}-army-rule`
  return [
    f.slug,
    f.name,
    f.boxName,
    {
      rule: f.rule
        ? {
            id: ruleId,
            name: f.rule.name || '',
            nameRu: ru?.rule?.nameRu || null,
            subheadings: subheadings(f.rule.body, ru?.rule?.body, ruleId),
          }
        : null,
      armyRule: f.armyRule
        ? {
            id: armyRuleId,
            name: f.armyRule.name || '',
            nameRu: ru?.armyRule?.nameRu || null,
            subheadings: subheadings(f.armyRule.body, ru?.armyRule?.body, armyRuleId),
          }
        : null,
      stratagems: (f.stratagems || []).map((s, si) => ({
        id: `cp-strat-${f.slug}-${slugify(s.name)}`,
        name: s.name || '',
        nameRu: ru?.stratagems?.[si]?.nameRu || null,
      })),
      enhancements: (f.enhancements || []).map((e, ei) => ({
        id: `cp-enh-${f.slug}-${slugify(e.name)}`,
        name: e.name || '',
        nameRu: ru?.enhancements?.[ei]?.nameRu || null,
      })),
    },
  ]
})

const body = `// Generated by scripts/gen-combat-patrol-search-index.mjs — do not edit by hand.
// Compact Combat Patrol NAME index for the global search (Ctrl+K): one entry per box,
// [slug, factionName, boxName, { rule, armyRule, stratagems[], enhancements[] }] — each rule
// also carries its h4 subheadings. Names only, same trade-off as factionRulesIndex.js. Loaded on
// demand by useSearch.js (dynamic import) so it never rides in the entry bundle.
export const combatPatrolSearchIndex = ${JSON.stringify(out)}
`
writeFileSync(path.join(ROOT, 'src/data/combatPatrolSearchIndex.js'), body)
console.log(`gen-combat-patrol-search-index: ${out.length} boxes → src/data/combatPatrolSearchIndex.js`)
