let enForms = null
let coreNames = null
export async function prime() {
  if (enForms) return
  const { glossary } = await import(pathToFileURL(path.join(DATA, 'glossary.js')).href)
  enForms = new Map()
  for (const [id, g] of Object.entries(glossary)) enForms.set(g.term.toLowerCase(), id)
  for (const f of enFiles(DATA)) {
    for (const m of fs.readFileSync(f, 'utf8').matchAll(/\[gloss:([a-z0-9-]+):([A-Za-z][^\]]*)\]/g)) enForms.set(m[2].toLowerCase(), m[1])
  }
  for (const [k, id] of Object.entries(EXTRA_EN)) enForms.set(k, id)
  for (const id of new Set(enForms.values())) if (!glossary[id]) throw new Error(`gloss-bold-terms: unknown glossary id ${id}`)
  const { coreAbilities } = await import(pathToFileURL(path.join(DATA, 'reference.js')).href)
  coreNames = coreAbilities.en.filter((a) => a.type === 'unit').map((a) => a.name)
    .filter((n) => !['Leader', 'Support', 'Damaged'].includes(n)).sort((a, b) => b.length - a.length)
}

const fold = (s) => s.toLowerCase().replace(/[’‘]/g, "'").replace(/‑|‐/g, '-').replace(/\s+/g, ' ').trim()
function enId(term) {
  const t = fold(term)
  if (!t) return null
  const hit = enForms.get(t) || enForms.get(t.replace(/s$/, '')) || enForms.get(`${t}s`)
  if (hit) return hit
  for (const [re, id] of EN_PATTERNS) if (re.test(t)) return id
  return null
}
function ruId(term) {
  const t = fold(term)
  if (!t) return null
  for (const [re, id] of RU_FORMS) if (re.test(t)) return id
  return null
}
// "Feel No Pain 5+", "Scouts 6\"", "Stealth" — a core unit ability, qualifier and all.
function coreOf(term) {
  const t = term.trim()
  for (const n of coreNames) {
    if (t.toLowerCase() === n.toLowerCase()) return n
    if (t.toLowerCase().startsWith(`${n.toLowerCase()} `) && /^[\dDX]/.test(t.slice(n.length + 1))) return `${n}${t.slice(n.length)}`
  }
  return null
}

// One bold span's replacement, or null. A slash list ("advance/fall-back move") links part by part
// when every part resolves — the shared tail word is lent to the parts that lack it.
function linkSpan(inner, idOf) {
  const lead = inner.match(/^\s*/)[0]
  const trail = inner.match(/[\s.:,]*$/)[0]
  const core = inner.slice(lead.length, inner.length - trail.length)
  if (!core || /[[\]*_]|\n/.test(core)) return null
  const id = idOf(core)
  if (id) return `${lead}[gloss:${id}:${core}]${trail}`
  if (core.includes('/')) {
    const parts = core.split('/')
    if (parts.some((p) => !p.trim())) return null // "PHOBOS**/**SCOUT": a bold slash, not a list
    const tail = parts[parts.length - 1].includes(' ') ? parts[parts.length - 1].split(' ').slice(1).join(' ') : ''
    const ids = parts.map((p) => idOf(p) || (tail && !p.includes(' ') ? idOf(`${p} ${tail}`) : null))
    if (ids.every(Boolean)) return `${lead}${parts.map((p, i) => `[gloss:${ids[i]}:${p}]`).join('/')}${trail}`
  }
  return null
}

// Rewrite every bold span of one string. Returns [newString, linked, unlinkedTerms].
// Rewrite every bold span of one string. Returns [newString, linked, unlinkedTerms].
//
// One popover per term per SECTION: a term linked once stays plain bold until the next `### `
// subheading (owner, 2026-09-30 — "боевая доктрина" four times in one list was too much). Every
// string is a section of its own too: a stratagem's WHEN/TARGET/EFFECT sit under their own labels,
// a datasheet's abilities under their own names. A repeat that is already a popover is unwrapped
// back to plain bold, so re-running the script tidies a file linked before this rule existed.
// Core abilities are left alone — `[core:…]` is how the rulebook's own emphasis is carried, not an
// extra, and the emphasis gate reads it.
export function glossString(str, locale, onSpan = null) {
  const idOf = locale === 'ru' ? ruId : enId
  let linked = 0
  const open = []
  const seen = new Set()
  const keepFirst = (tokens) => tokens.replace(/\[gloss:([a-z0-9-]+):([^\]]+)\]/g, (t, id, label) => {
    if (seen.has(id)) return label
    seen.add(id)
    linked++
    return t
  })
  // A gloss/def token is passed over whole: a hand-written one can carry bold INSIDE its label
  // (Astra Militarum's `[gloss:am-order:**Orders**]`), and linking that bold again nested a gloss
  // inside a gloss (2026-10-01).
  const out = str.replace(/^### .*$|\[(?:gloss|def):[^\]]*\]|\*\*([^*\n]+?)\*\*/gm, (m, inner) => {
    if (m.startsWith('[')) {
      // …and it counts as the section's popover for its term, like one this pass made.
      const id = m.match(/^\[(?:gloss|def):([^:\]]+)/)[1]
      if (!seen.has(id)) { seen.add(id); linked++ }
      return m
    }
    if (inner === undefined) { seen.clear(); return m }
    const bare = inner.replace(/[.:,]+$/, '')
    const core = coreOf(bare)
    if (core) { const to = `[core:${core}]${inner.slice(bare.length)}`; onSpan?.(m, to); return to }
    let body = /\[gloss:/.test(inner) ? inner : linkSpan(inner, idOf)
    if (!body) {
      if (!/\[core:/.test(inner)) open.push(inner.trim())
      return m
    }
    body = keepFirst(body)
    const to = `**${body}**`
    if (to !== m) onSpan?.(m, to)
    return to
  })
  return [out, linked, open]
}

// Every string literal of a JS source, in order: [start, end, quote, parts]. `parts` are the cooked
// static pieces (one for a quoted string; a template literal is split at each `${…}`, whose code is
// kept verbatim in `holes`). Comments are skipped. Enough of a tokenizer for data files — no regex
// literals, which these files do not use.
export function literals(src) {
  const out = []
  for (let i = 0; i < src.length; i++) {
    const c = src[i]
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue }
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i + 2) + 1; continue }
    if (c !== "'" && c !== '"' && c !== '`') continue
    const start = i
    const parts = ['']
    const holes = []
    for (i++; i < src.length && src[i] !== c; i++) {
      if (src[i] === '\\') { parts[parts.length - 1] += src[i] + src[i + 1]; i++; continue }
      if (c === '`' && src[i] === '$' && src[i + 1] === '{') {
        let depth = 1
        let j = i + 2
        for (; j < src.length && depth; j++) { if (src[j] === '{') depth++; else if (src[j] === '}') depth-- }
        holes.push(src.slice(i, j))
        parts.push('')
        i = j - 1
        continue
      }
      parts[parts.length - 1] += src[i]
    }
    out.push({ start, end: i + 1, quote: c, parts, holes })
  }
  return out
}
const COOK = { n: '\n', t: '\t', r: '\r', b: '\b', f: '\f', v: '\v', 0: '\0' }
export const cook = (raw) => raw.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|\n|[\s\S])/g, (m, e) => {
  if (e[0] === 'u' && e[1] === '{') return String.fromCodePoint(parseInt(e.slice(2, -1), 16))
  if (e[0] === 'u' || e[0] === 'x') return String.fromCharCode(parseInt(e.slice(1), 16))
  if (e === '\n') return ''
  return COOK[e] ?? e
})
export const raw = (text, quote) => text.replace(/\\/g, '\\\\')
  .replace(quote === '`' ? /`|\$\{/g : new RegExp(quote, 'g'), (m) => `\\${m}`)
  .replace(quote === '`' ? /(?!)/g : /\n/g, '\\n')

// Rewrite one source file literal by literal. A template's `${…}` holes become a sentinel while the
// text is linked, so a span never runs across one and the section rule still sees the whole string.
function glossSource(src, locale) {
  let out = ''
  let at = 0
  let changed = 0
  for (const lit of literals(src)) {
    const cooked = lit.parts.map(cook)
    const joined = cooked.join('\u0000')
    if (!joined.includes('**')) continue
    const [next] = glossString(joined, locale)
    if (next === joined) continue
    const pieces = next.split('\u0000')
    if (pieces.length !== cooked.length) continue
    let body = raw(pieces[0], lit.quote)
    lit.holes.forEach((h, k) => { body += h + raw(pieces[k + 1], lit.quote) })
    out += src.slice(at, lit.start) + lit.quote + body + lit.quote
    at = lit.end
    changed++
  }
  return [out + src.slice(at), changed]
}

async function processFile(rel, locale, write) {
  const file = path.join(DATA, rel)
  if (!fs.existsSync(file)) return { linked: 0, open: [], miss: 0 }
  const mod = await import(`${pathToFileURL(file).href}?${Date.now()}`)
  const pairs = new Map()
  let linked = 0
  const open = []
  const walk = (v) => {
    if (typeof v === 'string') {
      const [n, k, o] = glossString(v, locale)
      if (n !== v) pairs.set(v, n)
      linked += k
      open.push(...o)
    } else if (Array.isArray(v)) v.forEach(walk)
    else if (v && typeof v === 'object') Object.values(v).forEach(walk)
  }
  Object.values(mod).forEach(walk)
  let miss = 0
  if (write && pairs.size) {
    const src = fs.readFileSync(file, 'utf8')
    const [next] = glossSource(src, locale)
    fs.writeFileSync(file, next)
    // Whatever the module still disagrees on after the rewrite was not a literal of this file.
    const after = await import(`${pathToFileURL(file).href}?after=${Date.now()}`)
    const left = []
    const check = (v) => { if (typeof v === 'string') { if (glossString(v, locale)[0] !== v) left.push(v) } else if (Array.isArray(v)) v.forEach(check); else if (v && typeof v === 'object') Object.values(v).forEach(check) }
    Object.values(after).forEach(check)
    miss = left.length
    if (process.env.GLOSS_DEBUG) for (const l of left) console.log(`  MISS ${rel}: ${JSON.stringify(l).slice(0, 160)}`)
  }
  return { linked, open, miss, changed: pairs.size }
}

export async function glossFaction(slug, { write = true } = {}) {
  await prime()
  const res = []
  for (const [rel, loc] of [[`factions/${slug}.js`, 'en'], [`datasheets/${slug}.js`, 'en'], [`factions/ru/${slug}.js`, 'ru'], [`datasheets/ru/${slug}.js`, 'ru']]) {
    res.push({ rel, ...(await processFile(rel, loc, write)) })
  }
  return res
}

export async function run(argv = process.argv.slice(2)) {
  const check = argv.includes('--check')
  const slugs = argv.filter((a) => !a.startsWith('--'))
  let pending = 0
  let missed = 0
  const openAll = new Map()
  for (const slug of slugs.length ? slugs : GLOSS_SLUGS) {
    for (const r of await glossFaction(slug, { write: !check })) {
      pending += check ? (r.changed || 0) : 0
      missed += r.miss || 0
      if (!check && r.changed) console.log(`  ${r.rel}: ${r.changed} string(s) linked${r.miss ? `, ${r.miss} NOT written (text not found)` : ''}`)
      const key = (t) => `${r.rel.includes('/ru/') ? 'ru' : 'en'} · ${t}`
      for (const t of r.open) openAll.set(key(t), (openAll.get(key(t)) || 0) + 1)
    }
  }
  if (check) {
    console.log(pending ? `gloss-bold-terms: ${pending} string(s) have bold terms that could carry a popover — run \`npm run gloss\`` : 'gloss-bold-terms: every bold term the glossary knows is linked.')
  }
  const top = [...openAll].sort((a, b) => b[1] - a[1]).slice(0, 25)
  console.log(`  bold spans left as plain bold (not a glossary term, most common first): ${top.map(([t, n]) => `${t} (${n})`).join(' | ')}`)
  if (missed) { console.error(`  ${missed} replacement(s) could not be written — check the file by hand`); return 1 }
  return check && pending ? 1 : 0
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) process.exit(await run())
