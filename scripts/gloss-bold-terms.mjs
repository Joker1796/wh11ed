// gloss-bold-terms.mjs — turn the bold game terms of a faction's rules into popovers.
//
//   node scripts/gloss-bold-terms.mjs [slug …]            # write (default: every faction)
//   node scripts/gloss-bold-terms.mjs --check [slug …]    # report what is still unlinked, write nothing
//
// A bold span whose text is a glossary term becomes `**[gloss:<id>:<text>]**` — the popover shows
// the English term and the definition in the reader's language (src/data/glossary.js). A bold core
// unit ability ("**Stealth**", "**Feel No Pain 5+**") becomes `[core:…]`, the form src/data/CLAUDE.md
// prescribes for it. Both locales, in the same run: EN matches through the glossary's own terms and
// every English label already written into a gloss token anywhere in the data; RU through RU_FORMS
// below, because Russian inflects ("броскам на попадание", "броски на попадание"…).
//
// Why a script and not the renderer: a token in the data is what every other consumer —
// search, the index generators, the text-drift checks — already knows how to read. Those checks
// strip gloss tokens before comparing (sync-faction-text's plainText, the emphasis corpus), so a
// glossed term is never a finding. The EN files are REGENERATED by gen-faction-rules /
// gen-datasheets on a codex bump; both call this afterwards, so the popovers survive the next one.
//
// Deliberately NOT linked: a span that is not a term of the rules (loadout headers, "Designer's
// Note", item names), a slash list whose parts don't all resolve, and states a single rule defines
// in the same sentence (a unit's "quarry", "mark", "slayer's oath" — the popover would repeat the
// line beside it).
