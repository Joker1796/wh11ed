#!/usr/bin/env node
// Match the roster data just generated to the previous generation by what each stored index means,
// and write the moves the app applies to saved lists (src/data/rosterIndexMoves.js). Runs after
// gen-roster-data in `npm run roster:data`; `--check` (in `npm run roster:data:check`) fails when the
// data changed without this having run — the gate that data 963 had no one to trip (2026-11-08).
//
//   scripts/lib/roster-meanings.json      the ledger: the last generation's meanings and its revision
//   scripts/lib/roster-item-aliases.json  item names GW renamed, old → new (normalized), when a codex
//                                         renames a weapon the list still holds
//   src/data/rosterIndexMoves.js          DATA_REV + per revision the moves to the next one
//
// Any change of meaning — a move, a removal, an addition — is a new revision: a list saved with a new
// option must read as "from a newer version" to a build that does not have it.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { meaningsOf, matchMeanings } from './lib/roster-meanings.mjs'
import { SM_CHAPTERS } from '../src/core/shared/smChapters.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DATA = path.join(ROOT, 'src/data/roster')
const LEDGER = path.join(ROOT, 'scripts/lib/roster-meanings.json')
const ALIASES = path.join(ROOT, 'scripts/lib/roster-item-aliases.json')
const OUT = path.join(ROOT, 'src/data/rosterIndexMoves.js')
const check = process.argv.includes('--check')

const load = async (file) => (await import(pathToFileURL(file).href + `?t=${Date.now()}`)).default
const readJson = (file, fallback) => (fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : fallback)

export async function currentMeanings(aliases = {}) {
  const names = (await load(path.join(DATA, 'items.js'))).items
  const files = fs.readdirSync(DATA).filter((f) => f.endsWith('.js') && !['items.js', 'index.js', 'core.js'].includes(f) && !f.includes('.test.'))
  const out = {}
  const shared = {}
  for (const f of files.sort()) {
    const data = await load(path.join(DATA, f))
    Object.assign(out, meaningsOf(data.slug, data, names, aliases))
    if (SM_CHAPTERS.has(data.slug)) shared[data.slug] = data.sharedUnitIds || []
  }
  return { meanings: out, shared }
}

// A Chapter's borrowed Codex units are stored by the bare id in a Chapter's list: file their moves
// under the Chapter as well (rosterIndexMoves.js moveKeyOf).
function fileForChapters(moves, shared) {
  for (const [chapter, ids] of Object.entries(shared)) {
    for (const id of ids) {
      const m = moves[`space-marines:${id}`]
      if (m && !moves[`${chapter}:${id}`]) moves[`${chapter}:${id}`] = m
    }
  }
  return moves
}

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)))

function writeOut(rev, history) {
  const body = `// Generated by gen-roster-moves.mjs — do not edit. Re-run \`npm run roster:data\`.
// The roster data's revision, and per revision how a saved list's wargear picks ("g.o") and size
// indices move to the next one — 0 / -1: gone. See src/core/roster/rosterIndexMoves.js.
export const DATA_REV = ${rev}
export default ${JSON.stringify(history)}
`
  fs.writeFileSync(OUT, body)
}

async function main() {
  const aliases = readJson(ALIASES, {})
  const ledger = readJson(LEDGER, null)
  const { meanings, shared } = await currentMeanings(aliases)
  if (!ledger) {
    if (check) { console.error('✗ roster moves: no ledger — run `node scripts/gen-roster-moves.mjs`'); process.exit(1) }
    fs.writeFileSync(LEDGER, JSON.stringify({ rev: 1, units: meanings }) + '\n')
    writeOut(1, {})
    console.log('✓ roster moves: ledger started at revision 1')
    return
  }
  const same = JSON.stringify(sorted(ledger.units)) === JSON.stringify(sorted(meanings))
  const moduleRev = fs.existsSync(OUT) ? Number(/DATA_REV = (\d+)/.exec(fs.readFileSync(OUT, 'utf8'))?.[1]) : NaN
  if (check) {
    if (!same || moduleRev !== ledger.rev) {
      const { moves, gone } = matchMeanings(ledger.units, meanings)
      console.error(`✗ roster moves: the roster data changed since revision ${ledger.rev} (${Object.keys(moves).length} units move, ${gone.length} indices gone) and no moves were written.`)
      console.error('  Run `npm run roster:data` (it ends with gen-roster-moves) and read the list of what is gone.')
      process.exit(1)
    }
    console.log(`✓ roster moves: revision ${ledger.rev}, every stored index accounted for`)
    return
  }
  if (same) { console.log(`✓ roster moves: no change, revision ${ledger.rev}`); return }
  const { moves, gone } = matchMeanings(ledger.units, meanings)
  const history = (await load(OUT).catch(() => ({}))) || {}
  const rev = ledger.rev + 1
  history[ledger.rev] = sorted(fileForChapters(moves, shared))
  writeOut(rev, history)
  fs.writeFileSync(LEDGER, JSON.stringify({ rev, units: meanings }) + '\n')
  console.log(`✓ roster moves: revision ${ledger.rev} → ${rev}, ${Object.keys(moves).length} units move`)
  if (gone.length) {
    console.log(`  ${gone.length} stored indices have no counterpart and will be dropped from saved lists — read them;`)
    console.log('  a weapon GW renamed belongs in scripts/lib/roster-item-aliases.json, then re-run:')
    for (const g of gone) console.log(`    ${g}`)
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main()
